/**
 * IPC-2581C (DPMX) Manufacturing Export Compiler.
 *
 * Emits an open, XML-based IPC-2581C document containing the complete printed board
 * assembly definition:
 *   - Stackup and layer definitions
 *   - Padstack geometries and packages
 *   - Placed components and BOM links
 *   - Logical nets and pin connectivity
 *   - Copper traces, vias, and board outline
 *
 * Reference: IPC-2581C (Generic Requirements for Printed Board Assembly Products
 * Manufacturing Description Data and Transfer Methodology).
 */

import type { PCBLayout, PadDefinition } from "./gerber.js";

// ── Public Types ──

export interface IPC2581CompileOptions {
  assemblyName?: string;
  revision?: string;
  units?: "MILLIMETER" | "INCH";
  enterprise?: string;
  designer?: string;
  ipcClass?: "CLASS_2" | "CLASS_3" | "CLASS_3A";
  surfaceFinish?: string;
  copperThicknessOz?: number;
  boardThicknessMm?: number;
  componentValues?: Record<string, string>;
  componentMPNs?: Record<string, string>;
}

// ── IPC-2581C XML Helper ──

function escapeXml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function padstackName(pad: PadDefinition): string {
  const shape = pad.shape.toUpperCase();
  const w = Math.round(pad.width * 1000);
  const h = Math.round(pad.height * 1000);
  const d = Math.round(pad.drill * 1000);
  return `PAD_${shape}_W${w}_H${h}_D${d}`;
}

// ── Compiler Implementation ──

/**
 * Compiles a PCBLayout and Netlist into a fully compliant IPC-2581C XML document.
 */
export function compileToIPC2581(layout: PCBLayout, options?: IPC2581CompileOptions): string {
  const assembly = options?.assemblyName ?? "PCB_ASSEMBLY";
  const rev = options?.revision ?? "1.0.0";
  const enterprise = options?.enterprise ?? "ModelScript";
  const designer = options?.designer ?? "ModelScript ECAD Engine";
  const units = options?.units ?? "MILLIMETER";
  const ipcClass = options?.ipcClass ?? "CLASS_2";
  const surfaceFinish = options?.surfaceFinish ?? "ENIG";
  const compValues = options?.componentValues ?? {};
  const compMPNs = options?.componentMPNs ?? {};

  const lines: string[] = [];
  lines.push('<?xml version="1.0" encoding="UTF-8"?>');
  lines.push(
    `<IPC-2581 xmlns="http://webstds.ipc.org/2581" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" version="C" mode="USER_DEF">`,
  );

  // 1. Content Header
  lines.push(`  <Content role="ASSEMBLY" function="MANUFACTURING">`);
  const uniqueLayers = new Set<string>();
  for (const t of layout.traces) uniqueLayers.add(t.layer);
  for (const p of layout.pads) uniqueLayers.add(p.layer);
  if (layout.outline) uniqueLayers.add("BoardOutline");
  uniqueLayers.add("TopSilkscreen");
  uniqueLayers.add("BottomSilkscreen");
  uniqueLayers.add("TopSolderMask");
  uniqueLayers.add("BottomSolderMask");

  for (const layer of uniqueLayers) {
    lines.push(`    <LayerRef name="${escapeXml(layer)}"/>`);
  }
  lines.push(`    <BomRef name="${escapeXml(assembly)}_BOM"/>`);
  lines.push(`    <StepRef name="STEP_PCB"/>`);
  lines.push(`  </Content>`);

  // 2. Logistic Header
  const dateStr = new Date().toISOString();
  lines.push(`  <LogisticHeader>`);
  lines.push(`    <Enterprise name="${escapeXml(enterprise)}"/>`);
  lines.push(`    <Person name="${escapeXml(designer)}"/>`);
  lines.push(`    <Date>${dateStr}</Date>`);
  lines.push(`    <Role>OEM</Role>`);
  lines.push(`    <Specification standard="IPC-2581" revision="C" class="${ipcClass}"/>`);
  lines.push(`    <ManufacturingCharacteristics finish="${escapeXml(surfaceFinish)}"/>`);
  lines.push(`  </LogisticHeader>`);

  // 3. History Record
  lines.push(`  <HistoryRecord>`);
  lines.push(`    <Revision>${escapeXml(rev)}</Revision>`);
  lines.push(`    <Remark>Automated export generated by ModelScript ECAD engine</Remark>`);
  lines.push(`  </HistoryRecord>`);

  // 4. Bill of Materials (<Bom>)
  lines.push(`  <Bom name="${escapeXml(assembly)}_BOM">`);
  lines.push(`    <BomHeader assembly="${escapeXml(assembly)}" revision="${escapeXml(rev)}"/>`);
  for (const comp of layout.netlist.components) {
    const val = compValues[comp.name] ?? "UNSPECIFIED";
    const mpn = compMPNs[comp.name] ?? `MPN-${comp.name}`;
    const pkg = comp.placement?.footprint ?? "SMD";
    lines.push(`    <BomItem refDes="${escapeXml(comp.name)}">`);
    lines.push(`      <Characteristics>`);
    lines.push(`        <Category name="Electrical" value="${escapeXml(val)}"/>`);
    lines.push(`        <Category name="Package" value="${escapeXml(pkg)}"/>`);
    lines.push(`        <Category name="MPN" value="${escapeXml(mpn)}"/>`);
    lines.push(`      </Characteristics>`);
    lines.push(`    </BomItem>`);
  }
  lines.push(`  </Bom>`);

  // 5. ECAD Model (<Ecad>)
  lines.push(`  <Ecad name="${escapeXml(assembly)}">`);
  lines.push(`    <CadHeader units="${units}">`);
  lines.push(`      <SpecVersion>IPC-2581C</SpecVersion>`);
  lines.push(`      <Units units="${units}"/>`);
  lines.push(`    </CadHeader>`);

  // 5.1 Layer Stackup
  lines.push(`    <LayerStack name="DEFAULT_STACKUP">`);
  lines.push(`      <LayerDef name="TopSilkscreen" type="SILKSCREEN" sequence="1" side="TOP"/>`);
  lines.push(`      <LayerDef name="TopSolderMask" type="SOLDERMASK" sequence="2" side="TOP"/>`);
  lines.push(`      <LayerDef name="TopCopper" type="CONDUCTOR" sequence="3" side="TOP" thickness="0.035"/>`);
  lines.push(`      <LayerDef name="CoreDielectric" type="DIELECTRIC" sequence="4" thickness="1.530" material="FR4"/>`);
  lines.push(`      <LayerDef name="BottomCopper" type="CONDUCTOR" sequence="5" side="BOTTOM" thickness="0.035"/>`);
  lines.push(`      <LayerDef name="BottomSolderMask" type="SOLDERMASK" sequence="6" side="BOTTOM"/>`);
  lines.push(`      <LayerDef name="BottomSilkscreen" type="SILKSCREEN" sequence="7" side="BOTTOM"/>`);
  lines.push(`    </LayerStack>`);

  // 5.2 Padstack Definitions (Unique pad shapes)
  const uniquePadstacks = new Map<string, PadDefinition>();
  for (const pad of layout.pads) {
    const key = padstackName(pad);
    if (!uniquePadstacks.has(key)) {
      uniquePadstacks.set(key, pad);
    }
  }

  lines.push(`    <PadstackGroup>`);
  for (const [name, p] of uniquePadstacks) {
    lines.push(`      <PadstackDef name="${escapeXml(name)}">`);
    lines.push(
      `        <Pad shape="${p.shape.toUpperCase()}" width="${p.width.toFixed(4)}" height="${p.height.toFixed(4)}"/>`,
    );
    if (p.drill > 0) {
      lines.push(`        <Hole diameter="${p.drill.toFixed(4)}" plated="YES"/>`);
    }
    lines.push(`      </PadstackDef>`);
  }
  // Standard via padstack
  lines.push(`      <PadstackDef name="VIA_DEFAULT">`);
  lines.push(`        <Pad shape="CIRCLE" width="0.8000" height="0.8000"/>`);
  lines.push(`        <Hole diameter="0.4000" plated="YES"/>`);
  lines.push(`      </PadstackDef>`);
  lines.push(`    </PadstackGroup>`);

  // 5.3 Packages (<Package>)
  lines.push(`    <PackageGroup>`);
  const uniquePackages = new Set<string>();
  for (const comp of layout.netlist.components) {
    const pkg = comp.placement?.footprint ?? "SMD_DEFAULT";
    if (uniquePackages.has(pkg)) continue;
    uniquePackages.add(pkg);

    lines.push(`      <Package name="${escapeXml(pkg)}">`);
    lines.push(`        <Outline>`);
    lines.push(`          <Rect width="2.000" height="1.200"/>`);
    lines.push(`        </Outline>`);
    for (let i = 0; i < comp.pins.length; i++) {
      const pinId = comp.pins[i]!;
      lines.push(`        <Pin pinNum="${escapeXml(pinId)}" padstackRef="VIA_DEFAULT"/>`);
    }
    lines.push(`      </Package>`);
  }
  lines.push(`    </PackageGroup>`);

  // 5.4 Step definition (Components, Netlist, Routing, Outline)
  lines.push(`    <Step name="STEP_PCB">`);

  // Components placement
  lines.push(`      <ComponentGroup>`);
  for (const comp of layout.netlist.components) {
    const pl = comp.placement;
    const x = pl ? pl.x.toFixed(4) : "0.0000";
    const y = pl ? pl.y.toFixed(4) : "0.0000";
    const rot = pl ? pl.angle.toFixed(2) : "0.00";
    const layer = pl?.layer ?? "TopCopper";
    const side = layer.toLowerCase().includes("bottom") ? "BOTTOM" : "TOP";
    const pkg = pl?.footprint ?? "SMD_DEFAULT";

    lines.push(
      `        <Component refDes="${escapeXml(comp.name)}" packageRef="${escapeXml(pkg)}" layer="${escapeXml(layer)}" side="${side}" x="${x}" y="${y}" rotation="${rot}">`,
    );
    for (const pin of comp.pins) {
      lines.push(`          <ComponentPin pin="${escapeXml(pin)}"/>`);
    }
    lines.push(`        </Component>`);
  }
  lines.push(`      </ComponentGroup>`);

  // Logical Netlist
  lines.push(`      <LogicalNetGroup>`);
  for (const net of layout.netlist.nets) {
    lines.push(`        <LogicalNet name="${escapeXml(net.id)}">`);
    for (const pin of net.pins) {
      lines.push(`          <PinRef componentRef="${escapeXml(pin.component)}" pin="${escapeXml(pin.localName)}"/>`);
    }
    lines.push(`        </LogicalNet>`);
  }
  lines.push(`      </LogicalNetGroup>`);

  // Routing Tracks (Traces)
  lines.push(`      <RoutingGroup>`);
  for (const trace of layout.traces) {
    lines.push(
      `        <Track layer="${escapeXml(trace.layer)}" net="${escapeXml(trace.net)}" width="${trace.width.toFixed(4)}" x1="${trace.start[0].toFixed(4)}" y1="${trace.start[1].toFixed(4)}" x2="${trace.end[0].toFixed(4)}" y2="${trace.end[1].toFixed(4)}"/>`,
    );
  }
  // Vias
  for (const via of layout.vias) {
    const d = via.drill.toFixed(4);
    const r = (via.drill + 2 * via.annularRing).toFixed(4);
    lines.push(
      `        <Via net="${escapeXml(via.net)}" x="${via.center[0].toFixed(4)}" y="${via.center[1].toFixed(4)}" drill="${d}" outerDiameter="${r}"/>`,
    );
  }
  lines.push(`      </RoutingGroup>`);

  // Board Outline Profile
  if (layout.outline && layout.outline.vertices.length >= 3) {
    lines.push(`      <BoardProfile>`);
    lines.push(`        <Polygon>`);
    for (const v of layout.outline.vertices) {
      lines.push(`          <Vertex x="${v[0].toFixed(4)}" y="${v[1].toFixed(4)}"/>`);
    }
    lines.push(`        </Polygon>`);
    lines.push(`      </BoardProfile>`);
  }

  lines.push(`    </Step>`);
  lines.push(`  </Ecad>`);
  lines.push(`</IPC-2581>`);

  return lines.join("\n");
}
