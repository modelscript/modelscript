/**
 * FMU Harness — C source generator.
 *
 * Generates a standalone C program that:
 *   1. Extracts an FMU (.fmu = ZIP) archive to a temp directory
 *   2. dlopen()s the shared library matching the current platform
 *   3. Reads JSON-RPC commands from stdin
 *   4. Calls FMI 2.0 C API functions (both Co-Simulation and Model Exchange)
 *   5. Writes JSON-RPC responses to stdout
 *
 * Supports arbitrary variable counts, dynamic heap buffers (no 100-VR or 256-element caps),
 * multi-type getters/setters (Real, Integer, Boolean, String), FMU state serialization,
 * and both Co-Simulation and Model Exchange stepping.
 */

