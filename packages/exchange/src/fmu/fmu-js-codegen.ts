import { type DAEBuilder, BinOp, EqKind, ExprKind, UnaryOp } from "@modelscript/runtime";

import type { FmuOptions, FmuResult } from "./fmi.js";
import { binaryOpToJs, escapeJsString, mapFunctionNameJs, sanitizeIdentifier } from "./transpiler-utils.js";

/**
 * Generate FMI 2.0 compatible Javascript source file from a DAE and FMU result.
 */
export function generateFmuJsSources(dae: DAEBuilder, fmuResult: FmuResult, options: FmuOptions): string {
  const id = options.modelIdentifier;
  const vars = fmuResult.scalarVariables;
  const nStates = fmuResult.modelStructure.derivatives.length;
  const nVars = vars.length;

  return generateModelJs(id, nVars, nStates, dae, fmuResult);
}

function exprToJs(dae: DAEBuilder, id: number): string {
  if (id < 0) return "0.0";
  switch (dae.getExprKind(id)) {
    case ExprKind.RealLiteral:
      return `${dae.getExprRealValue(id)}`;
    case ExprKind.IntLiteral:
      return `${dae.getExprData1(id)}`;
    case ExprKind.BoolLiteral:
      return dae.getExprData1(id) !== 0 ? "1" : "0";
    case ExprKind.StringLiteral:
      return `"${escapeJsString(dae.interner.resolve(dae.getExprData1(id)))}"`;
    case ExprKind.Name:
      return varToJs(dae.interner.resolve(dae.getExprData1(id)));
    case ExprKind.Unary: {
      const uop = dae.getExprData1(id) as UnaryOp;
      const op = uop === UnaryOp.Negate ? "-" : "!";
      return `(${op}${exprToJs(dae, dae.getExprLeft(id))})`;
    }
    case ExprKind.Negate:
      return `(-${exprToJs(dae, dae.getExprLeft(id))})`;
    case ExprKind.Binary: {
      const op = dae.getExprData1(id) as BinOp;
      const lhs = exprToJs(dae, dae.getExprLeft(id));
      const rhs = exprToJs(dae, dae.getExprRight(id));
      const opStr = binaryOpToJs(op);
      if (opStr === "pow") return `Math.pow(${lhs}, ${rhs})`;
      return `(${lhs} ${opStr} ${rhs})`;
    }
    case ExprKind.Call: {
      const fname = dae.interner.resolve(dae.getExprData1(id));
      const argCount = dae.getExprRight(id);
      if (fname === "initial") return "this.isInitPhase";
      if (fname === "terminal") return "0";
      if (fname === "assert" && argCount >= 2) {
        const cond = exprToJs(dae, dae.getExprLeft(id));
        const msgExpr = dae.getExprLeft(id + 1);
        const msg =
          dae.getExprKind(msgExpr) === ExprKind.StringLiteral
            ? dae.interner.resolve(dae.getExprData1(msgExpr)).replace(/\\/g, "\\\\").replace(/"/g, '\\"')
            : "Assertion failed";
        return `((${cond}) ? 0.0 : (console.error("${msg}"), this.terminate = true, 0.0))`;
      }
      const args: string[] = [];
      for (let i = 0; i < argCount; i++) {
        args.push(exprToJs(dae, dae.getExprLeft(id + i)));
      }
      const mappedName = mapFunctionNameJs(fname);
      return `${mappedName}(${args.join(", ")})`;
    }
    case ExprKind.Der: {
      const inner = dae.getExprLeft(id);
      if (inner >= 0 && dae.getExprKind(inner) === ExprKind.Name) {
        const innerName = dae.interner.resolve(dae.getExprData1(inner));
        return varToJs(`der(${innerName})`);
      }
      return "0.0";
    }
    case ExprKind.Pre: {
      const inner = dae.getExprLeft(id);
      return exprToJs(dae, inner);
    }
    case ExprKind.IfElse: {
      const cond = exprToJs(dae, dae.getExprData1(id));
      const then = exprToJs(dae, dae.getExprLeft(id));
      const els = exprToJs(dae, dae.getExprRight(id));
      return `(${cond} ? ${then} : ${els})`;
    }
    default:
      return "0.0";
  }
}

function varToJs(name: string): string {
  if (name === "time") return "this.time";
  return `this.vars[VR_${sanitizeIdentifier(name).toUpperCase()}]`;
}

function generateModelJs(_id: string, nVars: number, nStates: number, dae: DAEBuilder, result: FmuResult): string {
  const lines: string[] = [];
  lines.push("/* Auto-generated by ModelScript — Javascript FMI */");

  // Variable Constants
  for (const sv of result.scalarVariables) {
    const cName = sanitizeIdentifier(sv.name).toUpperCase();
    lines.push(`const VR_${cName} = ${sv.valueReference};`);
  }

  lines.push("");
  lines.push("class FmuModel {");
  lines.push("  constructor() {");
  lines.push(`    this.vars = new Float64Array(${nVars + 1});`);
  lines.push(`    this.states = new Float64Array(${nStates + 1});`);
  lines.push(`    this.derivatives = new Float64Array(${nStates + 1});`);
  lines.push(`    this.time = 0.0;`);
  lines.push(`    this.isInitPhase = 1;`);
  lines.push(`    this.terminate = false;`);

  // Initial parameters
  for (const sv of result.scalarVariables) {
    if (sv.start !== undefined) {
      lines.push(`    this.vars[${sv.valueReference}] = ${sv.start};`);
    }
  }

  lines.push("  }");
  lines.push("");

  lines.push("  getDerivatives() {");

  // Extract state variables and mapping
  const derVRs = result.modelStructure.derivatives;
  const stateVRs: number[] = [];
  const derVars = result.scalarVariables.filter((sv) => sv.name.startsWith("der("));

  for (const dv of derVars) {
    if (dv.derivative !== undefined) {
      stateVRs.push(dv.derivative);
    } else {
      const stateName = dv.name.replace(/^der\((.+)\)$/, "$1");
      const stateSv = result.scalarVariables.find((sv) => sv.name === stateName);
      if (stateSv) stateVRs.push(stateSv.valueReference);
    }
  }

  for (let i = 0; i < stateVRs.length; i++) {
    lines.push(`    this.states[${i}] = this.vars[${stateVRs[i]}];`);
  }

  for (let idx = 0; idx < dae.eqCount; idx++) {
    if (dae.getEqKind(idx) !== EqKind.Simple) continue;
    const lhs = dae.getEqLhs(idx);
    const rhs = dae.getEqRhs(idx);
    if (dae.getExprKind(lhs) === ExprKind.Name) {
      const name = dae.interner.resolve(dae.getExprData1(lhs));
      lines.push(`    ${varToJs(name)} = ${exprToJs(dae, rhs)};`);
    } else if (dae.getExprKind(lhs) === ExprKind.Der) {
      const inner = dae.getExprLeft(lhs);
      if (inner >= 0 && dae.getExprKind(inner) === ExprKind.Name) {
        const innerName = dae.interner.resolve(dae.getExprData1(inner));
        lines.push(`    ${varToJs(`der(${innerName})`)} = ${exprToJs(dae, rhs)};`);
      }
    }
  }

  for (let i = 0; i < derVRs.length; i++) {
    lines.push(`    this.derivatives[${i}] = this.vars[${derVRs[i]}];`);
  }

  lines.push("  }");
  lines.push("");
  lines.push("  doStep(currentCommunicationPoint, communicationStepSize) {");
  lines.push("    this.isInitPhase = 0;");
  lines.push("    const nSubSteps = Math.max(1, Math.min(64, Math.ceil(Math.abs(communicationStepSize) / 0.01)));");
  lines.push("    const h = communicationStepSize / nSubSteps;");
  if (stateVRs.length > 0) {
    lines.push(`    const stateVRs = [${stateVRs.join(", ")}];`);
    lines.push("    const n = stateVRs.length;");
    lines.push("    const y0 = new Float64Array(n);");
    lines.push("    const k1 = new Float64Array(n);");
    lines.push("    const k2 = new Float64Array(n);");
    lines.push("    const k3 = new Float64Array(n);");
    lines.push("    const k4 = new Float64Array(n);");
    lines.push("    for (let step = 0; step < nSubSteps; step++) {");
    lines.push("      const t0 = currentCommunicationPoint + step * h;");
    lines.push("      this.time = t0;");
    lines.push("      for (let i = 0; i < n; i++) y0[i] = this.vars[stateVRs[i]];");
    lines.push("      this.getDerivatives();");
    lines.push("      for (let i = 0; i < n; i++) {");
    lines.push("        k1[i] = this.derivatives[i];");
    lines.push("        this.vars[stateVRs[i]] = y0[i] + 0.5 * h * k1[i];");
    lines.push("      }");
    lines.push("      this.time = t0 + 0.5 * h;");
    lines.push("      this.getDerivatives();");
    lines.push("      for (let i = 0; i < n; i++) {");
    lines.push("        k2[i] = this.derivatives[i];");
    lines.push("        this.vars[stateVRs[i]] = y0[i] + 0.5 * h * k2[i];");
    lines.push("      }");
    lines.push("      this.getDerivatives();");
    lines.push("      for (let i = 0; i < n; i++) {");
    lines.push("        k3[i] = this.derivatives[i];");
    lines.push("        this.vars[stateVRs[i]] = y0[i] + h * k3[i];");
    lines.push("      }");
    lines.push("      this.time = t0 + h;");
    lines.push("      this.getDerivatives();");
    lines.push("      for (let i = 0; i < n; i++) {");
    lines.push("        k4[i] = this.derivatives[i];");
    lines.push("        this.vars[stateVRs[i]] = y0[i] + (h / 6.0) * (k1[i] + 2.0 * k2[i] + 2.0 * k3[i] + k4[i]);");
    lines.push("      }");
    lines.push("    }");
  }
  lines.push("    this.time = currentCommunicationPoint + communicationStepSize;");
  lines.push("    this.getDerivatives();");
  lines.push("  }");
  lines.push("}");

  return lines.join("\n");
}
