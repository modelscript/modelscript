/**
 * @modelscript/simulate/opf — Turnkey ExaGO Deck Exporter & Bridge.
 *
 * Generates exascale-ready simulation and optimization bundles for PNNL's ExaGO:
 * - MATPOWER (.m) network with complete quadratic generator cost polynomials (mpc.gencost)
 * - Native ExaGO contingency deck (.cont) for Security-Constrained ACOPF (scopflow)
 * - ExaGO INI runtime configuration (PETSc options, HiOp/Ipopt solver selection)
 * - Turnkey Slurm/MPI execution script (run_exago.sh)
 */

import { serializeMatpower } from "./grid-converters.js";
import type { GenericPowerCase } from "./types.js";

export interface ExagoContingencyItem {
  id: string;
  type: "branch" | "gen" | "bus";
  fromBus?: number | undefined;
  toBus?: number | undefined;
  ckt?: string | undefined;
  bus?: number | undefined;
  genId?: string | undefined;
}

export interface ExagoExportOptions {
  caseName?: string | undefined;
  app?: "scopflow" | "opflow" | undefined;
  optSolver?: "hiop" | "ipopt" | undefined;
  linearSolver?: "petsc" | "ma57" | "mumps" | undefined;
  mpiRanks?: number | undefined;
  tolerance?: number | undefined;
  maxIterations?: number | undefined;
  contingencies?: ExagoContingencyItem[] | undefined;
}

export interface ExagoDeckBundle {
  caseName: string;
  matpowerCase: string;
  contingenciesCont?: string | undefined;
  configFile: string;
  slurmScript: string;
}

/**
 * Serializes a set of contingencies into native ExaGO `.cont` whitespace-delimited format.
 */
export function serializeExagoContingencies(items: ExagoContingencyItem[]): string {
  const lines: string[] = ["# ExaGO Native Contingency Deck"];
  for (const item of items) {
    if (item.type === "branch" && item.fromBus !== undefined && item.toBus !== undefined) {
      const ckt = (item.ckt ?? "1").trim() || "1";
      lines.push(`BRANCH\t${item.fromBus}\t${item.toBus}\t${ckt}\t# ${item.id}`);
    } else if (item.type === "gen" && item.bus !== undefined) {
      const genId = (item.genId ?? "1").trim() || "1";
      lines.push(`GEN\t${item.bus}\t${genId}\t# ${item.id}`);
    } else if (item.type === "bus" && item.bus !== undefined) {
      lines.push(`BUS\t${item.bus}\t# ${item.id}`);
    }
  }
  return lines.join("\n") + "\n";
}

/**
 * Exports a `GenericPowerCase` into a complete, turnkey ExaGO execution bundle.
 */
export function exportExagoDeck(powerCase: GenericPowerCase, options: ExagoExportOptions = {}): ExagoDeckBundle {
  const caseName = options.caseName || "case_exago";
  const app = options.app || (options.contingencies && options.contingencies.length > 0 ? "scopflow" : "opflow");
  const optSolver = options.optSolver || "hiop";
  const linearSolver = options.linearSolver || "petsc";
  const mpiRanks = options.mpiRanks && options.mpiRanks > 0 ? options.mpiRanks : 16;
  const tol = options.tolerance ?? 1e-6;
  const maxIter = options.maxIterations ?? 100;

  // 1. Generate MATPOWER case with gencost
  const matpowerCase = serializeMatpower(powerCase, caseName);

  // 2. Generate ExaGO contingencies if present
  let contingenciesCont: string | undefined;
  if (options.contingencies && options.contingencies.length > 0) {
    contingenciesCont = serializeExagoContingencies(options.contingencies);
  }

  // 3. Generate exago.ini configuration deck
  const iniLines: string[] = [
    `# ExaGO Configuration File`,
    `# Generated by @modelscript/simulate`,
    `[exago]`,
    `netfile = ${caseName}.m`,
  ];
  if (contingenciesCont) {
    iniLines.push(`ctgcfile = contingencies.cont`);
  }
  iniLines.push(`app = ${app}`);
  iniLines.push(`opt_solver = ${optSolver}`);
  iniLines.push(`linear_solver = ${linearSolver}`);
  iniLines.push(`tolerance = ${tol}`);
  iniLines.push(`max_iterations = ${maxIter}`);
  const configFile = iniLines.join("\n") + "\n";

  // 4. Generate HPC Slurm / MPI execution script
  const scriptLines: string[] = [
    `#!/usr/bin/env bash`,
    `# ExaGO Exascale Grid Optimization Runner`,
    `# Generated by ModelScript & Ansatz`,
    ``,
    `set -euo pipefail`,
    ``,
    `MPI_RANKS=${mpiRanks}`,
    `NETFILE="${caseName}.m"`,
    `CTGCFILE="contingencies.cont"`,
    `SOLVER="${optSolver}"`,
    ``,
    `echo "=========================================================="`,
    `echo " Launching ExaGO on \${NETFILE} with \${MPI_RANKS} MPI ranks"`,
    `echo " Optimization Solver: \${SOLVER} | Application: ${app}"`,
    `echo "=========================================================="`,
    ``,
  ];

  if (contingenciesCont) {
    scriptLines.push(
      `mpiexec -n "\${MPI_RANKS}" ./${app} -netfile "\${NETFILE}" -ctgcfile "\${CTGCFILE}" -opt_solver "\${SOLVER}" "$@"`,
    );
  } else {
    scriptLines.push(`mpiexec -n "\${MPI_RANKS}" ./${app} -netfile "\${NETFILE}" -opt_solver "\${SOLVER}" "$@"`);
  }
  scriptLines.push(``);
  const slurmScript = scriptLines.join("\n");

  return {
    caseName,
    matpowerCase,
    contingenciesCont,
    configFile,
    slurmScript,
  };
}
