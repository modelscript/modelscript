import assert from "node:assert";
import test from "node:test";
import { computeSolderDots } from "../src/solder-dots.js";

test("Auto-routed Waypoint Solder Dot Junction Engine", async (t) => {
  await t.test("should detect T-junction on an orthogonal bend generated by auto-router", () => {
    // Edge 1 routes from (0, 0) through (50, 0) and (50, 100) to (100, 100)
    // Edge 2 starts from (50, 50) on Edge 1's intermediate vertical segment and goes to (100, 50)
    const edges = [
      {
        id: "e1_routed",
        points: [
          { x: 0, y: 0 },
          { x: 50, y: 0 },
          { x: 50, y: 100 },
          { x: 100, y: 100 },
        ],
        color: "#0000ff",
      },
      {
        id: "e2_branch",
        points: [
          { x: 50, y: 50 },
          { x: 100, y: 50 },
        ],
        color: "#0000ff",
      },
    ];

    const dots = computeSolderDots(edges);
    assert.strictEqual(dots.length, 1, "Should find 1 junction dot on the routed Manhattan segment");
    assert.strictEqual(dots[0].x, 50);
    assert.strictEqual(dots[0].y, 50);
  });

  await t.test("should not produce false solder dot when direct chord crosses unrelated wire", () => {
    // Direct chord between (0, 0) and (100, 100) would pass through (50, 50).
    // But routed wire goes (0, 0) -> (0, 100) -> (100, 100), avoiding (50, 50).
    // An independent vertical wire sits at x=50 from y=40 to y=60.
    const edges = [
      {
        id: "e1_routed",
        points: [
          { x: 0, y: 0 },
          { x: 0, y: 100 },
          { x: 100, y: 100 },
        ],
        color: "#0000ff",
      },
      {
        id: "e2_isolated",
        points: [
          { x: 50, y: 40 },
          { x: 50, y: 60 },
        ],
        color: "#0000ff",
      },
    ];

    const dots = computeSolderDots(edges);
    assert.strictEqual(dots.length, 0, "No false dot should be generated when routed waypoints do not touch");
  });
});
