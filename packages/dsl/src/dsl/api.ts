/**
 * Generated AssemblyScript & TypeScript artifacts for a `kind: "binary"` entry in `LanguageOptions.formats`.
 */
export interface GeneratedBinaryCodec {
  /** Key in `LanguageOptions.formats` (e.g. `"sav"`, `"out"`). */
  formatKey: string;
  /** Declarative codec name (`BinaryCodecDefinition.name`). */
  codecName: string;
  /** File extensions routed to this binary codec. */
  fileExtensions: readonly string[];
  /** Emitted AssemblyScript WASM codec source (undefined if the codec uses JS-only combinators). */
  assemblyScript?: string | undefined;
  /** Emitted TypeScript zero-copy WASM bindings source. */
  typeScriptBindings: string;
  /** Reason AssemblyScript emission was skipped, if any. */
  assemblyScriptError?: string | undefined;
}

/**
 * Options for configuring language parser build and source AST extraction.
 */
export interface BuildOptions {
  /** Source file path for Direct Source AST extraction */
  sourcePath?: string | undefined;
  /** Source file URL (e.g. `import.meta.url`) for Direct Source AST extraction */
  sourceUrl?: string | URL | undefined;
  /** Source code text for in-memory Direct Source AST extraction */
  sourceText?: string | undefined;
}

/**
 * Metadata about the generated grammar parser.
 */
export interface ParserResult {
  /** The name of the language. */
  name: string;
  /** The root start symbol of the grammar. */
  startSymbol: string;
  /** An array of all non-terminal symbols extracted from the grammar. */
  nonTerminals: string[];
  /** An array of all terminal symbols (tokens) extracted from the grammar. */
  terminals: string[];
  /** The total number of states in the generated GLR action table. */
  statesCount: number;
}

/**
 * The full build output generated by the ModelScript language compiler.
 */
export interface BuildResult {
  /** Metadata and statistics about the generated parser. */
  parserInfo: ParserResult;
  /** The generated AssemblyScript files (action/goto tables, automata, grammar) to be compiled to WASM. */
  assemblyScriptFiles: GeneratedFile[];
  /** The generated JavaScript wrapper code and TypeScript typings to interface with the WASM parser. */
  javascriptWrapper: {
    js: string;
    dts: string;
    syntaxNames?: string[] | undefined;
    fieldNames?: string[] | undefined;
    semanticLegend?: { tokenTypes: string[]; tokenModifiers: string[] } | undefined;
  };
  syntaxNames?: string[] | undefined;
  fieldNames?: string[] | undefined;
  table?: unknown;
  /** Any unresolved grammar conflicts (shift/reduce or reduce/reduce). */
  conflicts?: GrammarConflictDiagnostic[] | undefined;
  /** Static grammar validation diagnostics (undefined rules, unreachable rules, nullable repeats, etc.). */
  grammarDiagnostics?: GrammarDiagnostic[] | undefined;
  /** Static TS-to-AssemblyScript subset diagnostics for `queries`, `lints`, and `scanner`. */
  queryDiagnostics?: TranspileSubsetDiagnostic[] | undefined;
  /** Declared supertype-to-subtype mappings from `LanguageOptions.supertypes`. */
  supertypes?: Record<string, string[]> | undefined;
  /** Compiled Model Context Protocol (MCP) tool and resource manifest. */
  mcpManifest?: McpManifest | undefined;
  /** Generated AssemblyScript & TypeScript artifacts for `kind: "binary"` entries in `languageDef.formats`. */
  binaryCodecs?: GeneratedBinaryCodec[] | undefined;
}

/**
 * Compiles a DSL grammar definition into a set of AssemblyScript source files,
 * JavaScript wrappers, and LR automata tables ready for WASM compilation.
 *
 * @param languageDef The grammar definition created using the DSL functions
 * @returns The final build result containing code strings and parser metadata
 */
export function buildParser(languageDef: LanguageOptions, options?: BuildOptions): BuildResult {
  const symTarget = languageDef as unknown as Record<symbol, unknown>;
  if (options?.sourcePath) {
    symTarget[SOURCE_PATH_SYMBOL] = options.sourcePath;
  } else if (options?.sourceUrl) {
    symTarget[SOURCE_PATH_SYMBOL] = resolveSourceUrl(options.sourceUrl);
  }
  if (options?.sourceText) {
    symTarget[SOURCE_TEXT_SYMBOL] = options.sourceText;
  }

  const result = generateParser(languageDef);

  const parserInfo = {
    name: languageDef.name,
    startSymbol: result.grammar.startSymbol,
    nonTerminals: Array.from(result.grammar.nonTerminals),
    terminals: Array.from(result.grammar.terminals),
    statesCount: result.table.actionTable.size,
  };

  const assemblyScriptFiles = generateParserTables(
    languageDef,
    result.grammar,
    result.table,
    languageDef.recovery?.sync || [],
  );

  const javascriptWrapper = generateJavaScriptWrapper(languageDef, result.grammar);

  const textMateContent = generateTextMate(languageDef);
  assemblyScriptFiles.push({ filename: "tmLanguage.json", content: textMateContent.tm });
  assemblyScriptFiles.push({ filename: "monarch.json", content: textMateContent.monarch });

  let mcpManifest: McpManifest | undefined;
  if (languageDef.mcp) {
    mcpManifest = compileMcpConfig(languageDef.mcp, languageDef.name).manifest;
  }

  let binaryCodecs: GeneratedBinaryCodec[] | undefined;
  if (languageDef.formats) {
    const emitted: GeneratedBinaryCodec[] = [];
    for (const [formatKey, fmtDef] of Object.entries(languageDef.formats)) {
      if (fmtDef.kind !== "binary" || !fmtDef.codec) continue;
      const typeScriptBindings = emitTypeScriptCodecBindings(fmtDef.codec);
      let assemblyScript: string | undefined;
      let assemblyScriptError: string | undefined;
      try {
        assemblyScript = emitAssemblyScriptCodec(fmtDef.codec);
      } catch (err) {
        assemblyScriptError = err instanceof Error ? err.message : String(err);
      }
      emitted.push({
        formatKey,
        codecName: fmtDef.codec.name,
        fileExtensions: fmtDef.fileExtensions,
        assemblyScript,
        typeScriptBindings,
        assemblyScriptError,
      });
    }
    if (emitted.length > 0) {
      binaryCodecs = emitted;
    }
  }

  return {
    parserInfo,
    assemblyScriptFiles,
    javascriptWrapper,
    syntaxNames: javascriptWrapper.syntaxNames,
    fieldNames: javascriptWrapper.fieldNames,
    table: result.table,
    conflicts: result.table.diagnostics || [],
    grammarDiagnostics: result.grammar.diagnostics,
    queryDiagnostics: validateLanguageQueries(languageDef),
    supertypes: result.grammar.supertypes.size > 0 ? Object.fromEntries(result.grammar.supertypes) : undefined,
    mcpManifest,
    binaryCodecs,
  };
}
