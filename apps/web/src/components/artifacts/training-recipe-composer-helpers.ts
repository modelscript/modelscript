export type TrainingRunBackend = "webgpu" | "local" | "cloud";

export interface TrainingStudioUrlParams {
  isTrainingStudio: boolean;
  forkRecipe: string | null;
  recipe: string | null;
  runBackend: TrainingRunBackend | null;
  artifactId: string | null;
}

export interface TrainingRecipeComposerInput {
  kind: Extract<MlPackageKind, "training-recipe" | "memory-shard"> | MlPackageKind;
  title?: string | undefined;
  packageName: string;
  version: string;
  authorHandle?: string | undefined;
  summary?: string | undefined;
  baseModel: string;
  parameterScale: SmallLlmRecipeTarget["parameterScale"];
  mode: SmallLlmRecipeTarget["mode"];
  loraRank?: number | undefined;
  mStart: number;
  mMax: number;
  mCap: number;
  expansionTau?: number | undefined;
  pruneEps?: number | undefined;
  collinearCosineThreshold?: number | undefined;
  girardReduceEvery?: number | undefined;
  retrievalTau?: number | undefined;
  embedderId: string;
  embedderHash?: string | undefined;
  embedderDimension?: number | undefined;
  quantization?: MemoryShardContract["quantization"] | undefined;
  datasetDependencies?: Record<string, string> | undefined;
  memoryPins?: MemoryShardPin[] | undefined;
  rewardWeights?: RecipeRewardWeights | undefined;
  aiGovernance?: AiGovernancePolicy | undefined;
  evalMetrics?: RecipeEvalMetrics | undefined;
  beforeAfterSamples?: RecipeBeforeAfterSample[] | undefined;
  failureBounties?: RecipeFailureBounty[] | undefined;
  lineage?: RecipeLineageInfo | undefined;
}

export interface TrainingRecipeArtifactPayload {
  view_type: "training-recipe" | "memory-shard";
  title: string;
  view_config: Record<string, unknown>;
}

function nonEmptyParam(value: string | null): string | null {
  if (!value) return null;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
}

function normalizeRunBackend(value: string | null): TrainingRunBackend | null {
  const normalized = nonEmptyParam(value)?.toLowerCase();
  if (normalized === "webgpu" || normalized === "local" || normalized === "cloud") {
    return normalized;
  }
  return null;
}

/**
 * Parses Training Studio deep-link query parameters generated by `TrainingRecipeArtifactCard`
 * (e.g. `?mode=training-studio&forkRecipe=...&recipe=...&run=webgpu&artifact=...`).
 */
export function parseTrainingStudioUrlParams(search: string): TrainingStudioUrlParams {
  const params = new URLSearchParams(search);
  const mode = nonEmptyParam(params.get("mode"))?.toLowerCase();
  const forkRecipe = nonEmptyParam(params.get("forkRecipe"));
  const recipe = nonEmptyParam(params.get("recipe"));
  const runBackend = normalizeRunBackend(params.get("run"));
  const artifactId = nonEmptyParam(params.get("artifact"));

  return {
    isTrainingStudio: mode === "training-studio",
    forkRecipe,
    recipe,
    runBackend,
    artifactId,
  };
}

function formatPct(value: number | undefined): string {
  return value !== undefined && Number.isFinite(value) ? `${Math.round(value * 100)}%` : "—";
}

function formatDynamicM(dm: DynamicMConfig | undefined): string {
  if (!dm) return "—";
  return `mStart=${dm.mStart} → mMax=${dm.mMax} (cap ${dm.mCap}, τ_exp=${dm.expansionTau}, τ_ret=${dm.retrievalTau})`;
}

/**
 * Auto-generates a ready-to-publish Distill.pub/Kaggle-style Markdown lab report
 * for a `training-recipe` or `memory-shard` post.
 */
export function buildRecipeBlogMarkdownDraft(
  recipe: NormalizedTrainingRecipeCard,
  parentRecipe?: NormalizedTrainingRecipeCard,
  postUrl?: string,
): string {
  const lines: string[] = [];

  lines.push(`# ${recipe.title}`);
  lines.push("");
  if (recipe.summary) {
    lines.push(recipe.summary);
    lines.push("");
  }
  lines.push(`> **Package:** \`${recipe.packageName}@${recipe.version}\` · **Kind:** \`${recipe.kind}\``);
  lines.push("");

  // Summary specification & formal eval table
  const baseModelLabel = recipe.targetModel
    ? `${recipe.targetModel.baseModel} · ${recipe.targetModel.parameterScale} (${recipe.targetModel.mode})`
    : "—";
  const embedderLabel = recipe.memoryContract?.embedderId
    ? `${recipe.memoryContract.embedderId} (${recipe.memoryContract.dimension}d, ${recipe.memoryContract.quantization})`
    : "—";
  const simRmseLabel =
    recipe.evalMetrics.simRmse !== undefined && Number.isFinite(recipe.evalMetrics.simRmse)
      ? String(recipe.evalMetrics.simRmse)
      : "—";

  lines.push("## Recipe Summary");
  lines.push("");
  lines.push("| Parameter | Value |");
  lines.push("| --- | --- |");
  lines.push(`| Base Model | ${baseModelLabel} |`);
  lines.push(`| Dynamic-m Schedule | ${formatDynamicM(recipe.dynamicM)} |`);
  lines.push(`| Embedder | ${embedderLabel} |`);
  lines.push(`| Gate 1–4 Pass Rate | ${formatPct(recipe.evalMetrics.gate1To4PassRate)} |`);
  lines.push(`| Pass@1 | ${formatPct(recipe.evalMetrics.passAt1)} |`);
  lines.push(`| Sim RMSE | ${simRmseLabel} |`);
  lines.push("");

  // Pinned datasets & memory shards
  lines.push("## Pinned Datasets & Memory Shards");
  lines.push("");
  const datasetEntries = Object.entries(recipe.datasetDependencies);
  if (datasetEntries.length === 0 && recipe.memoryPins.length === 0) {
    lines.push("- _No external dataset dependencies or federated memory shards pinned._");
  } else {
    for (const [pkg, range] of datasetEntries) {
      lines.push(`- **Dataset:** \`${pkg}@${range}\``);
    }
    for (const pin of recipe.memoryPins) {
      const signerSuffix = pin.signerPubkey ? `, signer \`${pin.signerPubkey}\`` : "";
      lines.push(
        `- **Memory Shard:** \`${pin.packageName}@${pin.version}\` (origin \`${pin.originNode}\`${signerSuffix})`,
      );
    }
  }
  lines.push("");

  // Semantic diff against parent recipe (when forked)
  if (parentRecipe) {
    const diffEntries = computeRecipeSemanticDiff(parentRecipe, recipe);
    lines.push(`## Semantic Diff vs. \`${parentRecipe.packageName}@${parentRecipe.version}\``);
    lines.push("");
    if (diffEntries.length === 0) {
      lines.push("_No semantic parameter changes detected relative to the parent recipe._");
    } else {
      lines.push("| Field | Change | Before | After | Delta |");
      lines.push("| --- | --- | --- | --- | --- |");
      for (const entry of diffEntries) {
        lines.push(
          `| \`${entry.field}\` | ${entry.kind} | ${entry.before ?? "—"} | ${entry.after ?? "—"} | ${entry.deltaLabel ?? "—"} |`,
        );
      }
    }
    lines.push("");
  }

  // Remaining failure bounties
  if (recipe.failureBounties.length > 0) {
    lines.push("## Help Fix Remaining Failure Cases");
    lines.push("");
    for (const bounty of recipe.failureBounties) {
      const bountyTag = bounty.bountyCredits !== undefined ? ` · **Bounty:** ${bounty.bountyCredits} credits` : "";
      const targetUrl =
        bounty.url ?? (bounty.challengeId !== undefined ? `/annotate/${bounty.challengeId}` : undefined);
      const linkSuffix = targetUrl ? ` — [Fix in Annotator](${targetUrl})` : "";
      lines.push(
        `- **${bounty.title}** (\`${bounty.dialect}\`, Δ_t = ${bounty.deltaT.toFixed(2)}${bountyTag})${linkSuffix}`,
      );
    }
    lines.push("");
  }

  // Ready-to-cite BibTeX block
  lines.push("## Citation");
  lines.push("");
  lines.push("```bibtex");
  lines.push(generateRecipeBibtex(recipe, postUrl));
  lines.push("```");

  return lines.join("\n");
}

/**
 * Builds the `{ view_type, title, view_config }` artifact payload expected by
 * `TrainingRecipeArtifactCard` and `POST /api/v1/posts`.
 */
export function buildTrainingRecipeArtifactPayload(
  formInput: TrainingRecipeComposerInput,
): TrainingRecipeArtifactPayload {
  const packageName = formInput.packageName.trim() || "@ansatz/untitled-recipe";
  const version = formInput.version.trim() || "0.1.0";
  const title = formInput.title?.trim() || `${packageName}@${version}`;
  const viewType: "training-recipe" | "memory-shard" =
    formInput.kind === "memory-shard" ? "memory-shard" : "training-recipe";

  const targetModel: SmallLlmRecipeTarget = {
    baseModel: formInput.baseModel.trim() || "ansatz-core-1.5b",
    parameterScale: formInput.parameterScale.trim() || "1.5B",
    mode: formInput.mode,
    ...(formInput.loraRank !== undefined ? { loraRank: formInput.loraRank } : {}),
  };

  const dynamicM: DynamicMConfig = {
    mStart: formInput.mStart,
    mMax: formInput.mMax,
    mCap: formInput.mCap,
    expansionTau: formInput.expansionTau ?? 0.05,
    pruneEps: formInput.pruneEps ?? 1e-4,
    collinearCosineThreshold: formInput.collinearCosineThreshold ?? 0.98,
    girardReduceEvery: formInput.girardReduceEvery ?? 4,
    retrievalTau: formInput.retrievalTau ?? 0.35,
  };

  const memoryContract: MemoryShardContract | undefined = formInput.embedderId.trim()
    ? {
        embedderId: formInput.embedderId.trim(),
        embedderHash: formInput.embedderHash?.trim() || "sha256:pending",
        dimension: formInput.embedderDimension ?? 1024,
        quantization: formInput.quantization ?? "int8-diskann",
        sourcePackages: [],
      }
    : undefined;

  const dependencies: Record<string, string> = {};
  if (formInput.datasetDependencies) {
    for (const [k, v] of Object.entries(formInput.datasetDependencies)) {
      const key = k.trim();
      const val = v.trim();
      if (key && val) dependencies[key] = val;
    }
  }

  const memoryPins: MemoryShardPin[] = (formInput.memoryPins ?? [])
    .filter((pin) => pin.packageName.trim().length > 0)
    .map((pin) => ({
      originNode: pin.originNode.trim() || "ansatz.social",
      packageName: pin.packageName.trim(),
      version: pin.version.trim() || "latest",
      signerPubkey: pin.signerPubkey.trim(),
      ...(pin.gitSha?.trim() ? { gitSha: pin.gitSha.trim() } : {}),
    }));

  const viewConfig: Record<string, unknown> = {
    packageName,
    version,
    title,
    ...(formInput.authorHandle?.trim() ? { authorHandle: formInput.authorHandle.trim() } : {}),
    ...(formInput.summary?.trim() ? { summary: formInput.summary.trim() } : {}),
    dependencies,
    ml: {
      kind: formInput.kind,
      targetModel,
      dynamicM,
      ...(formInput.rewardWeights ? { rewardWeights: formInput.rewardWeights } : {}),
      ...(formInput.aiGovernance ? { aiGovernance: formInput.aiGovernance } : {}),
      ...(memoryContract ? { memoryContract } : {}),
      memoryPins,
    },
    ...(formInput.evalMetrics ? { evalMetrics: formInput.evalMetrics } : {}),
    ...(formInput.beforeAfterSamples?.length ? { beforeAfterSamples: formInput.beforeAfterSamples } : {}),
    ...(formInput.failureBounties?.length ? { failureBounties: formInput.failureBounties } : {}),
    ...(formInput.lineage ? { lineage: formInput.lineage } : {}),
  };

  return {
    view_type: viewType,
    title,
    view_config: viewConfig,
  };
}
