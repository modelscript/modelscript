<!--
  Renders empirical maturity, conformance, and performance benchmark results for a language
  from data/benchmarks.generated.json (generated by `npm run bench:languages:record`).
  Never hand-edit benchmark tables; re-run the benchmark suite instead.
-->
<script setup lang="ts">
import { computed } from "vue";
import benchmarkData from "../data/benchmarks.generated.json";

interface PillarSummary {
  domainKind: string;
  hasParser: boolean;
  hasParserTests: boolean;
  hasLinter: boolean;
  hasLinterTests: boolean;
  testedErrorCodesCount: number;
  hasBenchmark: boolean;
  hasToleranceCheck: boolean;
  hasDomainLowering: boolean;
  hasDomainLoweringTests: boolean;
  usesRuntimeArena: boolean;
  hasLsp: boolean;
  hasLspTests: boolean;
  testFileCount: number;
  testCaseCount: number;
  auditedTier: string;
  currentDeclaredTier: string;
  gaps: string[];
}

interface StageTiming {
  status: "supported" | "n/a";
  medianMs: number;
  p95Ms: number;
  throughputMbPerSec?: number;
  iterations: number;
}

interface BenchmarkCase {
  id: string;
  name: string;
  scale: string;
  referenceTool: string;
  metricKind: string;
  threshold: number;
  measuredError: number | null;
  passed: boolean;
  durationMs: number;
  details?: string;
}

interface LangBenchmark {
  slug: string;
  name: string;
  pkgName: string;
  tier: string;
  reproduceCommand: string;
  catalogIds: string[];
  scorecard: PillarSummary;
  stages: {
    parse: { status: string; parserKind: string; cstNodeCount: number; errorRecoveryVerified: boolean };
    lint: { status: string; declaredRuleCount: number; testedRuleCount: number };
    lower: { status: string; targetIr: string; zeroAllocArena: boolean };
    solve: {
      status: string;
      casesRun: number;
      casesPassed: number;
      referenceTool: string;
      metricKind: string;
      tolerance: number;
      measuredWorstError: number | null;
    };
    projection: { status: string; targets: string[]; roundtripVerified: boolean };
  };
  timings: {
    parse: StageTiming;
    lint: StageTiming;
    lower: StageTiming;
    solve: StageTiming;
  };
  cases: BenchmarkCase[];
  summary: {
    totalCases: number;
    passedCases: number;
    passRate: number;
  };
}

interface CatalogMeta {
  id: string;
  name: string;
  version: string;
  license: string;
  referenceTool: string;
  metricTarget: string;
  threshold: number;
  description: string;
}

const props = defineProps<{ lang: string }>();

const payload = benchmarkData as {
  provenance: {
    gitSha: string;
    recordedAt: string;
    os: string;
    arch: string;
    cpuModel: string;
    cpuCores: number;
    nodeVersion: string;
    flattenerBackend: string;
  };
  catalogById: Record<string, CatalogMeta>;
  languages: LangBenchmark[];
};

const entry = computed(() => payload.languages.find((l) => l.slug === props.lang));

const catalogSuites = computed(() => {
  if (!entry.value) return [];
  return entry.value.catalogIds.map((id) => payload.catalogById[id]).filter((c): c is CatalogMeta => Boolean(c));
});

const pillars = computed(() => {
  const s = entry.value?.scorecard;
  if (!s) return [];
  return [
    { label: "Parser & Grammar", ok: s.hasParser && s.hasParserTests, detail: entry.value?.stages.parse.parserKind ?? "wasm-glr" },
    {
      label: "Diagnostics & Lint",
      ok: s.hasLinter && s.hasLinterTests,
      detail: `${entry.value?.stages.lint.testedRuleCount ?? 0} tested / ${entry.value?.stages.lint.declaredRuleCount ?? 0} rules`,
    },
    {
      label: "Domain Lowering",
      ok: s.hasDomainLowering && s.hasDomainLoweringTests,
      detail: entry.value?.stages.lower.targetIr ?? "n/a",
    },
    {
      label: "Zero-Alloc Arena",
      ok: s.usesRuntimeArena,
      detail: s.usesRuntimeArena ? "SoA Linear Memory" : "Standard",
    },
    {
      label: "Reference Parity",
      ok: s.hasBenchmark && (s.domainKind !== "simulation" || s.hasToleranceCheck),
      detail: `${entry.value?.summary.passedCases ?? 0}/${entry.value?.summary.totalCases ?? 0} cases`,
    },
    { label: "LSP & Tooling", ok: s.hasLsp && s.hasLspTests, detail: `${s.testFileCount} test suites (${s.testCaseCount} cases)` },
  ];
});

function formatError(val: number | null | undefined): string {
  if (val === null || val === undefined) return "—";
  if (val === 0) return "0";
  return val < 0.001 ? val.toExponential(2) : val.toFixed(4);
}

function formatDate(iso: string): string {
  return iso.split("T")[0] ?? iso;
}
</script>

<template>
  <div v-if="entry" class="lb-root">
    <div class="lb-summary-bar">
      <div class="lb-stat">
        <span class="lb-stat-label">Audited Tier</span>
        <span class="lb-stat-val lb-tier" :data-tier="entry.scorecard.auditedTier">{{ entry.scorecard.auditedTier }}</span>
      </div>
      <div class="lb-stat">
        <span class="lb-stat-label">Pass Rate</span>
        <span class="lb-stat-val">{{ entry.summary.passRate }}% ({{ entry.summary.passedCases }}/{{ entry.summary.totalCases }})</span>
      </div>
      <div class="lb-stat">
        <span class="lb-stat-label">Test Coverage</span>
        <span class="lb-stat-val">{{ entry.scorecard.testFileCount }} files · {{ entry.scorecard.testCaseCount }} cases</span>
      </div>
      <div class="lb-stat">
        <span class="lb-stat-label">Parse Latency</span>
        <span class="lb-stat-val">
          <template v-if="entry.timings.parse.status === 'supported'">
            {{ entry.timings.parse.medianMs.toFixed(2) }} ms (p95: {{ entry.timings.parse.p95Ms.toFixed(2) }} ms)
          </template>
          <template v-else>N/A</template>
        </span>
      </div>
    </div>

    <div class="lb-pillars">
      <div v-for="p in pillars" :key="p.label" class="lb-pillar" :data-ok="p.ok">
        <span class="lb-pillar-dot" />
        <div class="lb-pillar-text">
          <span class="lb-pillar-name">{{ p.label }}</span>
          <span class="lb-pillar-detail">{{ p.detail }}</span>
        </div>
      </div>
    </div>

    <div v-if="catalogSuites.length" class="lb-catalog">
      <div class="lb-subhead">Registered Industry Conformance Suites</div>
      <div v-for="c in catalogSuites" :key="c.id" class="lb-catalog-card">
        <div class="lb-catalog-title">
          <strong>{{ c.name }}</strong>
          <span class="lb-chip">v{{ c.version }}</span>
          <span class="lb-chip">{{ c.license }}</span>
          <span class="lb-chip">{{ c.referenceTool }}</span>
        </div>
        <p class="lb-catalog-desc">{{ c.description }} (Target: <code>{{ c.metricTarget }}</code> ≤ <code>{{ c.threshold }}</code>)</p>
      </div>
    </div>

    <div class="lb-table-wrap">
      <table>
        <thead>
          <tr>
            <th>Benchmark Case</th>
            <th>Scale</th>
            <th>Reference Oracle</th>
            <th>Metric / Threshold</th>
            <th>Measured</th>
            <th>Time</th>
            <th>Status</th>
          </tr>
        </thead>
        <tbody>
          <tr v-for="c in entry.cases" :key="c.id">
            <td>
              <strong>{{ c.name }}</strong>
              <div v-if="c.details" class="lb-case-details">{{ c.details }}</div>
            </td>
            <td>
              <span class="lb-chip">{{ c.scale }}</span>
            </td>
            <td>{{ c.referenceTool }}</td>
            <td>
              <code>{{ c.metricKind }}</code> ≤ <code>{{ c.threshold }}</code>
            </td>
            <td>
              <code>{{ formatError(c.measuredError) }}</code>
            </td>
            <td>{{ c.durationMs.toFixed(2) }} ms</td>
            <td>
              <span class="lb-status" :data-pass="c.passed">{{ c.passed ? "PASS" : "FAIL" }}</span>
            </td>
          </tr>
        </tbody>
      </table>
    </div>

    <div class="lb-provenance">
      <span>
        Reproduce: <code>{{ entry.reproduceCommand }}</code>
      </span>
      <span>
        Baseline: <code>{{ payload.provenance.gitSha }}</code> · {{ formatDate(payload.provenance.recordedAt) }} ·
        {{ payload.provenance.os }} ({{ payload.provenance.arch }}, {{ payload.provenance.cpuCores }} cores, Node {{ payload.provenance.nodeVersion }})
      </span>
    </div>
  </div>
</template>

