import { cleanroomSchemasToLibraryPayloads } from "@modelscript/runtime";
import fs from "node:fs";
import path from "node:path";
import { buildCleanroomStdLib } from "../../../scripts/build/build-cleanroom-stdlib.js";
import { buildFitsCleanroomSchemas } from "../src/catalog/fits-std-schemas.ts";

const fitsDir = new URL("..", import.meta.url).pathname;
const stdLibDir = path.join(fitsDir, "assets", "fits-std-lib");
const stdLibSrc = path.join(stdLibDir, "src");
fs.mkdirSync(stdLibSrc, { recursive: true });

// 1. Materialize symbols.json and diagrams.json (with cleanroom SVG block icons) from declarative schemas
const schemas = buildFitsCleanroomSchemas();
const { symbols, diagrams } = cleanroomSchemasToLibraryPayloads(schemas);
fs.writeFileSync(path.join(stdLibSrc, "symbols.json"), JSON.stringify(symbols, null, 2) + "\n", "utf-8");
fs.writeFileSync(path.join(stdLibSrc, "diagrams.json"), JSON.stringify(diagrams, null, 2) + "\n", "utf-8");

// 2. Build modelscript.yaml + AssemblyScript runtime.wasm + zero-I/O TS bundle
buildCleanroomStdLib({
  langName: "fits",
  packageName: "@modelscript/fits-std-lib",
  description: `Cleanroom NASA/IAU FITS 4.0 mandatory & WCS astrometry standard library (${schemas.length} schemas, cleanroom SVG block icons, AssemblyScript WASM runtime)`,
  stdLibDir,
  entryFile: "src/models.ts",
  outTsPath: path.join(fitsDir, "src", "catalog", "fits-std-lib-data.ts"),
  constPrefix: "FITS_STD_LIB",
  wasmGetterName: "getFitsStdLibWasmBytes",
});
