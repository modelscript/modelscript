import { solveApdlModal, solveApdlStatic } from "../solver/fea-solver.js";
import { expandApdlMacros } from "../solver/macro-expander.js";
import type { ApdlModel } from "../types.js";

function fmtNastranReal(val: number): string {
  if (val === 0) return "0.0";
  const abs = Math.abs(val);
  if (abs >= 1e-3 && abs < 1e5) return val.toFixed(4).replace(/\.?0+$/, (m) => (m.startsWith(".") ? ".0" : ""));
  return val.toExponential(4);
}

const DOF_TO_NASTRAN: Record<string, string> = {
  UX: "1",
  UY: "2",
  UZ: "3",
  ROTX: "4",
  ROTY: "5",
  ROTZ: "6",
  ALL: "123456",
};

/**
 * Projects an ANSYS APDL model to NASTRAN Bulk Data Format (`.bdf`).
 */
export function apdlToNastranBdf(sourceOrModel: string | ApdlModel): string {
  const model = typeof sourceOrModel === "string" ? expandApdlMacros(sourceOrModel) : sourceOrModel;
  const lines: string[] = [];

  const solCode = model.analysisType === "MODAL" ? "SOL 103" : "SOL 101";
  lines.push(`$ Generated by @modelscript/apdl — ${model.title}`);
  lines.push(solCode);
  lines.push("CEND");
  lines.push(`TITLE = ${model.title}`);
  if (model.constraints.length > 0) lines.push("SPC = 1");
  if (model.forces.length > 0) lines.push("LOAD = 1");
  if (model.analysisType === "MODAL") lines.push("METHOD = 1");
  lines.push("DISPLACEMENT(PRINT) = ALL");
  lines.push("BEGIN BULK");

  if (model.analysisType === "MODAL") {
    lines.push(`EIGRL,1,,,${model.numModes}`);
  }

  // GRID cards
  for (const node of Array.from(model.nodes.values()).sort((a, b) => a.id - b.id)) {
    lines.push(`GRID,${node.id},,${fmtNastranReal(node.x)},${fmtNastranReal(node.y)},${fmtNastranReal(node.z)}`);
  }

  // MAT1 cards
  for (const mat of Array.from(model.materials.values()).sort((a, b) => a.id - b.id)) {
    const E = mat.EX ?? 2.1e11;
    const nu = mat.PRXY ?? 0.3;
    const rho = mat.DENS ?? 7850.0;
    const G = mat.GXY ?? E / (2 * (1 + nu));
    lines.push(`MAT1,${mat.id},${fmtNastranReal(E)},${fmtNastranReal(G)},${fmtNastranReal(nu)},${fmtNastranReal(rho)}`);
  }

  // Property cards (PBEAM / PROD)
  const emittedProps = new Set<string>();
  for (const elem of Array.from(model.elements.values()).sort((a, b) => a.id - b.id)) {
    const etName = (model.elementTypes.get(elem.typeId)?.name ?? "BEAM188").toUpperCase();
    const sec = model.sections.get(elem.secId);
    const real = model.realConstants.get(elem.realId);
    const pid = elem.secId || elem.realId || 1;

    if (etName.startsWith("LINK") || etName === "TRUSS") {
      const key = `PROD_${pid}`;
      if (!emittedProps.has(key)) {
        emittedProps.add(key);
        const A = sec?.area ?? real?.values[0] ?? 1e-4;
        lines.push(`PROD,${pid},${elem.matId},${fmtNastranReal(A)}`);
      }
      if (elem.nodes.length >= 2) {
        lines.push(`CROD,${elem.id},${pid},${elem.nodes[0]},${elem.nodes[1]}`);
      }
    } else {
      const key = `PBEAM_${pid}`;
      if (!emittedProps.has(key)) {
        emittedProps.add(key);
        const A = sec?.area ?? real?.values[0] ?? 1e-3;
        const I1 = sec?.Izz ?? real?.values[1] ?? 1e-6;
        const I2 = sec?.Iyy ?? I1;
        const J = sec?.J ?? I1 + I2;
        lines.push(
          `PBEAM,${pid},${elem.matId},${fmtNastranReal(A)},${fmtNastranReal(I1)},${fmtNastranReal(I2)},0.0,${fmtNastranReal(J)}`,
        );
      }
      if (elem.nodes.length >= 2) {
        lines.push(`CBEAM,${elem.id},${pid},${elem.nodes[0]},${elem.nodes[1]},0.0,1.0,0.0`);
      }
    }
  }

  // SPC1 cards
  for (const bc of model.constraints) {
    const comp = DOF_TO_NASTRAN[bc.dof.toUpperCase()] ?? "123456";
    if (bc.value === 0) {
      lines.push(`SPC1,1,${comp},${bc.node}`);
    } else {
      lines.push(`SPC,1,${bc.node},${comp},${fmtNastranReal(bc.value)}`);
    }
  }

  // FORCE / MOMENT cards
  for (const f of model.forces) {
    const dof = f.dof.toUpperCase();
    const isMoment = dof.startsWith("M");
    const card = isMoment ? "MOMENT" : "FORCE";
    const nx = dof.endsWith("X") ? "1.0" : "0.0";
    const ny = dof.endsWith("Y") ? "1.0" : "0.0";
    const nz = dof.endsWith("Z") ? "1.0" : "0.0";
    lines.push(`${card},1,${f.node},0,${fmtNastranReal(f.value)},${nx},${ny},${nz}`);
  }

  lines.push("ENDDATA");
  return lines.join("\n") + "\n";
}

/**
 * Projects an ANSYS APDL structural model to a clean Modelica model.
 */
export function apdlToModelica(sourceOrModel: string | ApdlModel, modelName?: string): string {
  const model = typeof sourceOrModel === "string" ? expandApdlMacros(sourceOrModel) : sourceOrModel;
  const safeName = (modelName ?? model.title ?? "ApdlStructure").replace(/[^a-zA-Z0-9_]/g, "_").replace(/^(\d)/, "_$1");

  const lines: string[] = [];
  lines.push(`model ${safeName} "${model.title}"`);

  // Material parameters
  for (const [matId, mat] of model.materials.entries()) {
    if (mat.EX !== undefined) lines.push(`  parameter Real E_${matId} = ${mat.EX} "Young's modulus (Pa)";`);
    if (mat.PRXY !== undefined) lines.push(`  parameter Real nu_${matId} = ${mat.PRXY} "Poisson's ratio";`);
    if (mat.DENS !== undefined) lines.push(`  parameter Real rho_${matId} = ${mat.DENS} "Density (kg/m^3)";`);
  }

  // User APDL parameters
  for (const [k, v] of model.parameters.entries()) {
    lines.push(`  parameter Real p_${k} = ${v};`);
  }

  // Modal coordinates from FEA modal solver (fallback to default)
  let omegas: number[] = [];
  if (model.elements.size > 0 && model.constraints.length > 0) {
    try {
      const modalSol = solveApdlModal(model, Math.min(model.numModes || 3, 4));
      omegas = modalSol.modes.map((m) => m.omega);
    } catch {
      omegas = [];
    }
  }
  if (omegas.length === 0) omegas = [62.8318530718];

  let staticMaxDisp = 0;
  if (model.elements.size > 0 && model.constraints.length > 0) {
    try {
      staticMaxDisp = solveApdlStatic(model).maxDisplacement;
    } catch {
      staticMaxDisp = 0;
    }
  }

  lines.push(`  parameter Real zeta = 0.02 "Modal damping ratio";`);
  lines.push(`  output Real maxStaticDisplacement(start=${staticMaxDisp});`);
  for (let i = 0; i < omegas.length; i++) {
    lines.push(`  parameter Real omega_${i + 1} = ${omegas[i]!.toFixed(6)} "Mode ${i + 1} angular frequency (rad/s)";`);
    lines.push(`  Real q_${i + 1}(start=0.0) "Modal displacement ${i + 1}";`);
    lines.push(`  Real v_${i + 1}(start=0.0) "Modal velocity ${i + 1}";`);
    lines.push(`  input Real Q_${i + 1}(start=0.0) "Generalized modal force ${i + 1}";`);
  }

  lines.push("equation");
  lines.push(`  maxStaticDisplacement = ${staticMaxDisp};`);
  for (let i = 0; i < omegas.length; i++) {
    lines.push(`  der(q_${i + 1}) = v_${i + 1};`);
    lines.push(
      `  der(v_${i + 1}) = Q_${i + 1} - 2.0 * zeta * omega_${i + 1} * v_${i + 1} - omega_${i + 1}^2 * q_${i + 1};`,
    );
  }

  lines.push(`end ${safeName};`);
  return lines.join("\n") + "\n";
}
