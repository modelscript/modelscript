/**
 * @modelscript/dicom-rt — Cross-Language Projections to OpenSCAD (@modelscript/scad) and SysML v2.
 *
 * - `dicomRtToScad(doc)`: Projects RTSTRUCT 3D ROI contour slices into extruded OpenSCAD
 *   polygons/polyhedra and RTPLAN treatment beams into oriented 3D radiation beam cones.
 * - `dicomRtToSysML2(doc)`: Projects clinical target prescriptions, QUANTEC OAR dose limits,
 *   radiobiological metrics (BED, EQD2, CI, HI), and linac delivery parameters to SysML v2
 *   `requirement def` and `verification def` blocks.
 */

import { evaluateDicomRtDosimetry } from "../dosimetry/index.js";
import type { DicomRtDocument, RoiInterpretedType, RtRoiStructure } from "../types.js";

const DEFAULT_ROI_COLORS: Record<RoiInterpretedType, [number, number, number]> = {
  PTV: [255, 40, 40],
  CTV: [255, 120, 40],
  GTV: [220, 0, 80],
  ORGAN: [40, 200, 100],
  EXTERNAL: [180, 180, 200],
  AVOIDANCE: [240, 200, 40],
  BOLUS: [100, 160, 255],
  MARKER: [255, 255, 255],
};

/**
 * Projects a DICOM-RT document (RTSTRUCT contours + RTPLAN beams) into 3D OpenSCAD CSG code.
 */
export function dicomRtToScad(doc: DicomRtDocument): string {
  const lines: string[] = [];
  lines.push(`// Generated by @modelscript/dicom-rt`);
  lines.push(`// Plan: ${doc.planLabel} (${doc.planId}) | Patient: ${doc.patientId}`);
  lines.push(`// FrameOfReferenceUID: ${doc.frameOfReferenceUid}`);
  lines.push(`$fn = 36;`);
  lines.push("");

  // 1. Emit ROI contour slice modules
  const roiModuleNames: string[] = [];
  for (const roi of doc.structures) {
    const modName = `roi_${roi.roiNumber}_${sanitizeIdent(roi.name)}`;
    roiModuleNames.push(modName);
    const rgb = roi.color ?? DEFAULT_ROI_COLORS[roi.interpretedType];
    const r = (rgb[0] / 255).toFixed(3);
    const g = (rgb[1] / 255).toFixed(3);
    const b = (rgb[2] / 255).toFixed(3);
    const alpha = roi.interpretedType === "EXTERNAL" ? "0.20" : "0.65";

    const sliceThickness = estimateSliceThicknessMm(roi);

    lines.push(`module ${modName}() {`);
    lines.push(`  // ROI #${roi.roiNumber}: ${roi.name} (${roi.interpretedType}, ${roi.volumeCc} cc)`);
    lines.push(`  color([${r}, ${g}, ${b}, ${alpha}]) {`);

    if (roi.contours.length === 0) {
      const radiusMm = Math.max(5.0, Math.cbrt((3 * Math.max(1, roi.volumeCc) * 1000) / (4 * Math.PI)));
      lines.push(`    sphere(r = ${radiusMm.toFixed(2)});`);
    } else {
      lines.push(`    union() {`);
      for (const slice of roi.contours) {
        if (slice.geometricType === "POINT" || slice.points.length < 3) {
          const pt = slice.points[0] ?? [0, 0, slice.z];
          lines.push(`      translate([${pt[0]}, ${pt[1]}, ${pt[2]}]) sphere(r = 2.0);`);
        } else {
          const pts2d = slice.points.map((p) => `[${p[0]}, ${p[1]}]`).join(", ");
          lines.push(
            `      translate([0, 0, ${slice.z}]) linear_extrude(height = ${sliceThickness.toFixed(2)}) polygon(points = [${pts2d}]);`,
          );
        }
      }
      lines.push(`    }`);
    }

    lines.push(`  }`);
    lines.push(`}`);
    lines.push("");
  }

  // 2. Emit Beam cone modules
  const beamModuleNames: string[] = [];
  for (const beam of doc.beams) {
    const modName = `beam_${beam.beamNumber}_${sanitizeIdent(beam.name)}`;
    beamModuleNames.push(modName);
    const cp0 = beam.controlPoints[0];
    const gantry = cp0?.gantryAngleDeg ?? 0;
    const coll = cp0?.collimatorAngleDeg ?? 0;
    const couch = cp0?.couchAngleDeg ?? 0;
    const jawX = cp0 ? Math.max(10, cp0.jawX_mm[1] - cp0.jawX_mm[0]) : 100;
    const jawY = cp0 ? Math.max(10, cp0.jawY_mm[1] - cp0.jawY_mm[0]) : 100;

    lines.push(`module ${modName}() {`);
    lines.push(
      `  // Beam #${beam.beamNumber}: ${beam.name} (${beam.modality}, ${beam.energyMeV} MeV, ${beam.metersetMu} MU)`,
    );
    lines.push(`  color([1.000, 0.850, 0.100, 0.25]) {`);
    lines.push(`    rotate([0, ${gantry}, ${couch}]) rotate([0, 0, ${coll}]) {`);
    lines.push(
      `      translate([0, 0, 500]) linear_extrude(height = 500, scale = 0.05) square([${jawX.toFixed(1)}, ${jawY.toFixed(1)}], center = true);`,
    );
    lines.push(`    }`);
    lines.push(`  }`);
    lines.push(`}`);
    lines.push("");
  }

  // 3. Instantiate scene
  lines.push(`// Scene Assembly`);
  for (const m of roiModuleNames) {
    lines.push(`${m}();`);
  }
  for (const m of beamModuleNames) {
    lines.push(`${m}();`);
  }

  return lines.join("\n");
}

/**
 * Projects a DICOM-RT treatment plan, clinical QUANTEC dose constraints, and
 * radiobiological evaluation into SysML v2 requirement and verification definitions.
 */
export function dicomRtToSysML2(doc: DicomRtDocument): string {
  const pkgName = sanitizeIdent(doc.planLabel || doc.planId || "DicomRtPlanPackage");
  const dosimetry = evaluateDicomRtDosimetry(doc);
  const reportByRoi = new Map(dosimetry.roiReports.map((r) => [r.roiNumber, r]));

  const lines: string[] = [];
  lines.push(`package ${pkgName} {`);
  lines.push(
    `  doc /* Generated by @modelscript/dicom-rt for Plan ${doc.planLabel} (${doc.planId}), Patient ${doc.patientId} */`,
  );
  lines.push("");

  // 1. Anatomical ROI Structure part defs
  for (const roi of doc.structures) {
    const partName = sanitizeIdent(`ROI_${roi.name}`);
    const rep = reportByRoi.get(roi.roiNumber);
    lines.push(`  part def ${partName} {`);
    lines.push(`    attribute roiNumber = ${roi.roiNumber};`);
    lines.push(`    attribute interpretedType = "${roi.interpretedType}";`);
    lines.push(`    attribute volumeCc = ${roi.volumeCc};`);
    if (roi.maxDoseLimitGy !== undefined) {
      lines.push(`    attribute maxDoseLimitGy = ${roi.maxDoseLimitGy};`);
    }
    if (roi.meanDoseLimitGy !== undefined) {
      lines.push(`    attribute meanDoseLimitGy = ${roi.meanDoseLimitGy};`);
    }
    if (rep) {
      lines.push(`    attribute d95Gy = ${rep.d95Gy};`);
      lines.push(`    attribute meanDoseGy = ${rep.meanDoseGy};`);
      lines.push(`    attribute maxDoseGy = ${rep.maxDoseGy};`);
      lines.push(`    attribute bedGy = ${rep.bedGy};`);
      lines.push(`    attribute eqd2Gy = ${rep.eqd2Gy};`);
    }
    lines.push(`  }`);
    lines.push("");
  }

  // 2. Treatment Beam part defs
  for (const beam of doc.beams) {
    const beamPart = sanitizeIdent(`Beam_${beam.beamNumber}_${beam.name}`);
    lines.push(`  part def ${beamPart} {`);
    lines.push(`    attribute beamNumber = ${beam.beamNumber};`);
    lines.push(`    attribute modality = "${beam.modality}";`);
    lines.push(`    attribute treatmentDeliveryType = "${beam.treatmentDeliveryType}";`);
    lines.push(`    attribute energyMeV = ${beam.energyMeV};`);
    lines.push(`    attribute metersetMu = ${beam.metersetMu};`);
    lines.push(`    attribute doseRateMuPerMin = ${beam.doseRateMuPerMin};`);
    lines.push(`    attribute controlPointCount = ${beam.controlPoints.length};`);
    lines.push(`  }`);
    lines.push("");
  }

  // 3. Clinical Prescription & QUANTEC Dose Constraint requirement defs
  lines.push(`  requirement def PrescriptionDoseRequirement {`);
  lines.push(`    doc /* Clinical target prescription and radiobiological BED/EQD2 requirement */`);
  lines.push(`    attribute planId = "${doc.planId}";`);
  lines.push(`    attribute prescribedDoseGy = ${doc.prescribedDoseGy};`);
  lines.push(`    attribute fractions = ${doc.fractions};`);
  lines.push(`    attribute dosePerFractionGy = ${dosimetry.dosePerFractionGy};`);
  lines.push(`    attribute prescriptionBedGy = ${dosimetry.prescriptionBedGy};`);
  lines.push(`    attribute prescriptionEqd2Gy = ${dosimetry.prescriptionEqd2Gy};`);
  lines.push(`    attribute homogeneityIndex = ${dosimetry.homogeneityIndex};`);
  lines.push(`    attribute conformityIndex = ${dosimetry.conformityIndex};`);
  lines.push(`  }`);
  lines.push("");

  const reqNames: { id: string; reqDef: string }[] = [{ id: "prescription", reqDef: "PrescriptionDoseRequirement" }];

  for (const roi of doc.structures) {
    const reqDef = sanitizeIdent(`${roi.name}_DoseConstraintRequirement`);
    const rep = reportByRoi.get(roi.roiNumber);
    reqNames.push({ id: sanitizeIdent(roi.name), reqDef });

    lines.push(`  requirement def ${reqDef} {`);
    lines.push(`    doc /* QUANTEC / ICRU 83 clinical dose constraint for ${roi.name} (${roi.interpretedType}) */`);
    lines.push(`    attribute roiName = "${roi.name}";`);
    lines.push(`    attribute interpretedType = "${roi.interpretedType}";`);
    if (roi.interpretedType === "PTV") {
      lines.push(`    attribute minRequiredD95Gy = ${Math.round(0.95 * doc.prescribedDoseGy * 1000) / 1000};`);
    }
    if (roi.maxDoseLimitGy !== undefined) {
      lines.push(`    attribute maxDoseLimitGy = ${roi.maxDoseLimitGy};`);
    }
    if (roi.meanDoseLimitGy !== undefined) {
      lines.push(`    attribute meanDoseLimitGy = ${roi.meanDoseLimitGy};`);
    }
    if (rep) {
      lines.push(`    attribute withinConstraints = ${rep.withinConstraints};`);
    }
    lines.push(`  }`);
    lines.push("");
  }

  // 4. Verification definition
  lines.push(`  verification def RadiotherapyPlanVerification {`);
  lines.push(`    doc /* Automated AAPM TG-263 / QUANTEC Dosimetric Verification */`);
  lines.push(`    attribute totalMetersetMu = ${dosimetry.totalMetersetMu};`);
  lines.push(`    attribute totalDeliveryTimeSec = ${dosimetry.totalDeliveryTimeSec};`);
  for (const r of reqNames) {
    lines.push(`    verify requirement verify_${r.id} : ${r.reqDef};`);
  }
  lines.push(`  }`);
  lines.push(`}`);

  return lines.join("\n");
}

function estimateSliceThicknessMm(roi: RtRoiStructure): number {
  if (roi.contours.length >= 2) {
    const zs = roi.contours.map((c) => c.z).sort((a, b) => a - b);
    for (let i = 0; i < zs.length - 1; i++) {
      const dz = Math.abs((zs[i + 1] ?? 0) - (zs[i] ?? 0));
      if (dz > 0.1) return dz;
    }
  }
  return 3.0;
}

function sanitizeIdent(name: string): string {
  const cleaned = name.replace(/[^a-zA-Z0-9_]/g, "_");
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned || "DicomRtElement";
}
