/**
 * Projection from LLNL NEC-2 wire antenna decks to IEEE/EIA Touchstone 1.1 `.s1p`
 * one-port S-parameter files.
 */

import { solveNec2Deck } from "../solver/mom-solver.js";
import type { Nec2Deck, Nec2SolveResult } from "../types.js";

export interface Nec2TouchstoneOptions {
  /** S-parameter data format: "RI" (Real/Imag), "MA" (Mag/Angle), or "DB" (dB/Angle). Default: "RI" */
  format?: "RI" | "MA" | "DB" | undefined;
  /** Reference impedance Z0 in Ohms (default: 50) */
  z0?: number | undefined;
  /** Optional pre-computed solve result */
  solveResult?: Nec2SolveResult | undefined;
}

/**
 * Projects a NEC-2 antenna deck to a Touchstone 1.1 `.s1p` one-port S-parameter file.
 */
export function nec2ToTouchstone(deck: Nec2Deck, options: Nec2TouchstoneOptions = {}): string {
  const format = options.format ?? "RI";
  const z0 = options.z0 ?? 50.0;
  const result = options.solveResult ?? solveNec2Deck(deck, { z0, computeFarField: false });

  const lines: string[] = [
    `! Touchstone 1.1 S1P generated by @modelscript/nec2`,
    `! Title: ${deck.title}`,
    `! Segments: ${result.segmentCount}, GroundPlane: ${result.hasGroundPlane}`,
    `# MHZ S ${format} R ${z0}`,
  ];

  for (const pt of result.points) {
    const fStr = pt.frequencyMhz.toFixed(6);
    if (format === "RI") {
      lines.push(`${fStr} ${pt.reflectionCoeff.re.toFixed(6)} ${pt.reflectionCoeff.im.toFixed(6)}`);
    } else if (format === "MA") {
      lines.push(`${fStr} ${pt.s11Mag.toFixed(6)} ${pt.s11PhaseDeg.toFixed(4)}`);
    } else {
      const db = pt.s11Mag > 1e-12 ? 20.0 * Math.log10(pt.s11Mag) : -240.0;
      lines.push(`${fStr} ${db.toFixed(4)} ${pt.s11PhaseDeg.toFixed(4)}`);
    }
  }

  return lines.join("\n") + "\n";
}
