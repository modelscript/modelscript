/**
 * @modelscript/epanet — Projections to Modelica.Fluid Hydraulic Networks.
 *
 * Translates EPANET water distribution decks into Modelica.Fluid.Pipes,
 * Modelica.Fluid.Sources, and Modelica.Fluid.Fittings network models.
 */

import type { EpanetNetwork } from "../types.js";

export function epanetToModelica(net: EpanetNetwork): string {
  const modelName = (net.title ?? "EpanetNetwork").replace(/[^a-zA-Z0-9_]/g, "_");
  const lines: string[] = [];

  lines.push(`model ${modelName}`);
  lines.push(`  // Auto-generated by ModelScript @modelscript/epanet`);
  lines.push(`  import Modelica.Fluid.Pipes.StaticPipe;`);
  lines.push(`  import Modelica.Fluid.Sources.Boundary_pT;`);
  lines.push(`  import Modelica.Fluid.Sources.MassFlowSource_T;`);
  lines.push("");

  // 1. Reservoirs & Tanks (Sources)
  lines.push("  // Hydraulic Sources & Boundaries");
  for (const r of net.reservoirs) {
    const cleanId = r.id.replace(/[^a-zA-Z0-9_]/g, "_");
    // p = rho * g * H (rho=1000, g=9.81)
    const pressPa = 1000.0 * 9.81 * r.totalHead;
    lines.push(
      `  Boundary_pT res_${cleanId}(p = ${pressPa.toFixed(0)}, T = 293.15) "Reservoir ${r.id} (Head: ${r.totalHead}m)";`,
    );
  }
  for (const t of net.tanks) {
    const cleanId = t.id.replace(/[^a-zA-Z0-9_]/g, "_");
    const pressPa = 1000.0 * 9.81 * (t.elevation + t.initLevel);
    lines.push(
      `  Boundary_pT tank_${cleanId}(p = ${pressPa.toFixed(0)}, T = 293.15) "Tank ${t.id} (Head: ${(t.elevation + t.initLevel).toFixed(1)}m)";`,
    );
  }
  lines.push("");

  // 2. Junction Demands
  lines.push("  // Junction Consumer Demands");
  for (const j of net.junctions) {
    if (j.demand > 0) {
      const cleanId = j.id.replace(/[^a-zA-Z0-9_]/g, "_");
      // Flow in kg/s (1 L/s = 1 kg/s)
      lines.push(
        `  MassFlowSource_T sink_${cleanId}(m_flow = -${j.demand.toFixed(2)}, T = 293.15) "Junction ${j.id} Demand";`,
      );
    }
  }
  lines.push("");

  // 3. Pipes
  lines.push("  // Pipe Distribution Links");
  for (const p of net.pipes) {
    const cleanId = p.id.replace(/[^a-zA-Z0-9_]/g, "_");
    const D = p.diameter > 5.0 ? p.diameter / 1000.0 : p.diameter;
    lines.push(
      `  StaticPipe pipe_${cleanId}(length = ${p.length.toFixed(1)}, diameter = ${D.toFixed(3)}) "Pipe ${p.id} (${p.node1} -> ${p.node2})";`,
    );
  }
  lines.push("");

  // 4. Equations & Connections
  lines.push("equation");
  for (const p of net.pipes) {
    const cleanPipeId = p.id.replace(/[^a-zA-Z0-9_]/g, "_");
    const n1 = p.node1.toLowerCase();
    const n2 = p.node2.toLowerCase();

    // Check if node1 is reservoir/tank
    const isRes1 = net.reservoirs.some((r) => r.id.toLowerCase() === n1);
    const isTank1 = net.tanks.some((t) => t.id.toLowerCase() === n1);
    if (isRes1) {
      lines.push(`  connect(res_${p.node1.replace(/[^a-zA-Z0-9_]/g, "_")}.ports[1], pipe_${cleanPipeId}.port_a);`);
    } else if (isTank1) {
      lines.push(`  connect(tank_${p.node1.replace(/[^a-zA-Z0-9_]/g, "_")}.ports[1], pipe_${cleanPipeId}.port_a);`);
    }

    // Check if node2 is sink
    const isSink2 = net.junctions.some((j) => j.id.toLowerCase() === n2 && j.demand > 0);
    if (isSink2) {
      lines.push(`  connect(pipe_${cleanPipeId}.port_b, sink_${p.node2.replace(/[^a-zA-Z0-9_]/g, "_")}.ports[1]);`);
    }
  }

  lines.push(`end ${modelName};`);
  return lines.join("\n");
}
