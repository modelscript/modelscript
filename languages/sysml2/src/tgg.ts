/**
 * @fileoverview Triple Graph Grammar (TGG) rules for SysML v2 bidirectional translation.
 * Maps SysML v2 constructs to Modelica, OWL 2, and STEP CAD.
 */

import {
  tggComplement,
  tggDefaultVal,
  tggDer,
  tggEq,
  tggExprMap,
  tggForEach,
  tggFormatUri,
  tggPhysicalPort,
  tggRule,
  tggTypeMap,
} from "@modelscript/dsl";

