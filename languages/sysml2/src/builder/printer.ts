import { randomUUID } from "node:crypto";
import type { SysmlxDocument, SysmlxElement, SysmlxRelationship } from "../sysmlx-interchange.js";
import { OMG_SYSML2_CONTEXT } from "../sysmlx-interchange.js";
import type {
  ActionDefNode,
  AttributeUsageNode,
  CalcDefNode,
  ConnectionNode,
  ConstraintDefNode,
  ConstraintUsageNode,
  DocNode,
  ItemDefNode,
  ItemUsageNode,
  PackageNode,
  PartDefNode,
  PartUsageNode,
  PortDefNode,
  PortUsageNode,
  RequirementDefNode,
  RequirementUsageNode,
  StateDefNode,
  SysMLDefinitionNode,
  SysMLMemberNode,
  SysMLRootNode,
} from "./nodes.js";

export interface SysMLPrintOptions {
  /** Spaces per indentation level (default: 2) */
  indent?: number | undefined;
  /** Emit auto-generated header comment (default: true) */
  includeHeaderComment?: boolean | undefined;
  /** Header text if includeHeaderComment is true */
  headerComment?: string | undefined;
}

export class SysMLPrinter {
  public static print(node: SysMLRootNode | SysMLRootNode[], options: SysMLPrintOptions = {}): string {
    const indentStep = " ".repeat(options.indent ?? 2);
    const nodes = Array.isArray(node) ? node : [node];

    let output = "";
    if (options.includeHeaderComment ?? true) {
      const header = options.headerComment || "// Auto-generated by ModelScript SysML v2 Builder\n\n";
      output += header.endsWith("\n") ? header : `${header}\n`;
    }

    for (let i = 0; i < nodes.length; i++) {
      const n = nodes[i];
      if (!n) continue;
      output += this.printRootNode(n, 0, indentStep);
      if (i < nodes.length - 1) {
        output += "\n";
      }
    }

    return output.trimEnd() + "\n";
  }

  public static toSysmlx(root: SysMLRootNode | SysMLRootNode[]): SysmlxDocument {
    const nodes = Array.isArray(root) ? root : [root];
    const elements: SysmlxElement[] = [];
    const relationships: SysmlxRelationship[] = [];

    for (const n of nodes) {
      this.lowerNodeToSysmlx(n, null, elements, relationships);
    }

    return {
      "@context": OMG_SYSML2_CONTEXT,
      "@graph": [...elements, ...relationships],
      metadata: {
        generator: "ModelScript SysML v2 Builder",
        version: "1.0.0",
        created: new Date().toISOString(),
      },
    };
  }

  // =========================================================================
  // Text Unparser Implementation
  // =========================================================================

  private static printRootNode(node: SysMLRootNode, level: number, indentStep: string): string {
    if (node.kind === "package") {
      return this.printPackage(node, level, indentStep);
    }
    return this.printDefinition(node, level, indentStep);
  }

  private static printPackage(node: PackageNode, level: number, indentStep: string): string {
    const indent = indentStep.repeat(level);
    let res = "";

    if (node.doc && node.doc.length > 0) {
      for (const d of node.doc) {
        res += `${indent}doc /* ${d} */\n`;
      }
    }

    res += `${indent}package ${node.name} {\n`;

    // Imports
    for (const imp of node.imports) {
      const priv = (imp.isPrivate ?? true) ? "private " : "";
      const suffix = imp.isAll ? "::*" : "";
      res += `${indent}${indentStep}${priv}import ${imp.path}${suffix};\n`;
    }

    if (node.imports.length > 0 && node.members.length > 0) {
      res += "\n";
    }

    // Members
    for (let i = 0; i < node.members.length; i++) {
      const member = node.members[i];
      if (!member) continue;
      if (member.kind === "package") {
        res += this.printPackage(member, level + 1, indentStep);
      } else if (member.kind === "doc") {
        res += `${indent}${indentStep}doc /* ${(member as DocNode).text} */\n`;
      } else {
        res += this.printDefinition(member as SysMLDefinitionNode, level + 1, indentStep);
      }

      if (i < node.members.length - 1) {
        res += "\n";
      }
    }

    res += `${indent}}\n`;
    return res;
  }

  private static printDefinition(
    node:
      | PartDefNode
      | PortDefNode
      | ItemDefNode
      | RequirementDefNode
      | ConstraintDefNode
      | ActionDefNode
      | StateDefNode
      | CalcDefNode,
    level: number,
    indentStep: string,
  ): string {
    const indent = indentStep.repeat(level);
    let res = "";

    if (node.doc && node.doc.length > 0) {
      for (const d of node.doc) {
        res += `${indent}doc /* ${d} */\n`;
      }
    }

    const absPrefix = node.isAbstract ? "abstract " : "";
    const keyword = this.getDefKeyword(node.kind);
    const superClause = node.superTypes && node.superTypes.length > 0 ? ` :> ${node.superTypes.join(", ")}` : "";

    const hasMembers = node.members && node.members.length > 0;
    const hasReqContract =
      node.kind === "requirement_def" &&
      ((node.assume && node.assume.length > 0) || (node.guarantee && node.guarantee.length > 0) || node.text);
    const hasConstraintExpr = node.kind === "constraint_def" && node.expr;
    const hasCalcExpr = node.kind === "calc_def" && (node.calcExpr || node.returnType);

    if (!hasMembers && !hasReqContract && !hasConstraintExpr && !hasCalcExpr) {
      return `${indent}${absPrefix}${keyword} ${node.name}${superClause};\n`;
    }

    res += `${indent}${absPrefix}${keyword} ${node.name}${superClause} {\n`;

    // Requirement special fields
    if (node.kind === "requirement_def") {
      if (node.text) {
        res += `${indent}${indentStep}doc /* ${node.text} */\n`;
      }
      if (node.assume) {
        for (const a of node.assume) {
          res += `${indent}${indentStep}assume constraint { ${a} }\n`;
        }
      }
      if (node.guarantee) {
        for (const g of node.guarantee) {
          res += `${indent}${indentStep}require constraint { ${g} }\n`;
        }
      }
    }

    // Constraint expression
    if (node.kind === "constraint_def" && node.expr) {
      res += `${indent}${indentStep}${node.expr};\n`;
    }

    // Calc expression
    if (node.kind === "calc_def" && node.calcExpr) {
      const ret = node.returnType ? ` : ${node.returnType}` : "";
      res += `${indent}${indentStep}return ${node.calcExpr}${ret};\n`;
    }

    // Body members
    for (const m of node.members) {
      res += this.printMember(m, level + 1, indentStep);
    }

    res += `${indent}}\n`;
    return res;
  }

  private static printMember(node: SysMLMemberNode, level: number, indentStep: string): string {
    const indent = indentStep.repeat(level);

    switch (node.kind) {
      case "attribute_usage":
        return this.printAttributeUsage(node, indent);
      case "port_usage":
        return this.printPortUsage(node, indent);
      case "part_usage":
        return this.printPartUsage(node, level, indentStep);
      case "item_usage":
        return this.printItemUsage(node, level, indentStep);
      case "connection":
        return this.printConnection(node, indent);
      case "constraint_usage":
        return this.printConstraintUsage(node, indent);
      case "requirement_usage":
        return this.printRequirementUsage(node, indent);
      case "doc":
        return `${indent}doc /* ${node.text} */\n`;
      case "import": {
        const priv = (node.isPrivate ?? true) ? "private " : "";
        const suffix = node.isAll ? "::*" : "";
        return `${indent}${priv}import ${node.path}${suffix};\n`;
      }
      case "part_def":
      case "port_def":
      case "item_def":
      case "requirement_def":
      case "constraint_def":
      case "action_def":
      case "state_def":
      case "calc_def":
        return this.printDefinition(node, level, indentStep);
    }
  }

  private static printAttributeUsage(node: AttributeUsageNode, indent: string): string {
    let prefix = "";
    if (node.isConstant) prefix = "constant ";
    else if (node.isParameter) prefix = "attribute ";
    else prefix = "attribute ";

    const typeStr = node.type ? ` : ${node.type}` : "";
    let valStr = "";
    if (node.value !== undefined) {
      valStr = ` = ${typeof node.value === "string" && !node.value.startsWith('"') ? `"${node.value}"` : node.value}`;
    }
    const unitStr = node.unit ? ` [${node.unit}]` : "";

    return `${indent}${prefix}${node.name}${typeStr}${valStr}${unitStr};\n`;
  }

  private static printPortUsage(node: PortUsageNode, indent: string): string {
    const dir = node.direction ? `${node.direction} ` : "";
    const conj = node.isConjugated ? "~" : "";
    const typeStr = node.type ? ` : ${conj}${node.type}` : "";
    return `${indent}${dir}port ${node.name}${typeStr};\n`;
  }

  private static printPartUsage(node: PartUsageNode, level: number, indentStep: string): string {
    const indent = indentStep.repeat(level);
    const typeStr = node.type ? ` : ${node.type}` : "";
    const multStr = node.multiplicity ? `[${node.multiplicity}]` : "";

    if (!node.members || node.members.length === 0) {
      return `${indent}part ${node.name}${typeStr}${multStr};\n`;
    }

    let res = `${indent}part ${node.name}${typeStr}${multStr} {\n`;
    for (const m of node.members) {
      res += this.printMember(m, level + 1, indentStep);
    }
    res += `${indent}}\n`;
    return res;
  }

  private static printItemUsage(node: ItemUsageNode, level: number, indentStep: string): string {
    const indent = indentStep.repeat(level);
    const typeStr = node.type ? ` : ${node.type}` : "";

    if (!node.members || node.members.length === 0) {
      return `${indent}item ${node.name}${typeStr};\n`;
    }

    let res = `${indent}item ${node.name}${typeStr} {\n`;
    for (const m of node.members) {
      res += this.printMember(m, level + 1, indentStep);
    }
    res += `${indent}}\n`;
    return res;
  }

  private static printConnection(node: ConnectionNode, indent: string): string {
    const namePart = node.name ? `${node.name} ` : "";
    return `${indent}connect ${namePart}${node.fromPort} to ${node.toPort};\n`;
  }

  private static printConstraintUsage(node: ConstraintUsageNode, indent: string): string {
    const namePart = node.name ? `${node.name} ` : "";
    return `${indent}assert constraint ${namePart}{ ${node.expr} }\n`;
  }

  private static printRequirementUsage(node: RequirementUsageNode, indent: string): string {
    const typeStr = node.type ? ` : ${node.type}` : "";
    if (!node.text && (!node.assume || node.assume.length === 0) && (!node.guarantee || node.guarantee.length === 0)) {
      return `${indent}requirement ${node.name}${typeStr};\n`;
    }

    let res = `${indent}requirement ${node.name}${typeStr} {\n`;
    if (node.text) {
      res += `${indent}  doc /* ${node.text} */\n`;
    }
    if (node.assume) {
      for (const a of node.assume) {
        res += `${indent}  assume constraint { ${a} }\n`;
      }
    }
    if (node.guarantee) {
      for (const g of node.guarantee) {
        res += `${indent}  require constraint { ${g} }\n`;
      }
    }
    res += `${indent}}\n`;
    return res;
  }

  private static getDefKeyword(kind: string): string {
    switch (kind) {
      case "part_def":
        return "part def";
      case "port_def":
        return "port def";
      case "item_def":
        return "item def";
      case "requirement_def":
        return "requirement def";
      case "constraint_def":
        return "constraint def";
      case "action_def":
        return "action def";
      case "state_def":
        return "state def";
      case "calc_def":
        return "calc def";
      default:
        return "def";
    }
  }

  // =========================================================================
  // SysMLX (JSON-LD) Lowering
  // =========================================================================

  private static lowerNodeToSysmlx(
    node: SysMLRootNode | SysMLMemberNode,
    ownerId: string | null,
    elements: SysmlxElement[],
    relationships: SysmlxRelationship[],
  ): string {
    const elemId = node.id || `urn:uuid:${randomUUID()}`;
    const name = "name" in node ? (node as { name: string }).name : undefined;
    const type = this.getSysmlxMetaclass(node.kind);

    const elem: SysmlxElement = {
      "@id": elemId,
      "@type": type,
      name,
      owner: ownerId ? { "@id": ownerId } : null,
      ownedElement: [],
      attributes: node.doc && node.doc.length > 0 ? { documentation: node.doc } : undefined,
    };

    if ("superTypes" in node && node.superTypes && node.superTypes.length > 0) {
      elem.superclasses = node.superTypes;
    }

    if (node.kind === "attribute_usage") {
      elem.attributes = {
        type: node.type,
        value: node.value,
        unit: node.unit,
        isParameter: node.isParameter,
      };
    } else if (node.kind === "port_usage") {
      elem.attributes = {
        type: node.type,
        direction: node.direction,
        isConjugated: node.isConjugated,
      };
    } else if (node.kind === "connection") {
      // Connect relationship
      const relId = `urn:uuid:${randomUUID()}`;
      relationships.push({
        "@id": relId,
        "@type": "ConnectionUsage",
        relationshipType: "connection",
        source: [{ "@id": node.fromPort }],
        target: [{ "@id": node.toPort }],
      });
      return elemId;
    }

    elements.push(elem);

    // Recursively lower children
    const childMembers = "members" in node && Array.isArray(node.members) ? (node.members as SysMLMemberNode[]) : [];

    for (const child of childMembers) {
      const childId = this.lowerNodeToSysmlx(child, elemId, elements, relationships);
      if (elem.ownedElement) {
        elem.ownedElement.push({ "@id": childId });
      }
    }

    return elemId;
  }

  private static getSysmlxMetaclass(kind: string): string {
    switch (kind) {
      case "package":
        return "Package";
      case "part_def":
        return "PartDefinition";
      case "port_def":
        return "PortDefinition";
      case "item_def":
        return "ItemDefinition";
      case "requirement_def":
        return "RequirementDefinition";
      case "constraint_def":
        return "ConstraintDefinition";
      case "action_def":
        return "ActionDefinition";
      case "state_def":
        return "StateDefinition";
      case "calc_def":
        return "CalculationDefinition";
      case "part_usage":
        return "PartUsage";
      case "port_usage":
        return "PortUsage";
      case "item_usage":
        return "ItemUsage";
      case "attribute_usage":
        return "AttributeUsage";
      case "requirement_usage":
        return "RequirementUsage";
      case "constraint_usage":
        return "ConstraintUsage";
      default:
        return "Element";
    }
  }
}
