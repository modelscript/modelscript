/**
 * @modelscript/doe2 — Projection to Modelica 3.x Thermal Network.
 *
 * Translates DOE-2 spaces, composite walls, glazing, infiltration, and internal gains
 * into standard `Modelica.Thermal.HeatTransfer` components and `connect()` equations.
 */

import { buildSpaceThermalSummaries } from "../solver/doe2-thermal-solver.js";
import type { Doe2Document } from "../types.js";

function sanitizeIdent(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9_]/g, "_");
  return /^[0-9]/.test(cleaned) ? `M_${cleaned}` : cleaned;
}

/**
 * Projects a parsed `Doe2Document` to a Modelica 3.x thermal network model.
 */
export function doe2ToModelica(doc: Doe2Document): string {
  const modelName = sanitizeIdent(doc.title ?? "Doe2Building");
  const summaries = buildSpaceThermalSummaries(doc);
  const lines: string[] = [];

  lines.push(`model ${modelName}`);
  lines.push("  // Auto-generated by ModelScript @modelscript/doe2");
  lines.push("  import Modelica.Thermal.HeatTransfer.Components.*;");
  lines.push("  import Modelica.Thermal.HeatTransfer.Sources.*;");
  lines.push("");

  lines.push("  // Boundary Temperatures");
  lines.push('  FixedTemperature ambSource(T = 283.15) "Outdoor Ambient Air Temperature (10 deg C)";');
  lines.push('  FixedTemperature gndSource(T = 285.15) "Ground Temperature (12 deg C)";');
  lines.push("");

  lines.push("  // Thermal Zones & Envelope Conductors");
  const connects: string[] = [];

  for (const s of summaries) {
    const id = sanitizeIdent(s.spaceName);
    lines.push(
      `  HeatCapacitor zone_${id}(C = ${s.cZoneJPerK.toFixed(1)}, T(start = 293.15, fixed = true)) "DOE-2 Space ${s.spaceName}";`,
    );

    const gEnvAndInf = s.uaExteriorTotalWPerK + s.gInfiltrationWPerK;
    if (gEnvAndInf > 0) {
      lines.push(
        `  ThermalConductor cond_ext_${id}(G = ${gEnvAndInf.toFixed(4)}) "Envelope UA + infiltration for ${s.spaceName}";`,
      );
      connects.push(`  connect(ambSource.port, cond_ext_${id}.port_a);`);
      connects.push(`  connect(cond_ext_${id}.port_b, zone_${id}.port);`);
    }

    if (s.uaGroundWPerK > 0) {
      lines.push(
        `  ThermalConductor cond_gnd_${id}(G = ${s.uaGroundWPerK.toFixed(4)}) "Underground conductance for ${s.spaceName}";`,
      );
      connects.push(`  connect(gndSource.port, cond_gnd_${id}.port_a);`);
      connects.push(`  connect(cond_gnd_${id}.port_b, zone_${id}.port);`);
    }

    if (s.qInternalW > 0) {
      lines.push(
        `  FixedHeatFlow q_int_${id}(Q_flow = ${s.qInternalW.toFixed(1)}) "Internal gains for ${s.spaceName}";`,
      );
      connects.push(`  connect(q_int_${id}.port, zone_${id}.port);`);
    }
  }

  lines.push("");
  lines.push("equation");
  for (const c of connects) {
    lines.push(c);
  }
  lines.push(`end ${modelName};`);

  return lines.join("\n");
}
