/**
 * @modelscript/doe2 — Projection to EnergyPlus IDF.
 *
 * Translates DOE-2.1E / DOE-2.2 BDL materials, layers, constructions, glazing,
 * spaces, exterior/underground surfaces, windows, doors, infiltration, internal gains,
 * and zones into SI-unit EnergyPlus IDF objects.
 */

import {
  CP_IP_TO_SI,
  FT2_TO_M2,
  FT3_TO_M3,
  FT_TO_M,
  K_IP_TO_SI,
  RHO_IP_TO_SI,
  R_IP_TO_SI,
  U_IP_TO_SI,
  computeAllConstructionProps,
  fahrenheitToCelsius,
} from "../solver/doe2-thermal-solver.js";
import type { Doe2Document, Doe2Layers } from "../types.js";

/**
 * Projects a parsed `Doe2Document` to EnergyPlus IDF format (SI units).
 */
export function doe2ToEnergyPlusIdf(doc: Doe2Document): string {
  const isIp = doc.units === "IP";
  const lines: string[] = [];
  const bldgName = doc.title ?? "DOE2_Building";

  lines.push("!- Auto-generated by ModelScript @modelscript/doe2");
  lines.push("Version, 24.1;");
  lines.push("");

  // 1. Building
  lines.push("Building,");
  lines.push(`  ${bldgName},  !- Name`);
  lines.push(`  ${doc.buildingLocation?.azimuth ?? 0},  !- North Axis {deg}`);
  lines.push("  Suburbs,  !- Terrain");
  lines.push("  0.04,  !- Loads Convergence Tolerance Value");
  lines.push("  0.4,  !- Temperature Convergence Tolerance Value {deltaC}");
  lines.push("  FullExterior,  !- Solar Distribution");
  lines.push("  25,  !- Maximum Number of Warmup Days");
  lines.push("  6;  !- Minimum Number of Warmup Days");
  lines.push("");

  // 2. Materials
  for (const mat of doc.materials) {
    if (mat.type === "RESISTANCE" || (mat.resistance !== undefined && mat.conductivity === undefined)) {
      const rSi = (mat.resistance ?? 1.0) * (isIp ? R_IP_TO_SI : 1.0);
      lines.push("Material:NoMass,");
      lines.push(`  ${mat.name},  !- Name`);
      lines.push("  MediumRough,  !- Roughness");
      lines.push(`  ${rSi.toFixed(4)},  !- Thermal Resistance {m2-K/W}`);
      lines.push("  0.9,  !- Thermal Absorptance");
      lines.push("  0.7,  !- Solar Absorptance");
      lines.push("  0.7;  !- Visible Absorptance");
      lines.push("");
    } else {
      const thickM = (mat.thickness ?? 0.1) * (isIp ? FT_TO_M : 1.0);
      const kSi = (mat.conductivity ?? 1.0) * (isIp ? K_IP_TO_SI : 1.0);
      const rhoSi = (mat.density ?? 100.0) * (isIp ? RHO_IP_TO_SI : 1.0);
      const cpSi = (mat.specificHeat ?? 0.2) * (isIp ? CP_IP_TO_SI : 1.0);
      lines.push("Material,");
      lines.push(`  ${mat.name},  !- Name`);
      lines.push("  MediumRough,  !- Roughness");
      lines.push(`  ${thickM.toFixed(4)},  !- Thickness {m}`);
      lines.push(`  ${kSi.toFixed(4)},  !- Conductivity {W/m-K}`);
      lines.push(`  ${rhoSi.toFixed(1)},  !- Density {kg/m3}`);
      lines.push(`  ${cpSi.toFixed(1)};  !- Specific Heat {J/kg-K}`);
      lines.push("");
    }
  }

  // 3. Glazing materials & window constructions
  for (const glz of doc.glassTypes) {
    const uSi = (glz.glassConductance ?? 0.5) * (isIp ? U_IP_TO_SI : 1.0);
    const shgc = glz.shgc ?? (glz.shadingCoeff !== undefined ? glz.shadingCoeff * 0.87 : 0.65);
    const vt = glz.visibleTransmittance ?? 0.7;
    lines.push("WindowMaterial:SimpleGlazingSystem,");
    lines.push(`  ${glz.name}_MAT,  !- Name`);
    lines.push(`  ${uSi.toFixed(4)},  !- U-Factor {W/m2-K}`);
    lines.push(`  ${shgc.toFixed(4)},  !- Solar Heat Gain Coefficient`);
    lines.push(`  ${vt.toFixed(4)};  !- Visible Transmittance`);
    lines.push("");
    lines.push("Construction,");
    lines.push(`  ${glz.name},  !- Name`);
    lines.push(`  ${glz.name}_MAT;  !- Outside Layer`);
    lines.push("");
  }

  // 4. Constructions
  const layMap = new Map<string, Doe2Layers>();
  for (const lay of doc.layers) {
    layMap.set(lay.name.toLowerCase(), lay);
  }
  const conProps = computeAllConstructionProps(doc);

  for (const con of doc.constructions) {
    if (con.type === "U-VALUE") {
      const prop = conProps.get(con.name.toLowerCase());
      const rSi = prop ? prop.rTotalSi : 1.0;
      const synthMat = `${con.name}_UVAL_MAT`;
      lines.push("Material:NoMass,");
      lines.push(`  ${synthMat},  !- Name`);
      lines.push("  MediumRough,  !- Roughness");
      lines.push(`  ${rSi.toFixed(4)};  !- Thermal Resistance {m2-K/W}`);
      lines.push("");
      lines.push("Construction,");
      lines.push(`  ${con.name},  !- Name`);
      lines.push(`  ${synthMat};  !- Outside Layer`);
      lines.push("");
      continue;
    }

    const lay = con.layersName ? layMap.get(con.layersName.toLowerCase()) : undefined;
    const matList = lay ? lay.materials : con.materialName ? [con.materialName] : [];
    if (matList.length > 0) {
      lines.push("Construction,");
      lines.push(`  ${con.name},  !- Name`);
      for (let i = 0; i < matList.length; i++) {
        const sep = i === matList.length - 1 ? ";" : ",";
        lines.push(`  ${matList[i]}${sep}  !- Layer ${i + 1}`);
      }
      lines.push("");
    }
  }

  // 5. Zones (from DOE-2 SPACEs)
  const zoneBySpace = new Map<string, (typeof doc.zones)[number]>();
  for (const z of doc.zones) {
    if (z.spaceName) zoneBySpace.set(z.spaceName.toLowerCase(), z);
  }

  for (const sp of doc.spaces) {
    const areaM2 = (sp.area ?? 100.0) * (isIp ? FT2_TO_M2 : 1.0);
    const heightM = (sp.height ?? (isIp ? 10.0 : 3.0)) * (isIp ? FT_TO_M : 1.0);
    const volM3 = sp.volume !== undefined ? sp.volume * (isIp ? FT3_TO_M3 : 1.0) : areaM2 * heightM;

    lines.push("Zone,");
    lines.push(`  ${sp.name},  !- Name`);
    lines.push("  0,  !- Direction of Relative North {deg}");
    lines.push("  0, 0, 0,  !- X,Y,Z Origin {m}");
    lines.push("  1,  !- Type");
    lines.push("  1,  !- Multiplier");
    lines.push(`  ${heightM.toFixed(3)},  !- Ceiling Height {m}`);
    lines.push(`  ${volM3.toFixed(3)},  !- Volume {m3}`);
    lines.push(`  ${areaM2.toFixed(3)};  !- Floor Area {m2}`);
    lines.push("");

    if (sp.infiltrationAch !== undefined && sp.infiltrationAch > 0) {
      lines.push("ZoneInfiltration:DesignFlowRate,");
      lines.push(`  ${sp.name}_Infiltration,  !- Name`);
      lines.push(`  ${sp.name},  !- Zone Name`);
      lines.push("  AlwaysOn,  !- Schedule Name");
      lines.push("  AirChanges/Hour,  !- Design Flow Rate Calculation Method");
      lines.push("  , , ,");
      lines.push(`  ${sp.infiltrationAch.toFixed(4)};  !- Air Changes per Hour {1/hr}`);
      lines.push("");
    }

    if (sp.people !== undefined && sp.people > 0) {
      lines.push("People,");
      lines.push(`  ${sp.name}_People,  !- Name`);
      lines.push(`  ${sp.name},  !- Zone Name`);
      lines.push("  AlwaysOn,  !- Schedule Name");
      lines.push("  People,  !- Number of People Calculation Method");
      lines.push(`  ${sp.people.toFixed(2)};  !- Number of People`);
      lines.push("");
    }

    if (sp.lightingWPerArea !== undefined && sp.lightingWPerArea > 0) {
      const watts = sp.lightingWPerArea * (isIp ? (sp.area ?? areaM2 / FT2_TO_M2) : areaM2);
      lines.push("Lights,");
      lines.push(`  ${sp.name}_Lights,  !- Name`);
      lines.push(`  ${sp.name},  !- Zone Name`);
      lines.push("  AlwaysOn,  !- Schedule Name");
      lines.push("  LightingLevel,  !- Design Level Calculation Method");
      lines.push(`  ${watts.toFixed(1)};  !- Lighting Level {W}`);
      lines.push("");
    }

    if (sp.equipmentWPerArea !== undefined && sp.equipmentWPerArea > 0) {
      const watts = sp.equipmentWPerArea * (isIp ? (sp.area ?? areaM2 / FT2_TO_M2) : areaM2);
      lines.push("ElectricEquipment,");
      lines.push(`  ${sp.name}_Equip,  !- Name`);
      lines.push(`  ${sp.name},  !- Zone Name`);
      lines.push("  AlwaysOn,  !- Schedule Name");
      lines.push("  EquipmentLevel,  !- Design Level Calculation Method");
      lines.push(`  ${watts.toFixed(1)};  !- Design Level {W}`);
      lines.push("");
    }

    const z = zoneBySpace.get(sp.name.toLowerCase());
    if (z && z.type !== "UNCONDITIONED" && z.type !== "PLENUM") {
      const heatC = z.designHeatT !== undefined ? (isIp ? fahrenheitToCelsius(z.designHeatT) : z.designHeatT) : 20.0;
      const coolC = z.designCoolT !== undefined ? (isIp ? fahrenheitToCelsius(z.designCoolT) : z.designCoolT) : 24.0;
      lines.push("ZoneHVAC:IdealLoadsAirSystem,");
      lines.push(`  ${z.name}_IdealLoads,  !- Name`);
      lines.push("  ,  !- Availability Schedule Name");
      lines.push(`  ${sp.name}_SupplyNode,  !- Zone Supply Air Node Name`);
      lines.push("  , ,");
      lines.push(`  ${(heatC + 30.0).toFixed(1)},  !- Maximum Heating Supply Air Temperature {C}`);
      lines.push(`  ${(coolC - 10.0).toFixed(1)};  !- Minimum Cooling Supply Air Temperature {C}`);
      lines.push("");
    }
  }

  // 6. Surfaces
  for (const surf of doc.surfaces) {
    const areaM2 = (surf.area ?? (surf.width ?? 10) * (surf.height ?? 10)) * (isIp ? FT2_TO_M2 : 1.0);
    const side = Math.sqrt(Math.max(0.01, areaM2));
    const surfType = surf.kind === "ROOF" ? "Roof" : "Wall";
    const bc = surf.kind === "UNDERGROUND-WALL" ? "Ground" : "Outdoors";
    const sun = bc === "Outdoors" ? "SunExposed" : "NoSun";
    const wind = bc === "Outdoors" ? "WindExposed" : "NoWind";

    lines.push("BuildingSurface:Detailed,");
    lines.push(`  ${surf.name},  !- Name`);
    lines.push(`  ${surfType},  !- Surface Type`);
    lines.push(`  ${surf.constructionName ?? "DefaultConstruction"},  !- Construction Name`);
    lines.push(`  ${surf.spaceName ?? "DefaultZone"},  !- Zone Name`);
    lines.push(`  ${bc},  !- Outside Boundary Condition`);
    lines.push("  ,  !- Outside Boundary Condition Object");
    lines.push(`  ${sun},  !- Sun Exposure`);
    lines.push(`  ${wind},  !- Wind Exposure`);
    lines.push("  0.5,  !- View Factor to Ground");
    lines.push("  4,  !- Number of Vertices");
    lines.push(`  0.0, 0.0, ${side.toFixed(3)},`);
    lines.push("  0.0, 0.0, 0.0,");
    lines.push(`  ${side.toFixed(3)}, 0.0, 0.0,`);
    lines.push(`  ${side.toFixed(3)}, 0.0, ${side.toFixed(3)};`);
    lines.push("");
  }

  // 7. Windows
  for (const win of doc.windows) {
    const mult = win.multiplier ?? 1.0;
    const areaM2 = (win.area ?? (win.width ?? 4) * (win.height ?? 4)) * (isIp ? FT2_TO_M2 : 1.0);
    const side = Math.sqrt(Math.max(0.01, areaM2));
    lines.push("FenestrationSurface:Detailed,");
    lines.push(`  ${win.name},  !- Name`);
    lines.push("  Window,  !- Surface Type");
    lines.push(`  ${win.glassTypeName ?? "DefaultGlass"},  !- Construction Name`);
    lines.push(`  ${win.parentSurfaceName ?? "DefaultWall"},  !- Building Surface Name`);
    lines.push("  ,  !- Outside Boundary Condition Object");
    lines.push("  0.5,  !- View Factor to Ground");
    lines.push("  ,  !- Frame and Divider Name");
    lines.push(`  ${mult},  !- Multiplier`);
    lines.push("  4,  !- Number of Vertices");
    lines.push(`  0.5, 0.0, ${(0.5 + side).toFixed(3)},`);
    lines.push("  0.5, 0.0, 0.5,");
    lines.push(`  ${(0.5 + side).toFixed(3)}, 0.0, 0.5,`);
    lines.push(`  ${(0.5 + side).toFixed(3)}, 0.0, ${(0.5 + side).toFixed(3)};`);
    lines.push("");
  }

  return lines.join("\n");
}
