/**
 * @modelscript/qif — Bidirectional Cross-Language Projections to SysML v2 and Modelica 3.x.
 *
 * - `qifToSysML2(doc)`: Projects QIF characteristics, GD&T tolerances, and metrology inspection
 *   plans to SysML v2 `requirement def`, `verification def`, and `attribute` declarations.
 * - `qifToModelica(doc)`: Projects QIF features, tolerance zones, ASME Y14.5 bonus tolerances,
 *   and SPC distributions to a parameterized Modelica `record` and `model` block.
 */

import { evaluateQifSpc } from "../spc/index.js";
import type { QifDocument } from "../types.js";

export function qifToSysML2(doc: QifDocument): string {
  const pkgName = sanitizeIdent(doc.header.partName ?? "QifQualityPackage");
  const lines: string[] = [];

  lines.push(`package ${pkgName} {`);
  lines.push(`  doc /* Generated by @modelscript/qif from QIF ${doc.version} (QPId: ${doc.qpId}) */`);
  lines.push("");

  // 1. Features as part/item definitions with attribute tolerances
  for (const feat of doc.features) {
    const fName = sanitizeIdent(feat.name || feat.id);
    lines.push(`  part def ${fName} {`);
    lines.push(`    attribute featureId = "${feat.id}";`);
    lines.push(`    attribute featureType = "${feat.featureType}";`);
    lines.push(`    attribute isFeatureOfSize = ${feat.isFeatureOfSize};`);
    if (feat.nominalSize !== undefined) {
      lines.push(`    attribute nominalSize = ${feat.nominalSize};`);
    }
    if (feat.stepEntityId !== undefined) {
      lines.push(`    attribute stepEntityId = "${feat.stepEntityId}";`);
    }
    lines.push(`  }`);
    lines.push("");
  }

  // 2. Characteristics as SysML v2 requirement def blocks
  for (const char of doc.characteristics) {
    const reqName = sanitizeIdent(`${char.name || char.id}_Requirement`);
    const datumStr = char.datumReferences.map((d) => d.datumLabel).join(" | ");
    lines.push(`  requirement def ${reqName} {`);
    lines.push(
      `    doc /* GD&T ${char.gdtType} tolerance (${char.materialCondition})${datumStr ? ` wrt [${datumStr}]` : ""} */`,
    );
    lines.push(`    attribute characteristicId = "${char.id}";`);
    lines.push(`    attribute gdtType = "${char.gdtType}";`);
    if (char.nominalValue !== undefined) {
      lines.push(`    attribute nominalValue = ${char.nominalValue};`);
    }
    lines.push(`    attribute toleranceZone = ${char.toleranceZone};`);
    lines.push(`    attribute materialCondition = "${char.materialCondition}";`);
    if (char.balloonNumber !== undefined) {
      lines.push(`    attribute balloonNumber = ${char.balloonNumber};`);
    }
    lines.push(`  }`);
    lines.push("");
  }

  // 3. Inspection Plan & Metrology Verification as SysML v2 verification def
  lines.push(`  verification def InspectionPlanVerification {`);
  lines.push(`    doc /* Automated QIF 3.0 Metrology Verification Plan */`);
  for (const dev of doc.devices) {
    const devIdent = sanitizeIdent(dev.name || dev.id);
    lines.push(`    attribute ${devIdent}_uncertainty = ${dev.calibrationUncertainty};`);
  }
  for (const char of doc.characteristics) {
    const reqName = sanitizeIdent(`${char.name || char.id}_Requirement`);
    const verInst = sanitizeIdent(`verify_${char.id}`);
    lines.push(`    verify requirement ${verInst} : ${reqName};`);
  }
  for (const step of doc.planSteps) {
    const stepIdent = sanitizeIdent(`step_${step.stepNumber}_${step.id}`);
    lines.push(
      `    action ${stepIdent} { attribute featureId = "${step.featureId}"; attribute probingPointCount = ${step.probingPointCount}; }`,
    );
  }
  lines.push(`  }`);

  lines.push(`}`);
  return lines.join("\n");
}

export function qifToModelica(doc: QifDocument): string {
  const pkgName = sanitizeIdent(doc.header.partName ?? "QifMetrologyModel");
  const spc = evaluateQifSpc(doc);
  const spcByCharId = new Map(spc.characteristics.map((c) => [c.characteristicId, c]));

  const lines: string[] = [];
  lines.push(`package ${pkgName}`);
  lines.push(`  "Generated by @modelscript/qif from QIF ${doc.version} (QPId: ${doc.qpId})"`);
  lines.push("");

  // 1. Parameterized Tolerance Record
  lines.push(`  record ToleranceParameters`);
  lines.push(`    "QIF 3.0 Nominal Dimensions and GD&T Tolerance Parameters"`);
  for (const feat of doc.features) {
    const fName = sanitizeIdent(feat.name || feat.id);
    lines.push(
      `    parameter Real ${fName}_nominal = ${formatReal(feat.nominalSize ?? 0.0)} "Feature ${feat.name} (${feat.featureType}) nominal size";`,
    );
  }
  for (const char of doc.characteristics) {
    const cName = sanitizeIdent(char.name || char.id);
    const rep = spcByCharId.get(char.id);
    lines.push(
      `    parameter Real ${cName}_nominal = ${formatReal(char.nominalValue ?? 0.0)} "Characteristic ${char.name} nominal";`,
    );
    lines.push(
      `    parameter Real ${cName}_tolerance = ${formatReal(char.toleranceZone)} "Characteristic ${char.name} (${char.gdtType}) base tolerance";`,
    );
    lines.push(`    parameter Real ${cName}_mean = ${formatReal(rep?.mean ?? 0.0)} "SPC mean measured value";`);
    lines.push(
      `    parameter Real ${cName}_stdDev = ${formatReal(rep?.stdDev ?? 0.0)} "SPC sample standard deviation";`,
    );
  }
  lines.push(`  end ToleranceParameters;`);
  lines.push("");

  // 2. Metrology & Bonus Tolerance Evaluation Model
  lines.push(`  model QualityInspectionModel`);
  lines.push(`    "ASME Y14.5 GD&T Effective Tolerance and Deviation Model"`);
  lines.push(`    ToleranceParameters params;`);
  for (const char of doc.characteristics) {
    const cName = sanitizeIdent(char.name || char.id);
    const rep = spcByCharId.get(char.id);
    lines.push(
      `    parameter Real ${cName}_bonus = ${formatReal(rep?.meanBonusTolerance ?? 0.0)} "ASME Y14.5 ${char.materialCondition} bonus tolerance";`,
    );
    lines.push(`    Real ${cName}_effective_tol "Effective tolerance zone";`);
    lines.push(`    Real ${cName}_deviation "Measured geometric/dimensional deviation";`);
  }

  if (doc.characteristics.length > 0) {
    lines.push(`  equation`);
    for (const char of doc.characteristics) {
      const cName = sanitizeIdent(char.name || char.id);
      lines.push(`    ${cName}_effective_tol = params.${cName}_tolerance + ${cName}_bonus;`);
      lines.push(`    ${cName}_deviation = params.${cName}_mean;`);
    }
  }
  lines.push(`  end QualityInspectionModel;`);
  lines.push("");
  lines.push(`end ${pkgName};`);

  return lines.join("\n");
}

function formatReal(val: number): string {
  if (!Number.isFinite(val)) return "0.0";
  return Number.isInteger(val) ? `${val}.0` : String(val);
}

function sanitizeIdent(name: string): string {
  const cleaned = name.replace(/[^a-zA-Z0-9_]/g, "_");
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned || "QifElement";
}
