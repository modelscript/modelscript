/**
 * @modelscript/febio — Cross-Domain Projections to CalculiX (.inp) and Modelica 3.x (.mo).
 *
 * - `febioToCalculixInp(doc)`: Projects FEBio meshes, node sets, hyperelastic/elastic
 *   materials, boundary conditions, and time steps to CalculiX / Abaqus `.inp` deck format.
 * - `febioToModelica(doc)`: Projects FEBio tissue constitutive models, Mooney-Rivlin
 *   strain energy equations, and Cauchy stress laws to a Modelica 3.x package.
 */

import { deriveConstitutiveParameters, solveHyperelasticMechanics } from "../solver/index.js";
import type { FebioDocument } from "../types.js";

export function febioToCalculixInp(doc: FebioDocument): string {
  const lines: string[] = [];
  lines.push(`*HEADING`);
  lines.push(`FEBio ${doc.version} Biomechanics Model: ${doc.title} (Generated by @modelscript/febio)`);

  // 1. Nodes
  if (doc.nodes.length > 0) {
    lines.push(`*NODE, NSET=NALL`);
    for (const n of doc.nodes) {
      lines.push(`${n.id}, ${n.x}, ${n.y}, ${n.z}`);
    }
  }

  // 2. Elements grouped by type
  const tet4Elems = doc.elements.filter((e) => e.type === "tet4");
  if (tet4Elems.length > 0) {
    lines.push(`*ELEMENT, TYPE=C3D4, ELSET=EALL_TET4`);
    for (const el of tet4Elems) {
      lines.push(`${el.id}, ${el.nodeIds.join(", ")}`);
    }
  }

  const hex8Elems = doc.elements.filter((e) => e.type === "hex8");
  if (hex8Elems.length > 0) {
    lines.push(`*ELEMENT, TYPE=C3D8, ELSET=EALL_HEX8`);
    for (const el of hex8Elems) {
      lines.push(`${el.id}, ${el.nodeIds.join(", ")}`);
    }
  }

  // 3. NodeSets
  for (const ns of doc.nodeSets) {
    lines.push(`*NSET, NSET=${sanitizeIdent(ns.name)}`);
    lines.push(ns.nodeIds.join(", "));
  }

  // 4. Materials
  for (const mat of doc.materials) {
    const matIdent = sanitizeIdent(mat.name || `MAT_${mat.id}`);
    const params = deriveConstitutiveParameters(mat);
    lines.push(`*MATERIAL, NAME=${matIdent}`);
    if (
      mat.c1 !== undefined ||
      mat.c2 !== undefined ||
      mat.type.toLowerCase().includes("mooney") ||
      mat.type.toLowerCase().includes("hookean")
    ) {
      const d1 = params.bulkModulusK > 0 ? 2.0 / params.bulkModulusK : 0.001;
      lines.push(`*HYPERELASTIC, MOONEY-RIVLIN`);
      lines.push(`${params.c1}, ${params.c2}, ${d1}`);
    } else {
      lines.push(`*ELASTIC`);
      lines.push(`${params.youngsModulusE}, ${params.poissonRatioNu}`);
    }
    if (mat.density !== undefined) {
      lines.push(`*DENSITY`);
      lines.push(`${mat.density}`);
    }
  }

  // 5. Step & Boundary Conditions
  lines.push(`*STEP, NLGEOM`);
  const dt = doc.control?.stepSize ?? 0.1;
  const totalTime = (doc.control?.timeSteps ?? 10) * dt;
  lines.push(`*STATIC`);
  lines.push(`${dt}, ${totalTime}`);

  if (doc.boundaryConditions.length > 0) {
    lines.push(`*BOUNDARY`);
    for (const bc of doc.boundaryConditions) {
      const nset = sanitizeIdent(bc.nodeSet || "NALL");
      const val = bc.type === "prescribed displacement" ? (bc.value ?? 0.0) : 0.0;
      for (const dof of bc.dofs) {
        const dofNum = dof.toLowerCase() === "x" ? 1 : dof.toLowerCase() === "y" ? 2 : 3;
        lines.push(`${nset}, ${dofNum}, ${dofNum}, ${val}`);
      }
    }
  }

  lines.push(`*END STEP`);
  return lines.join("\n");
}

export function febioToModelica(doc: FebioDocument): string {
  const pkgName = sanitizeIdent(doc.title || "FEBioBiomechanicsPackage");
  const summary = solveHyperelasticMechanics(doc);

  const lines: string[] = [];
  lines.push(`package ${pkgName}`);
  lines.push(`  "Generated by @modelscript/febio from FEBio ${doc.version} (${doc.moduleType})"`);
  lines.push("");

  lines.push(`  model SoftTissueMechanics`);
  lines.push(`    "Hyperelastic Mooney-Rivlin / neo-Hookean Soft-Tissue Constitutive Model"`);
  lines.push(`    parameter Real meshVolume = ${formatReal(summary.totalVolume)} "Total mesh volume";`);

  for (const mat of summary.materials) {
    const prefix = sanitizeIdent(mat.materialName || `Mat_${mat.materialId}`);
    lines.push(`    parameter Real ${prefix}_C1 = ${formatReal(mat.c1)} "Mooney-Rivlin C1 coefficient";`);
    lines.push(`    parameter Real ${prefix}_C2 = ${formatReal(mat.c2)} "Mooney-Rivlin C2 coefficient";`);
    lines.push(`    parameter Real ${prefix}_K = ${formatReal(mat.bulkModulusK)} "Bulk modulus K";`);
    lines.push(`    parameter Real ${prefix}_lambda1 = ${formatReal(mat.principalStretches[0])} "Principal stretch";`);
    lines.push(`    Real ${prefix}_I1 "First right Cauchy-Green invariant";`);
    lines.push(`    Real ${prefix}_I2 "Second right Cauchy-Green invariant";`);
    lines.push(`    Real ${prefix}_W "Strain energy density";`);
    lines.push(`    Real ${prefix}_sigma11 "Axial Cauchy stress";`);
  }

  lines.push(`  equation`);
  for (const mat of summary.materials) {
    const prefix = sanitizeIdent(mat.materialName || `Mat_${mat.materialId}`);
    lines.push(`    ${prefix}_I1 = ${formatReal(mat.invariantI1)};`);
    lines.push(`    ${prefix}_I2 = ${formatReal(mat.invariantI2)};`);
    lines.push(`    ${prefix}_W = ${prefix}_C1 * (${prefix}_I1 - 3.0) + ${prefix}_C2 * (${prefix}_I2 - 3.0);`);
    lines.push(`    ${prefix}_sigma11 = ${formatReal(mat.cauchyStress[0])};`);
  }
  lines.push(`  end SoftTissueMechanics;`);
  lines.push("");
  lines.push(`end ${pkgName};`);

  return lines.join("\n");
}

function formatReal(val: number): string {
  if (!Number.isFinite(val)) return "0.0";
  return Number.isInteger(val) ? `${val}.0` : String(val);
}

function sanitizeIdent(name: string): string {
  const cleaned = name.replace(/[^a-zA-Z0-9_]/g, "_");
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned || "FEBioEntity";
}
