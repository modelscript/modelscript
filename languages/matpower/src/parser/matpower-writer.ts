/**
 * Serializer for MATPOWER case files (.m).
 */

import type { MatpowerCase } from "../types.js";

/**
 * Serializes a MatpowerCase object into a standard MATPOWER .m file string.
 */
export function writeMatpowerCase(mpc: MatpowerCase): string {
  const caseName = mpc.caseName ?? "case_export";
  const lines: string[] = [];

  lines.push(`function mpc = ${caseName}`);
  lines.push(`% Generated by ModelScript @modelscript/matpower`);
  lines.push(`mpc.version = '${mpc.version || "2"}';`);
  lines.push(`mpc.baseMVA = ${mpc.baseMVA.toFixed(1)};`);
  lines.push("");

  // Bus Data
  lines.push(`%% bus data`);
  lines.push(`%	bus_i	type	Pd	Qd	Gs	Bs	area	Vm	Va	baseKV	zone	Vmax	Vmin`);
  lines.push(`mpc.bus = [`);
  for (const b of mpc.bus) {
    lines.push(
      `\t${b.bus_i}\t${b.type}\t${b.pd.toFixed(4)}\t${b.qd.toFixed(4)}\t${b.gs.toFixed(4)}\t${b.bs.toFixed(4)}\t${b.area}\t${b.vm.toFixed(4)}\t${b.va.toFixed(4)}\t${b.baseKv.toFixed(2)}\t${b.zone}\t${b.vmax.toFixed(4)}\t${b.vmin.toFixed(4)};`,
    );
  }
  lines.push(`];`);
  lines.push("");

  // Generator Data
  lines.push(`%% generator data`);
  lines.push(`%	bus	Pg	Qg	Qmax	Qmin	Vg	mBase	status	Pmax	Pmin`);
  lines.push(`mpc.gen = [`);
  for (const g of mpc.gen) {
    lines.push(
      `\t${g.bus}\t${g.pg.toFixed(4)}\t${g.qg.toFixed(4)}\t${g.qmax.toFixed(4)}\t${g.qmin.toFixed(4)}\t${g.vg.toFixed(4)}\t${g.mbase.toFixed(2)}\t${g.status}\t${g.pmax.toFixed(4)}\t${g.pmin.toFixed(4)};`,
    );
  }
  lines.push(`];`);
  lines.push("");

  // Branch Data
  lines.push(`%% branch data`);
  lines.push(`%	fbus	tbus	r	x	b	rateA	rateB	rateC	ratio	angle	status	angmin	angmax`);
  lines.push(`mpc.branch = [`);
  for (const br of mpc.branch) {
    lines.push(
      `\t${br.fbus}\t${br.tbus}\t${br.r.toFixed(6)}\t${br.x.toFixed(6)}\t${br.b.toFixed(6)}\t${br.rateA.toFixed(2)}\t${br.rateB.toFixed(2)}\t${br.rateC.toFixed(2)}\t${br.ratio.toFixed(4)}\t${br.angle.toFixed(4)}\t${br.status}\t${br.angmin.toFixed(2)}\t${br.angmax.toFixed(2)};`,
    );
  }
  lines.push(`];`);
  lines.push("");

  // GenCost Data
  if (mpc.gencost && mpc.gencost.length > 0) {
    lines.push(`%% generator cost data`);
    lines.push(`%	1	startup	shutdown	n	c(n-1)	...	c0`);
    lines.push(`mpc.gencost = [`);
    for (const gc of mpc.gencost) {
      const costStr = gc.cost.map((c) => c.toFixed(6)).join("\t");
      lines.push(`\t${gc.model}\t${gc.startup.toFixed(2)}\t${gc.shutdown.toFixed(2)}\t${gc.ncost}\t${costStr};`);
    }
    lines.push(`];`);
    lines.push("");
  }

  // Bus Names (optional)
  if (mpc.busNames && mpc.busNames.size > 0) {
    lines.push(`%% bus names`);
    lines.push(`mpc.bus_name = {`);
    for (let i = 1; i <= mpc.busNames.size; i++) {
      const name = mpc.busNames.get(i) ?? `Bus ${i}`;
      lines.push(`\t'${name}';`);
    }
    lines.push(`};`);
    lines.push("");
  }

  lines.push(`return;`);
  return lines.join("\n");
}
