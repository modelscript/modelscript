import type { LpsModel } from "../types.js";

/**
 * Projects a PipelineStudio network into standard Modelica 3.x (Modelica.Fluid).
 */
export function lpsToModelica(model: LpsModel): string {
  const modelName = (model.title || model.id || "PipelineNetwork").replace(/[^a-zA-Z0-9_]/g, "_");
  const lines: string[] = [
    `model ${modelName}`,
    `  // Generated by @modelscript/lps Modelica.Fluid projection`,
    `  extends Modelica.Icons.Example;`,
    ``,
  ];

  // 1. Pipes
  lines.push(`  // Pipes`);
  for (const pipe of model.pipes) {
    const pName = pipe.name.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(
      `  Modelica.Fluid.Pipes.DynamicPipe ${pName}(length = ${pipe.length}, diameter = ${pipe.diameter}, roughness = ${pipe.roughness});`,
    );
  }

  // 2. Compressors
  if (model.compressors.length > 0) {
    lines.push(``);
    lines.push(`  // Compressor Stations`);
    for (const comp of model.compressors) {
      const cName = comp.name.replace(/[^a-zA-Z0-9_]/g, "_");
      lines.push(`  Modelica.Fluid.Machines.PrescribedPump ${cName}(V_flow_single = ${comp.surgeFlow ?? 20.0});`);
    }
  }

  // 3. Regulators / Valves
  if (model.regulators.length > 0 || model.valves.length > 0) {
    lines.push(``);
    lines.push(`  // Valves & Regulators`);
    for (const reg of model.regulators) {
      const rName = reg.name.replace(/[^a-zA-Z0-9_]/g, "_");
      lines.push(
        `  Modelica.Fluid.Valves.ValveIncompressible ${rName}(CvData = Modelica.Fluid.Types.CvTypes.OpPoint);`,
      );
    }
    for (const valve of model.valves) {
      const vName = valve.name.replace(/[^a-zA-Z0-9_]/g, "_");
      lines.push(`  Modelica.Fluid.Valves.ValveIncompressible ${vName}(opening = ${valve.opening});`);
    }
  }

  // 4. Boundary Nodes (Supplies, Deliveries, Junctions)
  lines.push(``);
  lines.push(`  // Boundary Nodes`);
  for (const node of model.nodes) {
    const nName = node.name.replace(/[^a-zA-Z0-9_]/g, "_");
    if (node.type === "SUPPLY") {
      lines.push(
        `  Modelica.Fluid.Sources.Boundary_pT ${nName}(p = ${node.pressure ?? 65.0e5}, T = ${node.temperature ?? 293.15});`,
      );
    } else if (node.type === "DELIVERY") {
      lines.push(
        `  Modelica.Fluid.Sources.MassFlowSource_T ${nName}(m_flow = ${node.flowRate ?? 20.0}, T = ${node.temperature ?? 288.15});`,
      );
    } else {
      lines.push(
        `  Modelica.Fluid.Sources.Boundary_pT ${nName}(p = ${node.pressure ?? 50.0e5}, T = ${node.temperature ?? 293.15});`,
      );
    }
  }

  // 5. Connections
  lines.push(``);
  lines.push(`equation`);
  for (const pipe of model.pipes) {
    const pName = pipe.name.replace(/[^a-zA-Z0-9_]/g, "_");
    const fromN = pipe.fromNode.replace(/[^a-zA-Z0-9_]/g, "_");
    const toN = pipe.toNode.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(`  connect(${fromN}.ports[1], ${pName}.port_a);`);
    lines.push(`  connect(${pName}.port_b, ${toN}.ports[1]);`);
  }

  lines.push(`end ${modelName};`);
  return lines.join("\n");
}
