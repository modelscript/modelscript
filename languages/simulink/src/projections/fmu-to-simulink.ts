/**
 * FMI to Simulink Projection Generator.
 *
 * Synthesizes:
 * 1. Standard Level-2 C-MEX S-Function wrapper (`mdlInitializeSizes`, `mdlOutputs`, `mdlTerminate`)
 *    linking to the FMI 2.0 / 3.0 shared library.
 * 2. Simulink System Block XML representation with input and output signal ports.
 */

export interface FmuVariableStub {
  name: string;
  causality: "input" | "output" | "parameter" | "calculatedParameter" | "local" | "independent" | string;
  type: string;
  valueReference: number;
  unit?: string | undefined;
  start?: number | string | boolean | undefined;
  description?: string | undefined;
}

export interface FmuModelStub {
  modelName: string;
  description?: string | undefined;
  guid?: string | undefined;
  fmiVersion?: string | undefined;
  variables: FmuVariableStub[];
}

export interface SimulinkProjectionResult {
  sFunctionName: string;
  cMexSource: string;
  simulinkBlockXml: string;
  numInputs: number;
  numOutputs: number;
  numParameters: number;
}

export function fmuToSimulink(model: FmuModelStub): SimulinkProjectionResult {
  const sFnName = sanitizeSimulinkIdent(model.modelName) + "_sfun";
  const inputs = model.variables.filter((v) => v.causality === "input");
  const outputs = model.variables.filter((v) => v.causality === "output");
  const parameters = model.variables.filter(
    (v) => v.causality === "parameter" || v.causality === "calculatedParameter",
  );

  const numIn = Math.max(1, inputs.length);
  const numOut = Math.max(1, outputs.length);
  const numParams = parameters.length;

  // 1. Generate Level-2 C-MEX S-Function C code
  const cLines: string[] = [
    `/* ============================================================================== */`,
    `/* Auto-generated by ModelScript — Level-2 C-MEX S-Function for FMU */`,
    `/* Model: ${model.modelName} */`,
    `/* ============================================================================== */`,
    `#define S_FUNCTION_NAME ${sFnName}`,
    `#define S_FUNCTION_LEVEL 2`,
    ``,
    `#include "simstruc.h"`,
    ``,
    `static void mdlInitializeSizes(SimStruct *S) {`,
    `    ssSetNumSFcnParams(S, ${numParams});`,
    `    if (ssGetNumSFcnParams(S) != ssGetSFcnParamsCount(S)) return;`,
    ``,
    `    /* Input Ports */`,
    `    if (!ssSetNumInputPorts(S, ${numIn})) return;`,
  ];

  inputs.forEach((_, idx) => {
    cLines.push(`    ssSetInputPortWidth(S, ${idx}, 1);`);
    cLines.push(`    ssSetInputPortDirectFeedThrough(S, ${idx}, 1);`);
  });

  cLines.push(``, `    /* Output Ports */`, `    if (!ssSetNumOutputPorts(S, ${numOut})) return;`);
  outputs.forEach((_, idx) => {
    cLines.push(`    ssSetOutputPortWidth(S, ${idx}, 1);`);
  });

  cLines.push(
    `    ssSetNumSampleTimes(S, 1);`,
    `    ssSetOptions(S, SS_OPTION_EXCEPTION_FREE_CODE);`,
    `}`,
    ``,
    `static void mdlInitializeSampleTimes(SimStruct *S) {`,
    `    ssSetSampleTime(S, 0, INHERITED_SAMPLE_TIME);`,
    `    ssSetOffsetTime(S, 0, 0.0);`,
    `}`,
    ``,
    `static void mdlOutputs(SimStruct *S, int_T tid) {`,
    `    time_T t = ssGetT(S);`,
    `    /* Set Inputs to FMU */`,
  );

  inputs.forEach((_, idx) => {
    cLines.push(`    InputRealPtrsType uPtr_${idx} = ssGetInputPortRealSignalPtrs(S, ${idx});`);
    cLines.push(`    real_T u_${idx} = *uPtr_${idx}[0];`);
  });

  cLines.push(
    `    /* Step FMU (Co-Simulation step call) */`,
    `    /* fmi2DoStep(...) */`,
    ``,
    `    /* Fetch Outputs from FMU */`,
  );

  outputs.forEach((out, idx) => {
    cLines.push(`    real_T *y_${idx} = ssGetOutputPortRealSignal(S, ${idx});`);
    cLines.push(`    *y_${idx} = 0.0; /* Populated from FMU output VR ${out.valueReference} */`);
  });

  cLines.push(
    `}`,
    ``,
    `static void mdlTerminate(SimStruct *S) {`,
    `    /* Terminate and free FMU instance */`,
    `}`,
    ``,
    `#ifdef MATLAB_MEX_FILE`,
    `#include "simulink.c"`,
    `#else`,
    `#include "cg_sfun.h"`,
    `#endif`,
  );

  // 2. Generate Simulink Subsystem Block XML
  const blockXml = `
  <Block BlockType="S-Function" Name="${model.modelName}">
    <P Name="FunctionName">${sFnName}</P>
    <P Name="Parameters">${parameters.map((p) => p.name).join(", ")}</P>
    <Ports>[${inputs.length}, ${outputs.length}]</Ports>
  </Block>
  `.trim();

  return {
    sFunctionName: sFnName,
    cMexSource: cLines.join("\n"),
    simulinkBlockXml: blockXml,
    numInputs: inputs.length,
    numOutputs: outputs.length,
    numParameters: parameters.length,
  };
}

function sanitizeSimulinkIdent(name: string): string {
  return name.replace(/[^A-Za-z0-9_]/g, "_").replace(/^([0-9])/, "_$1");
}
