/**
 * Polyglot projections from Motorola S-Record (SREC) to:
 * - Intel HEX (`.hex`)
 * - Verilog `$readmemh` (`.mem`)
 * - C `const uint8_t[]` firmware array (`.h` / `.c`)
 */

import { solveSrecMemory } from "../solver/index.js";
import type { SrecFile } from "../types.js";

function hex(value: number, width: number): string {
  return (value >>> 0).toString(16).toUpperCase().padStart(width, "0");
}

function ihexRecord(address16: number, recordType: number, data: Uint8Array): string {
  const count = data.length & 0xff;
  const addrHi = (address16 >>> 8) & 0xff;
  const addrLo = address16 & 0xff;
  let sum = count + addrHi + addrLo + (recordType & 0xff);
  let payload = "";
  for (let i = 0; i < data.length; i++) {
    const b = data[i]!;
    sum += b;
    payload += hex(b, 2);
  }
  const checksum = -sum & 0xff;
  return `:${hex(count, 2)}${hex(address16 & 0xffff, 4)}${hex(recordType, 2)}${payload}${hex(checksum, 2)}`;
}

/**
 * Projects a Motorola S-Record image to Intel HEX format (`.hex`),
 * emitting Type `04` Extended Linear Address records for addresses > 0xFFFF
 * and Type `05` Start Linear Address when an entry point is present.
 */
export function srecToIntelHex(file: SrecFile, bytesPerLine: number = 16): string {
  const solved = solveSrecMemory(file);
  const chunkMax = Math.max(1, Math.min(255, bytesPerLine));
  const lines: string[] = [];
  let currentUpper16 = -1;

  for (const region of solved.regions) {
    let cursor = 0;
    while (cursor < region.data.length) {
      const addr = (region.startAddress + cursor) >>> 0;
      const upper16 = (addr >>> 16) & 0xffff;
      const lower16 = addr & 0xffff;

      if (upper16 !== currentUpper16 && (upper16 !== 0 || currentUpper16 !== -1)) {
        const ela = new Uint8Array([(upper16 >>> 8) & 0xff, upper16 & 0xff]);
        lines.push(ihexRecord(0x0000, 0x04, ela));
        currentUpper16 = upper16;
      }

      // Do not cross a 64 KiB boundary in a single Intel HEX record
      const maxToBoundary = 0x10000 - lower16;
      const take = Math.min(chunkMax, region.data.length - cursor, maxToBoundary);
      lines.push(ihexRecord(lower16, 0x00, region.data.subarray(cursor, cursor + take)));
      cursor += take;
    }
  }

  if (file.startAddress !== undefined && file.startAddress > 0) {
    const sa = file.startAddress >>> 0;
    const sla = new Uint8Array([(sa >>> 24) & 0xff, (sa >>> 16) & 0xff, (sa >>> 8) & 0xff, sa & 0xff]);
    lines.push(ihexRecord(0x0000, 0x05, sla));
  }

  // EOF record
  lines.push(":00000001FF");
  return lines.join("\n") + "\n";
}

/**
 * Projects a Motorola S-Record image to Verilog `$readmemh` format (`.mem`).
 */
export function srecToVerilogReadmemh(file: SrecFile, bytesPerLine: number = 16): string {
  const solved = solveSrecMemory(file);
  const cols = Math.max(1, bytesPerLine);
  const lines: string[] = [
    `// Generated by @modelscript/srec from ${file.name}`,
    `// Regions: ${solved.regions.length}, Total Bytes: ${solved.totalDataBytes}, CRC32: 0x${hex(solved.overallCrc32, 8)}`,
  ];

  for (const region of solved.regions) {
    lines.push(`@${hex(region.startAddress, 8)}`);
    for (let i = 0; i < region.data.length; i += cols) {
      const slice = region.data.subarray(i, Math.min(i + cols, region.data.length));
      const parts: string[] = [];
      for (let j = 0; j < slice.length; j++) {
        parts.push(hex(slice[j]!, 2));
      }
      lines.push(parts.join(" "));
    }
  }

  return lines.join("\n") + "\n";
}

export interface SrecToCArrayOptions {
  /** Base C identifier prefix (default derived from `file.name`). */
  symbolName?: string | undefined;
  /** Number of hex bytes per source line (default 12). */
  bytesPerLine?: number | undefined;
}

/**
 * Projects a Motorola S-Record image to a C `const uint8_t[]` firmware array with address, length, and CRC-32 metadata.
 */
export function srecToCArray(file: SrecFile, options: SrecToCArrayOptions = {}): string {
  const solved = solveSrecMemory(file);
  const rawName = options.symbolName || file.name || "firmware";
  const sym = rawName
    .replace(/[^A-Za-z0-9_]/g, "_")
    .replace(/^(\d)/, "_$1")
    .toLowerCase();
  const cols = Math.max(1, options.bytesPerLine ?? 12);

  const lines: string[] = [
    `/* Generated by @modelscript/srec from ${file.name} */`,
    `#include <stdint.h>`,
    `#include <stddef.h>`,
    ``,
    `#define ${sym.toUpperCase()}_REGION_COUNT (${solved.regions.length}u)`,
    `#define ${sym.toUpperCase()}_TOTAL_BYTES  (${solved.totalDataBytes}u)`,
    `#define ${sym.toUpperCase()}_CRC32        (0x${hex(solved.overallCrc32, 8)}u)`,
  ];

  if (file.startAddress !== undefined) {
    lines.push(`#define ${sym.toUpperCase()}_ENTRY_POINT  (0x${hex(file.startAddress, 8)}u)`);
  }
  lines.push(``);

  for (const region of solved.regions) {
    const regSym = `${sym}_region_${region.index}`;
    lines.push(
      `/* Region ${region.index}: 0x${hex(region.startAddress, 8)}..0x${hex(region.endAddress, 8)} (${region.size} bytes, CRC32=0x${hex(region.crc32, 8)}) */`,
    );
    lines.push(`static const uint32_t ${regSym}_addr = 0x${hex(region.startAddress, 8)}u;`);
    lines.push(`static const size_t ${regSym}_size = ${region.size}u;`);
    lines.push(`static const uint8_t ${regSym}_data[${Math.max(1, region.size)}] = {`);
    for (let i = 0; i < region.data.length; i += cols) {
      const slice = region.data.subarray(i, Math.min(i + cols, region.data.length));
      const row = Array.from(slice, (b) => `0x${hex(b, 2)}`).join(", ");
      const comma = i + cols < region.data.length ? "," : "";
      lines.push(`  ${row}${comma}`);
    }
    lines.push(`};`);
    lines.push(``);
  }

  return lines.join("\n");
}
