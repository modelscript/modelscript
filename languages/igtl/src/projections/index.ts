/**
 * @modelscript/igtl — Projections to ROS URDF (.urdf) and Modelica 3.x (.mo).
 */

import { solveTransformChainAndPivot } from "../kinematics/index.js";
import type { IgtlDocument, Matrix4x4 } from "../types.js";

function matrixToRpy(T: Matrix4x4): [number, number, number] {
  const r00 = T[0]!;
  const r10 = T[4]!,
    r11 = T[5]!,
    r12 = T[6]!;
  const r20 = T[8]!,
    r21 = T[9]!,
    r22 = T[10]!;

  const sy = Math.sqrt(r00 * r00 + r10 * r10);
  let roll = 0,
    pitch = 0,
    yaw = 0;
  if (sy > 1e-6) {
    roll = Math.atan2(r21, r22);
    pitch = Math.atan2(-r20, sy);
    yaw = Math.atan2(r10, r00);
  } else {
    roll = Math.atan2(-r12, r11);
    pitch = Math.atan2(-r20, sy);
    yaw = 0;
  }
  return [Math.round(roll * 1e6) / 1e6, Math.round(pitch * 1e6) / 1e6, Math.round(yaw * 1e6) / 1e6];
}

/**
 * Projects an OpenIGTLink / PLUS coordinate frame tree into a ROS URDF (<robot>) XML model.
 */
export function igtlToUrdf(doc: IgtlDocument, robotName = "SurgicalNavigationRobot"): string {
  const lines: string[] = [`<?xml version="1.0" encoding="UTF-8"?>`, `<robot name="${robotName}">`];

  const frames = new Set<string>();
  for (const tf of doc.transforms) {
    frames.add(tf.from);
    frames.add(tf.to);
  }
  if (frames.size === 0) {
    frames.add("Reference");
    frames.add("StylusTip");
  }

  for (const frame of frames) {
    lines.push(`  <link name="${frame}"/>`);
  }

  for (const tf of doc.transforms) {
    if (tf.from === tf.to) continue;
    // Convert mm to meters for standard ROS URDF xyz, or preserve clear xyz and rpy
    const txM = Math.round((tf.matrix[3]! / 1000.0) * 1e6) / 1e6;
    const tyM = Math.round((tf.matrix[7]! / 1000.0) * 1e6) / 1e6;
    const tzM = Math.round((tf.matrix[11]! / 1000.0) * 1e6) / 1e6;
    const [r, p, y] = matrixToRpy(tf.matrix);

    lines.push(`  <joint name="${tf.from}To${tf.to}_joint" type="fixed">`);
    lines.push(`    <parent link="${tf.to}"/>`);
    lines.push(`    <child link="${tf.from}"/>`);
    lines.push(`    <origin xyz="${txM} ${tyM} ${tzM}" rpy="${r} ${p} ${y}"/>`);
    lines.push(`  </joint>`);
  }

  lines.push(`</robot>`);
  return lines.join("\n");
}

/**
 * Projects an OpenIGTLink / PLUS surgical navigation configuration into a Modelica 3.x model.
 */
export function igtlToModelica(doc: IgtlDocument, modelName = "SurgicalNavigationModel"): string {
  const safeName = modelName.replace(/[^a-zA-Z0-9_]/g, "_");
  const lines: string[] = [
    `model ${safeName}`,
    `  "Generated by @modelscript/igtl — OpenIGTLink & PLUS Surgical Navigation Kinematics"`,
    "",
  ];

  for (const dev of doc.devices) {
    const base = dev.id.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(`  parameter Real ${base}_AcquisitionRate(unit="Hz") = ${dev.acquisitionRate ?? 60.0};`);
  }

  const eqLines: string[] = [];
  for (const tf of doc.transforms) {
    const base = `${tf.from}To${tf.to}`.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(`  parameter Real ${base}_Tx(unit="mm") = ${tf.matrix[3]!};`);
    lines.push(`  parameter Real ${base}_Ty(unit="mm") = ${tf.matrix[7]!};`);
    lines.push(`  parameter Real ${base}_Tz(unit="mm") = ${tf.matrix[11]!};`);
    if (tf.errorMm !== undefined) {
      lines.push(`  parameter Real ${base}_CalibrationError(unit="mm") = ${tf.errorMm};`);
    }
  }

  const solved = solveTransformChainAndPivot(doc);
  lines.push(`  Real ComposedTranslationNorm(unit="mm");`);
  eqLines.push(`  ComposedTranslationNorm = ${solved.translationNormMm};`);

  if (solved.pivotCalibration) {
    lines.push(`  Real StylusPivotRmsError(unit="mm");`);
    eqLines.push(`  StylusPivotRmsError = ${solved.pivotCalibration.rmsErrorMm};`);
  }

  if (solved.fitzpatrickTre) {
    lines.push(`  Real FitzpatrickTRE(unit="mm");`);
    eqLines.push(`  FitzpatrickTRE = ${solved.fitzpatrickTre.treMm};`);
  }

  lines.push("");
  lines.push("equation");
  for (const eq of eqLines) {
    lines.push(eq);
  }
  lines.push(`end ${safeName};`);
  return lines.join("\n");
}
