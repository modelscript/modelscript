import { computeBraggPeakDepthDose } from "../physics/index.js";
import type { TopasDocument, TopasGeometryComponent } from "../types.js";

function materialColor(material?: string): string {
  switch (material) {
    case "G4_WATER":
    case "Water":
      return "[0.2, 0.6, 0.95, 0.45]";
    case "G4_BONE_COMPACT_ICRU":
      return "[0.95, 0.92, 0.80, 0.85]";
    case "G4_Pb":
    case "Lead":
      return "[0.35, 0.35, 0.40, 0.9]";
    case "G4_LEXAN":
    case "G4_PMMA":
    case "Lucite":
      return "[0.85, 0.90, 0.25, 0.6]";
    case "G4_AIR":
    case "Air":
    case "Vacuum":
      return "[0.8, 0.9, 1.0, 0.15]";
    default:
      return "[0.7, 0.7, 0.75, 0.7]";
  }
}

function renderScadPrimitive(comp: TopasGeometryComponent): string {
  const t = comp.type.toLowerCase();
  if (t.includes("cylinder")) {
    const rMax = comp.rMax ?? 10.0;
    const rMin = comp.rMin ?? 0.0;
    const h = 2.0 * (comp.hl ?? 10.0);
    if (rMin > 0 && rMin < rMax) {
      return `difference() { cylinder(h = ${h}, r = ${rMax}, center = true, $fn = 64); cylinder(h = ${h + 0.2}, r = ${rMin}, center = true, $fn = 64); }`;
    }
    return `cylinder(h = ${h}, r = ${rMax}, center = true, $fn = 64);`;
  }
  if (t.includes("sphere")) {
    const rMax = comp.rMax ?? 10.0;
    const rMin = comp.rMin ?? 0.0;
    if (rMin > 0 && rMin < rMax) {
      return `difference() { sphere(r = ${rMax}, $fn = 64); sphere(r = ${rMin}, $fn = 64); }`;
    }
    return `sphere(r = ${rMax}, $fn = 64);`;
  }
  const dx = 2.0 * (comp.hlx ?? 10.0);
  const dy = 2.0 * (comp.hly ?? 10.0);
  const dz = 2.0 * (comp.hlz ?? 10.0);
  return `cube([${dx}, ${dy}, ${dz}], center = true);`;
}

/**
 * Projects a TOPAS / GATE geometry hierarchy into OpenSCAD (.scad) 3D CSG code.
 */
export function topasToScad(doc: TopasDocument): string {
  const lines: string[] = [
    "// Generated by @modelscript/topas — OpenSCAD Treatment Nozzle & Phantom Geometry",
    "$fn = 64;",
    "",
  ];

  for (const comp of doc.components) {
    const tx = comp.transX ?? 0;
    const ty = comp.transY ?? 0;
    const tz = comp.transZ ?? 0;
    const rx = comp.rotX ?? 0;
    const ry = comp.rotY ?? 0;
    const rz = comp.rotZ ?? 0;
    const col = materialColor(comp.material);
    const prim = renderScadPrimitive(comp);

    lines.push(
      `// Component: ${comp.name} (Type: ${comp.type}, Parent: ${comp.parent ?? "World"}, Material: ${comp.material ?? "G4_AIR"})`,
    );
    lines.push(`module Ge_${comp.name.replace(/[^a-zA-Z0-9_]/g, "_")}() {`);
    lines.push(`  translate([${tx}, ${ty}, ${tz}])`);
    lines.push(`    rotate([${rx}, ${ry}, ${rz}])`);
    lines.push(`      color(${col})`);
    lines.push(`        ${prim}`);
    lines.push("}");
    lines.push(`Ge_${comp.name.replace(/[^a-zA-Z0-9_]/g, "_")}();`);
    lines.push("");
  }

  return lines.join("\n");
}

/**
 * Projects a TOPAS / GATE simulation model into a parameterized Modelica 3.x hadrontherapy model.
 */
export function topasToModelica(doc: TopasDocument, modelName = "TopasHadrontherapyModel"): string {
  const safeModelName = modelName.replace(/[^a-zA-Z0-9_]/g, "_");
  const lines: string[] = [
    `model ${safeModelName}`,
    `  "Generated by @modelscript/topas — Proton/Ion Bragg Peak & Dosimetry Model"`,
    "",
    "  // --- Geometry Parameters ---",
  ];

  for (const comp of doc.components) {
    const base = comp.name.replace(/[^a-zA-Z0-9_]/g, "_");
    const hlx = comp.hlx ?? comp.rMax ?? 10.0;
    const hly = comp.hly ?? comp.rMax ?? 10.0;
    const hlz = comp.hlz ?? comp.hl ?? comp.rMax ?? 10.0;
    lines.push(`  parameter Real ${base}_HLX(unit="mm") = ${hlx};`);
    lines.push(`  parameter Real ${base}_HLY(unit="mm") = ${hly};`);
    lines.push(`  parameter Real ${base}_HLZ(unit="mm") = ${hlz};`);
  }

  lines.push("");
  lines.push("  // --- Beam Source & Bragg Peak Parameters ---");
  const sources =
    doc.sources.length > 0
      ? doc.sources
      : [
          {
            name: "ProtonBeam",
            type: "Beam",
            beamParticle: "proton",
            beamEnergy: 150.0,
            beamEnergySpread: 0.5,
            range: doc.range,
          },
        ];

  const eqLines: string[] = [];
  for (const src of sources) {
    const base = src.name.replace(/[^a-zA-Z0-9_]/g, "_");
    const E0 = src.beamEnergy && src.beamEnergy > 0 ? src.beamEnergy : 150.0;
    const spread = src.beamEnergySpread && src.beamEnergySpread >= 0 ? src.beamEnergySpread : 0.5;
    const bragg = computeBraggPeakDepthDose({
      energyMeV: E0,
      energySpreadPercent: spread,
      particle: src.beamParticle,
    });

    lines.push(`  parameter Real ${base}_BeamEnergy(unit="MeV") = ${E0};`);
    lines.push(`  parameter Real ${base}_BeamEnergySpread(unit="%") = ${spread};`);
    lines.push(`  parameter Real ${base}_Alpha(unit="mm/MeV^p") = ${bragg.alphaMm};`);
    lines.push(`  parameter Real ${base}_ExponentP = ${bragg.exponentP};`);
    lines.push(`  Real ${base}_BraggRange(unit="mm");`);
    lines.push(`  Real ${base}_DistalR80(unit="mm");`);
    lines.push(`  Real ${base}_PeakToEntranceRatio;`);

    eqLines.push(`  ${base}_BraggRange = ${base}_Alpha * (${base}_BeamEnergy ^ ${base}_ExponentP);`);
    eqLines.push(`  ${base}_DistalR80 = ${bragg.distal80DepthMm};`);
    eqLines.push(`  ${base}_PeakToEntranceRatio = ${bragg.peakToEntranceRatio};`);
  }

  lines.push("");
  lines.push("equation");
  for (const eq of eqLines) {
    lines.push(eq);
  }
  lines.push(`end ${safeModelName};`);
  return lines.join("\n");
}
