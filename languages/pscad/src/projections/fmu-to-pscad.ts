/**
 * FMI to PSCAD Projection Generator.
 *
 * Automatically synthesizes:
 * 1. PSCAD v4/v5 `<User classid="UserCmp">` XML component definition with graphical canvas pins.
 * 2. Fortran companion subroutine binding PSCAD Dommel EMT node voltages and branch currents
 *    to FMI 2.0 / 3.0 C stepping functions (`fmi2SetReal`, `fmi2DoStep`, `fmi2GetReal`).
 */

export interface FmuVariableStub {
  name: string;
  causality: "input" | "output" | "parameter" | "calculatedParameter" | "local" | "independent" | string;
  type: string;
  valueReference: number;
  unit?: string | undefined;
  start?: number | string | boolean | undefined;
  description?: string | undefined;
}

export interface FmuModelStub {
  modelName: string;
  description?: string | undefined;
  guid?: string | undefined;
  fmiVersion?: string | undefined;
  variables: FmuVariableStub[];
}

export interface PscadProjectionResult {
  componentName: string;
  pscxXml: string;
  fortranGlue: string;
  inputPins: string[];
  outputPins: string[];
  parameterCount: number;
}

export function fmuToPscad(model: FmuModelStub): PscadProjectionResult {
  const compName = sanitizePscadIdent(model.modelName);
  const inputs = model.variables.filter((v) => v.causality === "input");
  const outputs = model.variables.filter((v) => v.causality === "output");
  const parameters = model.variables.filter(
    (v) => v.causality === "parameter" || v.causality === "calculatedParameter",
  );

  const inputPins = inputs.map((v) => sanitizePscadIdent(v.name));
  const outputPins = outputs.map((v) => sanitizePscadIdent(v.name));

  // 1. Generate PSCAD <User classid="UserCmp"> XML
  const xmlLines: string[] = [];
  xmlLines.push(`  <User classid="UserCmp" defn="${compName}" id="${compName}_inst">`);
  xmlLines.push(`    <description>${model.description ?? `FMU blackbox adapter for ${model.modelName}`}</description>`);
  xmlLines.push(`    <param name="fmu_guid" value="${model.guid ?? "{00000000-0000-0000-0000-000000000000}"}" />`);
  xmlLines.push(`    <param name="fmu_version" value="${model.fmiVersion ?? "2.0"}" />`);

  // Parameters
  for (const p of parameters) {
    const pName = sanitizePscadIdent(p.name);
    const pVal = p.start !== undefined ? String(p.start) : "0.0";
    xmlLines.push(`    <param name="${pName}" value="${pVal}" />`);
  }

  // Graphical Canvas Pins
  xmlLines.push(`    <graphics>`);
  xmlLines.push(`      <rect left="-40" top="-40" right="40" bottom="40" color="Navy" fill="LightBlue" />`);
  xmlLines.push(`      <text x="0" y="0" align="center" text="${compName}" />`);

  // Left side input pins
  let pinY = -20;
  for (const inp of inputs) {
    const pinName = sanitizePscadIdent(inp.name);
    xmlLines.push(`      <port name="${pinName}" type="in" x="-40" y="${pinY}" />`);
    pinY += 20;
  }

  // Right side output pins
  pinY = -20;
  for (const out of outputs) {
    const pinName = sanitizePscadIdent(out.name);
    xmlLines.push(`      <port name="${pinName}" type="out" x="40" y="${pinY}" />`);
    pinY += 20;
  }

  xmlLines.push(`    </graphics>`);
  xmlLines.push(`  </User>`);

  // 2. Generate Fortran Companion Subroutine
  const fLines: string[] = [];
  fLines.push(`! ==============================================================================`);
  fLines.push(`! Auto-generated by ModelScript — PSCAD EMT Companion Subroutine`);
  fLines.push(`! Model: ${model.modelName} (FMI ${model.fmiVersion ?? "2.0"})`);
  fLines.push(`! ==============================================================================`);
  fLines.push(`      SUBROUTINE ${compName}_STEP(TIME, DELT, &`);
  fLines.push(`                                  ${inputPins.join(", ")}, &`);
  fLines.push(`                                  ${outputPins.join(", ")})`);
  fLines.push(`      IMPLICIT NONE`);
  fLines.push(`      DOUBLE PRECISION, INTENT(IN)  :: TIME, DELT`);
  for (const inp of inputPins) {
    fLines.push(`      DOUBLE PRECISION, INTENT(IN)  :: ${inp}`);
  }
  for (const out of outputPins) {
    fLines.push(`      DOUBLE PRECISION, INTENT(OUT) :: ${out}`);
  }
  fLines.push(``);
  fLines.push(`      ! Internal FMI C-bridge call interface`);
  fLines.push(`      INTERFACE`);
  fLines.push(`        SUBROUTINE C_FMU_STEP(TIME, DELT, IN_VALS, OUT_VALS) BIND(C, NAME="${compName}_c_step")`);
  fLines.push(`          USE, INTRINSIC :: ISO_C_BINDING`);
  fLines.push(`          REAL(C_DOUBLE), VALUE :: TIME, DELT`);
  fLines.push(`          REAL(C_DOUBLE), DIMENSION(*) :: IN_VALS, OUT_VALS`);
  fLines.push(`        END SUBROUTINE C_FMU_STEP`);
  fLines.push(`      END INTERFACE`);
  fLines.push(``);
  fLines.push(`      REAL(8) :: IN_ARR(${Math.max(1, inputs.length)})`);
  fLines.push(`      REAL(8) :: OUT_ARR(${Math.max(1, outputs.length)})`);
  fLines.push(``);

  // Pack inputs
  inputs.forEach((inp, idx) => {
    fLines.push(`      IN_ARR(${idx + 1}) = ${sanitizePscadIdent(inp.name)}`);
  });

  fLines.push(`      CALL C_FMU_STEP(TIME, DELT, IN_ARR, OUT_ARR)`);

  // Unpack outputs
  outputs.forEach((out, idx) => {
    fLines.push(`      ${sanitizePscadIdent(out.name)} = OUT_ARR(${idx + 1})`);
  });

  fLines.push(`      END SUBROUTINE ${compName}_STEP`);

  return {
    componentName: compName,
    pscxXml: xmlLines.join("\n"),
    fortranGlue: fLines.join("\n"),
    inputPins,
    outputPins,
    parameterCount: parameters.length,
  };
}

function sanitizePscadIdent(name: string): string {
  return name.replace(/[^A-Za-z0-9_]/g, "_").replace(/^([0-9])/, "_$1");
}
