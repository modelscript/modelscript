import fs from "node:fs";
import path from "node:path";
import { writeFormattedTsIfChanged } from "../../../scripts/build/build-cleanroom-stdlib.js";
import { runLanguageWasmBuild } from "../../../scripts/build/build-language-wasm.js";

const pscadDir = new URL("..", import.meta.url).pathname;

runLanguageWasmBuild({
  langName: "pscad",
  dir: pscadDir,
  entryFile: "assembly/psout.ts",
  outWasmFile: "dist/psout.wasm",
});

// Option B: Build @modelscript/pscad-master-lib/dist from src/
const masterLibDir = path.join(pscadDir, "assets", "pscad-master-lib");
const masterLibSrc = path.join(masterLibDir, "src");
const masterLibDist = path.join(masterLibDir, "dist");
fs.mkdirSync(masterLibDist, { recursive: true });
for (const file of ["symbols.json", "diagrams.json"]) {
  const srcFile = path.join(masterLibSrc, file);
  if (fs.existsSync(srcFile)) {
    fs.copyFileSync(srcFile, path.join(masterLibDist, file));
  }
}

// Emit browser-safe TypeScript bundle so @modelscript/pscad-master-lib loads in browser/Ansatz without node:fs
const pkgJsonPath = path.join(masterLibDir, "package.json");
const symbolsPath = path.join(masterLibSrc, "symbols.json");
const diagramsPath = path.join(masterLibSrc, "diagrams.json");
const defaultPkgJsonText = JSON.stringify(
  {
    name: "@modelscript/pscad-master-lib",
    version: "0.1.0",
    type: "module",
    license: "AGPL-3.0-or-later",
    modelscript: {
      category: "library",
      language: "pscad",
      symbols: "./dist/symbols.json",
      diagrams: "./dist/diagrams.json",
      runtime: { wasm: "./dist/runtime.wasm" },
    },
  },
  null,
  2,
);
if (fs.existsSync(symbolsPath) && fs.existsSync(diagramsPath)) {
  const pkgJsonText = fs.existsSync(pkgJsonPath) ? fs.readFileSync(pkgJsonPath, "utf-8").trim() : defaultPkgJsonText;
  const catalogSrcDir = path.join(pscadDir, "src", "catalog");
  const catalogDistDir = path.join(pscadDir, "dist", "src", "catalog");
  fs.mkdirSync(catalogDistDir, { recursive: true });
  for (const [srcFile, destName] of [
    [symbolsPath, "pscad-master-lib-symbols.json"],
    [diagramsPath, "pscad-master-lib-diagrams.json"],
  ]) {
    fs.copyFileSync(srcFile, path.join(catalogSrcDir, destName));
    fs.copyFileSync(srcFile, path.join(catalogDistDir, destName));
  }
  const outTsPath = path.join(catalogSrcDir, "pscad-master-lib-data.ts");
  const banner = [
    "// SPDX-License-Identifier: AGPL-3.0-or-later",
    "// AUTO-GENERATED by languages/pscad/scripts/build-wasm.js — do not edit manually.",
    "",
    'import type { DiagramComponentSpec, LibrarySymbolStub, ModelscriptLibraryManifest } from "@modelscript/runtime";',
    'import rawDiagrams from "./pscad-master-lib-diagrams.json" with { type: "json" };',
    'import rawSymbols from "./pscad-master-lib-symbols.json" with { type: "json" };',
    "",
    `export const PSCAD_MASTER_LIB_PKG_JSON = ${pkgJsonText} as {`,
    "  name: string;",
    "  version: string;",
    "  license: string;",
    "  modelscript: ModelscriptLibraryManifest;",
    "};",
    "",
    "export const PSCAD_MASTER_LIB_SYMBOLS: LibrarySymbolStub[] = rawSymbols;",
    "",
    "export const PSCAD_MASTER_LIB_DIAGRAMS: DiagramComponentSpec[] = rawDiagrams;",
    "",
  ].join("\n");
  await writeFormattedTsIfChanged(outTsPath, banner);
}

runLanguageWasmBuild({
  langName: "pscad-master-lib",
  dir: masterLibDir,
  entryFile: "src/companions.ts",
  outWasmFile: "dist/runtime.wasm",
});
