import fs from "node:fs";
import path from "node:path";
import { runLanguageWasmBuild } from "../../../scripts/build-language-wasm.js";

const pscadDir = new URL("..", import.meta.url).pathname;

runLanguageWasmBuild({
  langName: "pscad",
  dir: pscadDir,
  entryFile: "assembly/psout.ts",
  outWasmFile: "dist/psout.wasm",
});

// Option B: Build @modelscript/pscad-master-lib/dist from src/
const masterLibDir = path.join(pscadDir, "assets", "pscad-master-lib");
const masterLibSrc = path.join(masterLibDir, "src");
const masterLibDist = path.join(masterLibDir, "dist");
fs.mkdirSync(masterLibDist, { recursive: true });
for (const file of ["symbols.json", "diagrams.json"]) {
  const srcFile = path.join(masterLibSrc, file);
  if (fs.existsSync(srcFile)) {
    fs.copyFileSync(srcFile, path.join(masterLibDist, file));
  }
}

// Emit browser-safe TypeScript bundle so @modelscript/pscad-master-lib loads in browser/Morsel without node:fs
const pkgJsonPath = path.join(masterLibDir, "package.json");
const symbolsPath = path.join(masterLibSrc, "symbols.json");
const diagramsPath = path.join(masterLibSrc, "diagrams.json");
if (fs.existsSync(pkgJsonPath) && fs.existsSync(symbolsPath) && fs.existsSync(diagramsPath)) {
  const pkgJsonText = fs.readFileSync(pkgJsonPath, "utf-8").trim();
  const symbolsText = fs.readFileSync(symbolsPath, "utf-8").trim();
  const diagramsText = fs.readFileSync(diagramsPath, "utf-8").trim();
  const outTsPath = path.join(pscadDir, "src", "catalog", "pscad-master-lib-data.ts");
  const banner = [
    "// SPDX-License-Identifier: AGPL-3.0-or-later",
    "// AUTO-GENERATED by languages/pscad/scripts/build-wasm.js — do not edit manually.",
    "",
    'import type { DiagramComponentSpec, LibrarySymbolStub, ModelscriptLibraryManifest } from "@modelscript/runtime";',
    "",
    `export const PSCAD_MASTER_LIB_PKG_JSON = ${pkgJsonText} as {`,
    "  name: string;",
    "  version: string;",
    "  license: string;",
    "  modelscript: ModelscriptLibraryManifest;",
    "};",
    "",
    `export const PSCAD_MASTER_LIB_SYMBOLS = ${symbolsText} as LibrarySymbolStub[];`,
    "",
    `export const PSCAD_MASTER_LIB_DIAGRAMS = ${diagramsText} as DiagramComponentSpec[];`,
    "",
  ].join("\n");
  if (!fs.existsSync(outTsPath) || fs.readFileSync(outTsPath, "utf-8") !== banner) {
    fs.writeFileSync(outTsPath, banner, "utf-8");
  }
}

runLanguageWasmBuild({
  langName: "pscad-master-lib",
  dir: masterLibDir,
  entryFile: "src/companions.ts",
  outWasmFile: "dist/runtime.wasm",
});
