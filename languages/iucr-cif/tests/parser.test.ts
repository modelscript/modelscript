import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { CANONICAL_CIF_TEMPLATES } from "../src/catalog/iucr-cif-std-schemas.js";
import { extractCrystalStructure, parseCifNumber, parseIucrCif } from "../src/parser/index.js";

describe("STAR / IUCr CIF 1.1 Parser", () => {
  it("parses numeric standard uncertainties accurately", () => {
    const n1 = parseCifNumber("5.4310(2)");
    assert.ok(n1);
    assert.equal(n1.value, 5.431);
    assert.ok(n1.su !== undefined && Math.abs(n1.su - 0.0002) < 1e-12);

    const n2 = parseCifNumber("1.23e-4(5)");
    assert.ok(n2);
    assert.ok(Math.abs(n2.value - 1.23e-4) < 1e-12);
    assert.ok(n2.su !== undefined && Math.abs(n2.su - 5e-6) < 1e-12);

    const n3 = parseCifNumber("90(1)");
    assert.ok(n3);
    assert.equal(n3.value, 90);
    assert.equal(n3.su, 1);

    assert.equal(parseCifNumber("?"), undefined);
    assert.equal(parseCifNumber("."), undefined);
  });

  it("parses data blocks, loops, comments, quoted strings, semicolon blocks, and ?/. values", () => {
    const src = `# Header comment
data_test_block
_publ_author_name 'O'Brien, J.'
_publ_section_title "Crystal Structure of SiO2"
_audit_creation_method
;
Generated by ModelScript
Multi-line semicolon text field
;
_cell_length_a 5.4310(2)
_cell_length_b 5.4310(2)
_cell_length_c 5.4310(2)
_cell_angle_alpha 90
_cell_angle_beta ?
_cell_angle_gamma .

loop_
_atom_site_label
_atom_site_type_symbol
_atom_site_fract_x
_atom_site_fract_y
_atom_site_fract_z
Si1 Si 0.0 0.0 0.0
`;

    const doc = parseIucrCif(src);
    assert.equal(doc.errors.length, 0);
    assert.equal(doc.comments.length, 1);
    assert.equal(doc.blocks.length, 1);

    const blk = doc.blocks[0]!;
    assert.equal(blk.name, "test_block");
    assert.equal(blk.tags.get("_publ_author_name")?.value.value, "O'Brien, J.");
    assert.equal(blk.tags.get("_publ_section_title")?.value.value, "Crystal Structure of SiO2");
    assert.ok(blk.tags.get("_audit_creation_method")?.value.value.includes("Multi-line semicolon text field"));
    assert.equal(blk.tags.get("_cell_angle_beta")?.value.kind, "unknown");
    assert.equal(blk.tags.get("_cell_angle_gamma")?.value.kind, "inapplicable");
    assert.equal(blk.loops.length, 1);
    assert.equal(blk.loops[0]!.tags.length, 5);
    assert.equal(blk.loops[0]!.rows.length, 1);
  });

  it("extracts canonical Silicon crystal structure with symmetry operations and atom sites", () => {
    const structure = extractCrystalStructure(CANONICAL_CIF_TEMPLATES.silicon);
    assert.ok(structure);
    assert.equal(structure.name, "silicon_fd3m");
    assert.equal(structure.cell.a, 5.431);
    assert.ok(structure.cell.aSu !== undefined && Math.abs(structure.cell.aSu - 0.0002) < 1e-12);
    assert.equal(structure.spaceGroupNumber, 227);
    assert.equal(structure.symmetryOps.length, 8);
    assert.equal(structure.asymmetricAtoms.length, 1);
    assert.equal(structure.asymmetricAtoms[0]!.symbol, "Si");
  });
});
