import type { BufrDescriptor, BufrTableBEntry, BufrTableDEntry } from "../types.js";

/**
 * Formats (F, X, Y) integers into canonical WMO BUFR descriptor string `F-XX-YYY`.
 */
export function formatBufrDescriptor(f: number, x: number, y: number): string {
  const xx = String(x).padStart(2, "0");
  const yyy = String(y).padStart(3, "0");
  return `${f}-${xx}-${yyy}`;
}

/**
 * Parses a BUFR descriptor string in `F-XX-YYY` or 6-digit `FXXYYY` form.
 */
export function parseBufrDescriptor(
  raw: string,
  line?: number,
  startOffset?: number,
  endOffset?: number,
): BufrDescriptor | null {
  const trimmed = raw.trim();
  let f: number;
  let x: number;
  let y: number;

  const hyphenMatch = /^(-?\d+)-(-?\d+)-(-?\d+)$/.exec(trimmed);
  if (hyphenMatch) {
    f = Number.parseInt(hyphenMatch[1]!, 10);
    x = Number.parseInt(hyphenMatch[2]!, 10);
    y = Number.parseInt(hyphenMatch[3]!, 10);
  } else if (/^\d{6}$/.test(trimmed)) {
    f = Number.parseInt(trimmed.slice(0, 1), 10);
    x = Number.parseInt(trimmed.slice(1, 3), 10);
    y = Number.parseInt(trimmed.slice(3, 6), 10);
  } else {
    return null;
  }

  return {
    f,
    x,
    y,
    code: f >= 0 && x >= 0 && y >= 0 ? formatBufrDescriptor(f, x, y) : trimmed,
    line,
    startOffset,
    endOffset,
  };
}

/**
 * Encodes a BUFR descriptor (F, X, Y) into its 16-bit WMO binary representation:
 * bits 15..14 = F (2 bits), bits 13..8 = X (6 bits), bits 7..0 = Y (8 bits).
 */
export function encodeDescriptor16(f: number, x: number, y: number): number {
  return ((f & 0x03) << 14) | ((x & 0x3f) << 8) | (y & 0xff);
}

/**
 * Decodes a 16-bit WMO binary descriptor into a `BufrDescriptor`.
 */
export function decodeDescriptor16(word: number): BufrDescriptor {
  const f = (word >>> 14) & 0x03;
  const x = (word >>> 8) & 0x3f;
  const y = word & 0xff;
  return { f, x, y, code: formatBufrDescriptor(f, x, y) };
}

