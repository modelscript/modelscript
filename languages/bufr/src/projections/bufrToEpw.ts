import { solveBufrMeteorology } from "../solver/meteo-qa.js";
import type { BufrMessage } from "../types.js";

/**
 * Projects a WMO BUFR meteorological report into an EnergyPlus Weather (EPW)
 * header and hourly observation snippet.
 */
export function bufrToEpw(message: BufrMessage): string {
  const sol = solveBufrMeteorology(message);
  const s1 = message.section1;
  const primary = sol.stations[0];

  const stnId = primary?.stationId ?? message.name ?? "BUFR_STN";
  const lat = primary?.latitude ?? 0.0;
  const lon = primary?.longitude ?? 0.0;
  const elev = primary?.elevationM ?? 0.0;
  const tz = Math.round(lon / 15);

  const lines: string[] = [
    `LOCATION,${stnId},NA,WMO,BUFR,${stnId},${lat.toFixed(4)},${lon.toFixed(4)},${tz.toFixed(1)},${elev.toFixed(1)}`,
    "DESIGN CONDITIONS,0",
    "TYPICAL/EXTREME PERIODS,0",
    "GROUND TEMPERATURES,0",
    "HOLIDAYS/DAYLIGHT SAVINGS,No,0,0,0",
    `COMMENTS 1,Generated by @modelscript/bufr from WMO BUFR Edition ${message.section0.edition}`,
    `COMMENTS 2,Originating centre ${s1.originatingCentre} | Master Table v${s1.masterTableVersion}`,
    `DATA PERIODS,1,1,Data,Sunday,${s1.month}/${s1.day},${s1.month}/${s1.day}`,
  ];

  const rows =
    sol.stations.length > 0
      ? sol.stations
      : [
          {
            stationId: stnId,
            timestampIso: "",
            surfacePressurePa: 101325,
            temperatureK: 288.15,
            dewpointK: 281.15,
            relativeHumidityPct: 63,
            windDirectionDeg: 0,
            windSpeedMs: 0,
            precipitationMm: 0,
          },
        ];

  for (let i = 0; i < rows.length; i++) {
    const st = rows[i]!;
    const dryBulbC = st.temperatureK !== undefined ? (st.temperatureK - 273.15).toFixed(1) : "99.9";
    const dewpointC = st.dewpointK !== undefined ? (st.dewpointK - 273.15).toFixed(1) : "99.9";
    const rh = st.relativeHumidityPct !== undefined ? Math.round(st.relativeHumidityPct).toString() : "999";
    const pressPa = st.surfacePressurePa !== undefined ? Math.round(st.surfacePressurePa).toString() : "999999";
    const wDir = st.windDirectionDeg !== undefined ? Math.round(st.windDirectionDeg).toString() : "999";
    const wSpd = st.windSpeedMs !== undefined ? st.windSpeedMs.toFixed(1) : "999.0";
    const precip = st.precipitationMm !== undefined ? st.precipitationMm.toFixed(1) : "0.0";
    const hour = Math.min(24, Math.max(1, s1.hour + i + 1));

    // Standard 35-column EnergyPlus EPW data line
    lines.push(
      [
        s1.year,
        s1.month,
        s1.day,
        hour,
        s1.minute,
        "?9?9?9?9E0?9?9?9?9?9?9?9?9?9?9?9?9?9?9?9*9*9?9?9",
        dryBulbC,
        dewpointC,
        rh,
        pressPa,
        "9999",
        "9999",
        "9999",
        "9999",
        "9999",
        "9999",
        "999999",
        "999999",
        "999999",
        "9999",
        wDir,
        wSpd,
        "5",
        "5",
        "999.9",
        "99999",
        "9",
        "999999999",
        "999",
        "0.999",
        "999",
        "99",
        "999",
        precip,
        "1",
      ].join(","),
    );
  }

  return lines.join("\n") + "\n";
}
