const ASCII_TO_EBCDIC = new Uint8Array(128).fill(0x40); // Default to EBCDIC space (0x40)
for (let ebcdic = 0; ebcdic < 256; ebcdic++) {
  const ascii = EBCDIC_TO_ASCII[ebcdic]!;
  if (ascii < 128 && (ascii !== 0x20 || ebcdic === 0x40)) {
    ASCII_TO_EBCDIC[ascii] = ebcdic;
  }
}
ASCII_TO_EBCDIC[0x20] = 0x40;

/**
 * Decodes an EBCDIC byte buffer to an ASCII string.
 */
export function ebcdicToAscii(bytes: Uint8Array): string {
  const chars = new Array<string>(bytes.length);
  for (let i = 0; i < bytes.length; i++) {
    chars[i] = String.fromCharCode(EBCDIC_TO_ASCII[bytes[i]!]!);
  }
  return chars.join("");
}

/**
 * Encodes an ASCII string to an EBCDIC byte buffer.
 */
export function asciiToEbcdic(text: string): Uint8Array {
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    out[i] = code < 128 ? ASCII_TO_EBCDIC[code]! : 0x40;
  }
  return out;
}

/**
 * Decodes an ASCII byte buffer to a string.
 */
export function asciiBytesToString(bytes: Uint8Array): string {
  const chars = new Array<string>(bytes.length);
  for (let i = 0; i < bytes.length; i++) {
    const b = bytes[i]!;
    chars[i] =
      b >= 0x20 && b <= 0x7e ? String.fromCharCode(b) : b === 0x0a || b === 0x0d ? String.fromCharCode(b) : " ";
  }
  return chars.join("");
}

/**
 * Encodes an ASCII string to a Uint8Array.
 */
export function stringToAsciiBytes(text: string): Uint8Array {
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    out[i] = code < 128 ? code : 0x20;
  }
  return out;
}

/**
 * Heuristically detects whether a 3200-byte SEG-Y textual reel header is EBCDIC or ASCII.
 */
export function detectTextualHeaderEncoding(bytes: Uint8Array): SegyTextEncoding {
  if (bytes.length === 0) return "ascii";
  // Check card 1 prefix 'C' (ASCII 0x43 vs EBCDIC 0xC3)
  if (bytes[0] === 0xc3) return "ebcdic";
  if (bytes[0] === 0x43) return "ascii";

  let asciiPrintable = 0;
  let ebcdicSpacesAndChars = 0;
  const n = Math.min(bytes.length, 3200);
  for (let i = 0; i < n; i++) {
    const b = bytes[i]!;
    if (b === 0x20 || (b >= 0x30 && b <= 0x7a)) {
      asciiPrintable++;
    }
    if (b === 0x40 || (b >= 0xc1 && b <= 0xf9)) {
      ebcdicSpacesAndChars++;
    }
  }
  return ebcdicSpacesAndChars > asciiPrintable ? "ebcdic" : "ascii";
}
