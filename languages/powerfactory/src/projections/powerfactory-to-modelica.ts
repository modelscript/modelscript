/**
 * Projection from DIgSILENT PowerFactory Model to OpenIPSL / Modelica 3.x Grid Model.
 *
 * Synthesizes an executable, equation-based Modelica class compatible with OpenIPSL,
 * declaring topological buses, transmission lines, transformers, generators, and loads.
 */

import { processPowerFactoryTopology } from "../topology/topology-processor.js";
import type { PowerFactoryModel } from "../types.js";

export interface PowerFactoryToModelicaOptions {
  modelName?: string | undefined;
  sbaseMva?: number | undefined;
}

/**
 * Projects a PowerFactoryModel into OpenIPSL Modelica 3.x code.
 */
export function powerFactoryToModelica(
  model: PowerFactoryModel,
  options: PowerFactoryToModelicaOptions = {},
): string {
  const modelName = (options.modelName || model.name || "PowerFactory_Grid").replace(/[^A-Za-z0-9_]/g, "_");
  const sbase = options.sbaseMva ?? 100.0;
  const topo = processPowerFactoryTopology(model, sbase);
  const { buses, termToBus, mappedLines, mappedTransformers, fnomHz } = topo;

  const lines: string[] = [
    `// SPDX-License-Identifier: AGPL-3.0-or-later`,
    `// Auto-generated by ModelScript @modelscript/powerfactory from DIgSILENT PowerFactory`,
    `model ${modelName}`,
    `  extends Modelica.Icons.Example;`,
    `  constant Real S_b = ${sbase.toFixed(1)}e6 "System Base MVA";`,
    `  constant Real fn = ${fnomHz.toFixed(1)} "Nominal Frequency Hz";`,
    ``,
    `  // ── Topological Buses ──`,
  ];

  for (const [bNum, bus] of buses) {
    const vNom = bus.baseKv * 1e3; // V
    lines.push(`  OpenIPSL.Electrical.Buses.Bus bus_${bNum}(V_nom = ${vNom.toFixed(1)});`);
  }

  lines.push(``, `  // ── Transmission Lines ──`);
  let lineIdx = 1;
  for (const mapped of mappedLines) {
    const vBase = (buses.get(mapped.fromBus)?.baseKv ?? 110.0) * 1e3;
    const zBase = (vBase * vBase) / (sbase * 1e6);
    const rPu = mapped.r1Ohm / zBase;
    const xPu = Math.max(1e-5, mapped.x1Ohm / zBase);
    const bPu = (mapped.b1USiemens * 1e-6) * zBase;

    lines.push(
      `  OpenIPSL.Electrical.Branches.Line line_${lineIdx}(` +
        `R = ${rPu.toExponential(4)}, ` +
        `X = ${xPu.toExponential(4)}, ` +
        `B = ${bPu.toExponential(4)});`,
    );
    lineIdx++;
  }

  lines.push(``, `  // ── Two-Winding Transformers ──`);
  let trIdx = 1;
  for (const mTr of mappedTransformers) {
    lines.push(
      `  OpenIPSL.Electrical.Branches.TwoWindingTransformer trafo_${trIdx}(` +
        `R = ${mTr.rPu.toExponential(4)}, ` +
        `X = ${mTr.xPu.toExponential(4)}, ` +
        `ratio = ${mTr.ratioPu.toFixed(4)});`,
    );
    trIdx++;
  }

  lines.push(``, `  // ── Synchronous Machines ──`);
  let genIdx = 1;
  for (const [, gen] of model.generators) {
    if (gen.outserv) continue;
    const bNum = termToBus.get(gen.bus1Id);
    if (bNum === undefined) continue;
    const type = gen.typId ? model.symTypes.get(gen.typId) : undefined;
    const snom = gen.sgini ?? type?.snom ?? 100.0;
    const pPu = gen.pgini / snom;
    const qPu = gen.qgini / snom;

    lines.push(
      `  OpenIPSL.Electrical.Machines.PSSE.GENSAL gen_${genIdx}(` +
        `M_b = ${snom.toFixed(1)}, ` +
        `P_0 = ${pPu.toFixed(4)}, ` +
        `Q_0 = ${qPu.toFixed(4)}, ` +
        `v_0 = ${gen.usetp.toFixed(4)});`,
    );
    genIdx++;
  }

  lines.push(``, `  // ── Loads ──`);
  let loadIdx = 1;
  for (const [, lod] of model.loads) {
    if (lod.outserv) continue;
    const bNum = termToBus.get(lod.bus1Id);
    if (bNum === undefined) continue;
    const pPu = lod.plini / sbase;
    const qPu = lod.qlini / sbase;

    lines.push(
      `  OpenIPSL.Electrical.Loads.PSSE.Load load_${loadIdx}(` +
        `P_0 = ${pPu.toFixed(4)}, ` +
        `Q_0 = ${qPu.toFixed(4)});`,
    );
    loadIdx++;
  }

  lines.push(``, `equation`);

  // Connect branches to buses
  lineIdx = 1;
  for (const mapped of mappedLines) {
    lines.push(`  connect(line_${lineIdx}.p, bus_${mapped.fromBus}.p);`);
    lines.push(`  connect(line_${lineIdx}.n, bus_${mapped.toBus}.p);`);
    lineIdx++;
  }

  trIdx = 1;
  for (const mTr of mappedTransformers) {
    lines.push(`  connect(trafo_${trIdx}.p, bus_${mTr.hvBus}.p);`);
    lines.push(`  connect(trafo_${trIdx}.n, bus_${mTr.lvBus}.p);`);
    trIdx++;
  }

  genIdx = 1;
  for (const [, gen] of model.generators) {
    if (gen.outserv) continue;
    const bNum = termToBus.get(gen.bus1Id);
    if (bNum === undefined) continue;
    lines.push(`  connect(gen_${genIdx}.p, bus_${bNum}.p);`);
    genIdx++;
  }

  loadIdx = 1;
  for (const [, lod] of model.loads) {
    if (lod.outserv) continue;
    const bNum = termToBus.get(lod.bus1Id);
    if (bNum === undefined) continue;
    lines.push(`  connect(load_${loadIdx}.p, bus_${bNum}.p);`);
    loadIdx++;
  }

  lines.push(`end ${modelName};`, ``);
  return lines.join("\n");
}
