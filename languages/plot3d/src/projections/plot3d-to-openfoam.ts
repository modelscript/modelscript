import { plot3dIndex, type Plot3dGrid } from "../types.js";

/**
 * Projects a PLOT3D multi-block structured grid into an OpenFOAM `blockMeshDict`
 * dictionary using each block's 8 corner vertices and structured cell counts.
 */
export function plot3dToOpenFoamBlockMesh(grid: Plot3dGrid, scale: number = 1.0): string {
  const lines: string[] = [
    "/*--------------------------------*- C++ -*----------------------------------*\\",
    "| =========                 |                                                 |",
    "| \\\\      /  F ield         | OpenFOAM: Projected from NASA PLOT3D Grid      |",
    "|  \\\\    /   O peration     | Generated by @modelscript/plot3d               |",
    "|   \\\\  /    A nd           |                                                 |",
    "|    \\\\/     M anipulation  |                                                 |",
    "\\*---------------------------------------------------------------------------*/",
    "FoamFile",
    "{",
    "    version     2.0;",
    "    format      ascii;",
    "    class       dictionary;",
    "    object      blockMeshDict;",
    "}",
    "",
    `scale ${scale};`,
    "",
    "vertices",
    "(",
  ];

  const blockEntries: string[] = [];
  const inletFaces: string[] = [];
  const outletFaces: string[] = [];
  const wallFaces: string[] = [];

  let vBase = 0;
  for (let bIdx = 0; bIdx < grid.blocks.length; bIdx++) {
    const b = grid.blocks[bIdx]!;
    const i1 = Math.max(0, b.ni - 1);
    const j1 = Math.max(0, b.nj - 1);
    const k1 = Math.max(0, b.nk - 1);

    // OpenFOAM hex vertex ordering:
    // 0:(0,0,0), 1:(i1,0,0), 2:(i1,j1,0), 3:(0,j1,0),
    // 4:(0,0,k1), 5:(i1,0,k1), 6:(i1,j1,k1), 7:(0,j1,k1)
    const corners: Array<[number, number, number]> = [
      [0, 0, 0],
      [i1, 0, 0],
      [i1, j1, 0],
      [0, j1, 0],
      [0, 0, k1],
      [i1, 0, k1],
      [i1, j1, k1],
      [0, j1, k1],
    ];

    for (let c = 0; c < corners.length; c++) {
      const [ci, cj, ck] = corners[c]!;
      const idx = plot3dIndex(ci, cj, ck, b.ni, b.nj);
      const x = b.x[idx] ?? 0;
      const y = b.y[idx] ?? 0;
      const z = grid.dimension === "3d" ? (b.z[idx] ?? 0) : c >= 4 ? 1.0 : 0.0;
      lines.push(`    (${x} ${y} ${z}) // block ${bIdx} v${vBase + c}`);
    }

    const nx = Math.max(1, b.ni - 1);
    const ny = Math.max(1, b.nj - 1);
    const nz = Math.max(1, b.nk - 1);
    const vIds = [0, 1, 2, 3, 4, 5, 6, 7].map((k) => vBase + k).join(" ");
    blockEntries.push(`    hex (${vIds}) (${nx} ${ny} ${nz}) simpleGrading (1 1 1)`);

    if (bIdx === 0) {
      inletFaces.push(`            (${vBase + 0} ${vBase + 4} ${vBase + 7} ${vBase + 3})`);
    }
    if (bIdx === grid.blocks.length - 1) {
      outletFaces.push(`            (${vBase + 1} ${vBase + 2} ${vBase + 6} ${vBase + 5})`);
    }
    wallFaces.push(`            (${vBase + 0} ${vBase + 1} ${vBase + 5} ${vBase + 4})`);
    wallFaces.push(`            (${vBase + 3} ${vBase + 7} ${vBase + 6} ${vBase + 2})`);

    vBase += 8;
  }

  lines.push(");");
  lines.push("");
  lines.push("blocks");
  lines.push("(");
  lines.push(...blockEntries);
  lines.push(");");
  lines.push("");
  lines.push("edges");
  lines.push("(");
  lines.push(");");
  lines.push("");
  lines.push("boundary");
  lines.push("(");
  lines.push("    inlet");
  lines.push("    {");
  lines.push("        type patch;");
  lines.push("        faces");
  lines.push("        (");
  lines.push(...inletFaces);
  lines.push("        );");
  lines.push("    }");
  lines.push("    outlet");
  lines.push("    {");
  lines.push("        type patch;");
  lines.push("        faces");
  lines.push("        (");
  lines.push(...outletFaces);
  lines.push("        );");
  lines.push("    }");
  lines.push("    walls");
  lines.push("    {");
  lines.push("        type wall;");
  lines.push("        faces");
  lines.push("        (");
  lines.push(...wallFaces);
  lines.push("        );");
  lines.push("    }");
  lines.push(");");
  lines.push("");
  lines.push("mergePatchPairs");
  lines.push("(");
  lines.push(");");

  return lines.join("\n") + "\n";
}
