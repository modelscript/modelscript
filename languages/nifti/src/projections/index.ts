/**
 * @modelscript/nifti — Cross-Domain CAD Projections to OpenSCAD (.scad) and ISO 10303-21 STEP (.stp).
 *
 * - `niftiToScad(doc, options)`: Projects extracted NIfTI/NRRD anatomical segmentation
 *   surface meshes to OpenSCAD `polyhedron(points = [...], faces = [...]);`.
 * - `niftiToStep(doc, options)`: Projects extracted NIfTI/NRRD RAS surface meshes to
 *   ISO 10303-21 STEP AP242 faceted B-Rep geometry (`CARTESIAN_POINT`, `POLY_LOOP`, `CLOSED_SHELL`).
 */

import { type ExtractIsoSurfaceOptions, extractIsoSurfaceMesh } from "../mesh/index.js";
import type { NiftiDocument } from "../types.js";

export function niftiToScad(doc: NiftiDocument, options?: ExtractIsoSurfaceOptions): string {
  const mesh = extractIsoSurfaceMesh(doc, options);
  const modName = sanitizeIdent(doc.title || "AnatomicalSegmentation");

  const lines: string[] = [];
  lines.push(`// Generated by @modelscript/nifti from ${doc.format.toUpperCase()} volume: ${doc.title}`);
  lines.push(
    `// Foreground voxels: ${mesh.foregroundVoxelCount}, Volume: ${mesh.totalVolumeMm3.toFixed(2)} mm^3, Surface Area: ${mesh.surfaceAreaMm2.toFixed(2)} mm^2`,
  );
  lines.push("");
  lines.push(`module ${modName}() {`);
  lines.push(`  polyhedron(`);
  lines.push(`    points = [`);
  for (let i = 0; i < mesh.verticesRAS.length; i++) {
    const v = mesh.verticesRAS[i]!;
    const comma = i + 1 < mesh.verticesRAS.length ? "," : "";
    lines.push(`      [${v[0].toFixed(4)}, ${v[1].toFixed(4)}, ${v[2].toFixed(4)}]${comma}`);
  }
  lines.push(`    ],`);
  lines.push(`    faces = [`);
  for (let i = 0; i < mesh.triangles.length; i++) {
    const t = mesh.triangles[i]!;
    const comma = i + 1 < mesh.triangles.length ? "," : "";
    lines.push(`      [${t[0]}, ${t[1]}, ${t[2]}]${comma}`);
  }
  lines.push(`    ],`);
  lines.push(`    convexity = 10`);
  lines.push(`  );`);
  lines.push(`}`);
  lines.push("");
  lines.push(`${modName}();`);

  return lines.join("\n");
}

export function niftiToStep(doc: NiftiDocument, options?: ExtractIsoSurfaceOptions): string {
  const mesh = extractIsoSurfaceMesh(doc, options);
  const partName = sanitizeIdent(doc.title || "NiftiAnatomicalMesh");

  const lines: string[] = [];
  lines.push(`ISO-10303-21;`);
  lines.push(`HEADER;`);
  lines.push(`FILE_DESCRIPTION(('NIfTI/NRRD Anatomical Segmentation B-Rep: ${partName}'),'2;1');`);
  lines.push(
    `FILE_NAME('${partName}.stp','2026-11-04T00:00:00',('ModelScript'),('ModelScript'),'','@modelscript/nifti','');`,
  );
  lines.push(`FILE_SCHEMA(('AUTOMOTIVE_DESIGN { 1 0 10303 214 1 1 1 1 }'));`);
  lines.push(`ENDSEC;`);
  lines.push(`DATA;`);

  let entityId = 1;
  const pointIds: number[] = [];
  const vertexIds: number[] = [];

  for (const v of mesh.verticesRAS) {
    const pId = entityId++;
    pointIds.push(pId);
    lines.push(`#${pId} = CARTESIAN_POINT('',(${v[0].toFixed(4)},${v[1].toFixed(4)},${v[2].toFixed(4)}));`);

    const vId = entityId++;
    vertexIds.push(vId);
    lines.push(`#${vId} = VERTEX_POINT('',#${pId});`);
  }

  const faceIds: number[] = [];
  const maxFaces = Math.min(mesh.triangles.length, 250);
  for (let i = 0; i < maxFaces; i++) {
    const tri = mesh.triangles[i]!;
    const vp0 = vertexIds[tri[0]] ?? 1;
    const vp1 = vertexIds[tri[1]] ?? 1;
    const vp2 = vertexIds[tri[2]] ?? 1;

    const loopId = entityId++;
    lines.push(`#${loopId} = POLY_LOOP('',(#${vp0},#${vp1},#${vp2}));`);

    const boundId = entityId++;
    lines.push(`#${boundId} = FACE_OUTER_BOUND('',#${loopId},.T.);`);

    const faceId = entityId++;
    faceIds.push(faceId);
    lines.push(`#${faceId} = FACE_SURFACE('',(#${boundId}),#${vp0},.T.);`);
  }

  const shellId = entityId++;
  const faceListStr = faceIds.map((id) => `#${id}`).join(",");
  lines.push(`#${shellId} = CLOSED_SHELL('${partName}_Shell',(${faceListStr}));`);

  const brepId = entityId++;
  lines.push(`#${brepId} = MANIFOLD_SOLID_BREP('${partName}',#${shellId});`);

  lines.push(`ENDSEC;`);
  lines.push(`END-ISO-10303-21;`);

  return lines.join("\n");
}

function sanitizeIdent(name: string): string {
  const cleaned = name.replace(/[^a-zA-Z0-9_]/g, "_");
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned || "NiftiMesh";
}
