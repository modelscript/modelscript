/**
 * @modelscript/endf6 — Polyglot Projections (MCNP Material Card, SCALE Composition, CSV).
 */

import type { Endf6Tape } from "../types.js";

export interface McnpMaterialProjectionOptions {
  /** Starting MCNP material number (default: `1`). */
  materialNumber?: number | undefined;
  /** ACE cross-section library suffix (default: `"80c"` for ENDF/B-VIII.0). */
  librarySuffix?: string | undefined;
  /** Whether to combine all ENDF materials into a single MCNP material card (default: `true`). */
  combineIntoSingleMaterial?: boolean | undefined;
}

export interface ScaleCompositionProjectionOptions {
  /** Starting SCALE mixture ID (default: `1`). */
  mixtureId?: number | undefined;
  /** Temperature in Kelvin (default: `293.6`). */
  temperatureK?: number | undefined;
  /** Atom density in atoms/(barn·cm) (default: `0.048`). */
  atomDensity?: number | undefined;
}

export interface CsvProjectionOptions {
  /** Optional filter of MT reaction numbers to include. */
  mts?: readonly number[] | undefined;
}

/**
 * Projects an `Endf6Tape` to an MCNP `Mn` material card block.
 */
export function endf6ToMcnpMaterial(tape: Endf6Tape, options?: McnpMaterialProjectionOptions): string {
  const matNum = options?.materialNumber ?? 1;
  const suffix = options?.librarySuffix ?? "80c";
  const combine = options?.combineIntoSingleMaterial ?? true;
  const mats = [...tape.materials.values()];

  const lines: string[] = [`c Generated by @modelscript/endf6${tape.tpid ? ` — ${tape.tpid}` : ""}`];

  if (mats.length === 0) {
    lines.push(`c (No materials present in ENDF-6 tape)`);
    return lines.join("\n") + "\n";
  }

  if (combine) {
    const frac = (1.0 / mats.length).toFixed(6);
    mats.forEach((m, idx) => {
      const zaid = `${Math.round(m.za)}.${suffix}`;
      const prefix = idx === 0 ? `M${matNum}` : "  ";
      lines.push(`${prefix}    ${zaid}  ${frac}  $ ${m.name} (MAT=${m.mat})`);
    });
  } else {
    mats.forEach((m, idx) => {
      const zaid = `${Math.round(m.za)}.${suffix}`;
      lines.push(`M${matNum + idx}    ${zaid}  1.000000  $ ${m.name} (MAT=${m.mat})`);
    });
  }

  return lines.join("\n") + "\n";
}

/**
 * Projects an `Endf6Tape` to a SCALE/KENO/ORIGAMI `read comp ... end comp` standard composition block.
 */
export function endf6ToScaleComposition(tape: Endf6Tape, options?: ScaleCompositionProjectionOptions): string {
  const mixId = options?.mixtureId ?? 1;
  const tempK = options?.temperatureK ?? 293.6;
  const atomDens = options?.atomDensity ?? 0.048;
  const mats = [...tape.materials.values()];

  const lines: string[] = [`' Generated by @modelscript/endf6${tape.tpid ? ` — ${tape.tpid}` : ""}`, "read comp"];

  mats.forEach((m, idx) => {
    const scaleNuclide = m.name.toLowerCase();
    const id = mixId + idx;
    lines.push(
      `  ${scaleNuclide} ${id} 0 ${atomDens.toExponential(4)} ${tempK.toFixed(1)} end ' MAT=${m.mat} ZA=${Math.round(m.za)}`,
    );
  });

  lines.push("end comp");
  return lines.join("\n") + "\n";
}

/**
 * Projects all `MF=3` pointwise cross-sections in an `Endf6Tape` to RFC-4180 CSV.
 */
export function endf6ToCsv(tape: Endf6Tape, options?: CsvProjectionOptions): string {
  const mtFilter = options?.mts ? new Set(options.mts) : null;
  const rows: string[] = ["mat,za,nuclide,mt,energy_eV,sigma_barns"];

  for (const mat of tape.materials.values()) {
    for (const xs of mat.crossSections.values()) {
      if (mtFilter && !mtFilter.has(xs.mt)) continue;
      for (const pt of xs.tab1.points) {
        rows.push(
          `${mat.mat},${Math.round(mat.za)},${mat.name},${xs.mt},${pt.x.toExponential(6)},${pt.y.toExponential(6)}`,
        );
      }
    }
  }

  return rows.join("\n") + "\n";
}
