/**
 * Multi-span optical transmission and Generalized OSNR (GSNR) solver.
 */

import type { OpticalChannel, OpticalTopology } from "../types.js";
import { computeAseNoisePowerWatts, computeSpanNli } from "./gn-model.js";

export interface ChannelTransmissionMetrics {
  channelId: string;
  totalLengthKm: number;
  totalSpanLossDb: number;
  totalAmpGainDb: number;
  totalAsePowerWatts: number;
  totalNliPowerWatts: number;
  accumulatedDispersionPsPerNm: number;
  accumulatedPmdPs: number;
  signalPowerEndWatts: number;
  osnrLinear: number;
  osnrDb: number;
  gsnrLinear: number;
  gsnrDb: number;
  osnrMarginDb: number;
  estimatedBer: number;
  estimatedQFactorDb: number;
}

export function solveChannelTransmission(topo: OpticalTopology, channel: OpticalChannel): ChannelTransmissionMetrics {
  const launchPowerWatts = Math.pow(10, (channel.launchPowerDbm - 30) / 10);
  let currentSignalWatts = launchPowerWatts;
  let totalAseWatts = 0.0;
  let totalNliWatts = 0.0;
  let totalLengthKm = 0.0;
  let totalLossDb = 0.0;
  let totalGainDb = 0.0;
  let totalDispersion = 0.0;
  let sumPmdSquared = 0.0;

  const wavelengthNm = (299792458 / (channel.centerFrequencyThz * 1e12)) * 1e9;

  for (const spanId of channel.pathSpanIds) {
    const span = topo.getSpan(spanId);
    if (!span) continue;

    totalLengthKm += span.lengthKm;
    const spanLossDb = span.lengthKm * span.attenuationDbPerKm;
    totalLossDb += spanLossDb;
    totalDispersion += span.dispersionPsPerNmKm * span.lengthKm;
    sumPmdSquared += Math.pow(span.pmdPsPerSqrtKm, 2) * span.lengthKm;

    // Attenuate signal across fiber span
    const spanLossLinear = Math.pow(10, -spanLossDb / 10);
    const spanInputSignalWatts = currentSignalWatts;

    // Compute NLI generated in this span
    const nli = computeSpanNli({
      lengthKm: span.lengthKm,
      attenuationDbPerKm: span.attenuationDbPerKm,
      dispersionPsPerNmKm: span.dispersionPsPerNmKm,
      nonLinearCoeffPerWKm: span.nonLinearCoeffPerWKm,
      wavelengthNm,
      baudRateGbaud: channel.baudRateGbaud,
      totalChannels: 40,
      channelSpacingGhz: 75.0,
    });
    const spanNliWatts = nli.nliPowerWatts(spanInputSignalWatts);

    // Signal at span end before amplifier
    currentSignalWatts *= spanLossLinear;

    // Propagate existing noise through span attenuation
    totalAseWatts *= spanLossLinear;
    totalNliWatts *= spanLossLinear;

    // Amplification at span end (EDFA)
    for (const amp of span.amplifiers) {
      const gLinear = Math.pow(10, amp.gainDb / 10);
      totalGainDb += amp.gainDb;
      currentSignalWatts *= gLinear;

      // Existing noise is amplified
      totalAseWatts *= gLinear;
      totalNliWatts *= gLinear;

      // Add new ASE noise generated by this amplifier
      const ase = computeAseNoisePowerWatts(amp.gainDb, amp.noiseFigureDb, channel.centerFrequencyThz);
      totalAseWatts += ase;
    }

    // Add NLI generated by this span (referenced to span output / amp output)
    totalNliWatts += spanNliWatts;
  }

  // OSNR = P_sig / P_ASE
  const osnrLinear = totalAseWatts > 0 ? currentSignalWatts / totalAseWatts : 1e9;
  const osnrDb = 10 * Math.log10(Math.max(1e-9, osnrLinear));

  // GSNR = P_sig / (P_ASE + P_NLI)
  const totalNoiseWatts = totalAseWatts + totalNliWatts;
  const gsnrLinear = totalNoiseWatts > 0 ? currentSignalWatts / totalNoiseWatts : 1e9;
  const gsnrDb = 10 * Math.log10(Math.max(1e-9, gsnrLinear));

  const osnrMarginDb = gsnrDb - channel.requiredOsnrDb;

  // Approximate BER for M-QAM:
  // For PM-QPSK: BER \approx 0.5 * erfc(sqrt(GSNR / 2))
  // For PM-16QAM: BER \approx (3/8) * erfc(sqrt(GSNR / 10))
  let snrFactor = 2.0;
  if (channel.modulation === "PM-16QAM") snrFactor = 10.0;
  else if (channel.modulation === "PM-64QAM") snrFactor = 42.0;

  const qLinear = Math.sqrt(Math.max(0, gsnrLinear / snrFactor));
  const estimatedBer = 0.5 * Math.exp(-Math.pow(qLinear, 2) / 2);
  const estimatedQFactorDb = 20 * Math.log10(Math.max(1e-3, qLinear * Math.SQRT2));

  return {
    channelId: channel.id,
    totalLengthKm,
    totalSpanLossDb: totalLossDb,
    totalAmpGainDb: totalGainDb,
    totalAsePowerWatts: totalAseWatts,
    totalNliPowerWatts: totalNliWatts,
    accumulatedDispersionPsPerNm: totalDispersion,
    accumulatedPmdPs: Math.sqrt(sumPmdSquared),
    signalPowerEndWatts: currentSignalWatts,
    osnrLinear,
    osnrDb,
    gsnrLinear,
    gsnrDb,
    osnrMarginDb,
    estimatedBer,
    estimatedQFactorDb,
  };
}
