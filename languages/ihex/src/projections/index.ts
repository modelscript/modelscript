/**
 * Polyglot Projections for `@modelscript/ihex`:
 * - Motorola S-Record (`ihexToSrec`)
 * - Verilog `$readmemh` `.mem` (`ihexToVerilogMem`)
 * - C `const uint8_t` byte array (`ihexToCArray`)
 */

import { hexByte, hexDword } from "../parser/index.js";
import { coalesceIhexMemoryMap, computeCrc32, toBinaryRomImage } from "../solver/index.js";
import type { IhexModel } from "../types.js";

function srecChecksum(bytes: readonly number[]): number {
  let sum = 0;
  for (let i = 0; i < bytes.length; i++) {
    sum = (sum + (bytes[i] ?? 0)) & 0xff;
  }
  return ~sum & 0xff;
}

function formatSrecLine(type: string, addrBytes: readonly number[], data: readonly number[]): string {
  const count = addrBytes.length + data.length + 1;
  const payload = [count, ...addrBytes, ...data];
  const cs = srecChecksum(payload);
  return `${type}${payload.map((b) => hexByte(b, true)).join("")}${hexByte(cs, true)}`;
}

export interface IhexToSrecOptions {
  /** Data bytes per S-Record line (default 16) */
  bytesPerLine?: number | undefined;
  /** S0 header string (default model name) */
  header?: string | undefined;
}

/**
 * Projects an `IhexModel` to Motorola S-Record format (`S0`, `S1`/`S2`/`S3`, `S5`, `S7`/`S8`/`S9`).
 */
export function ihexToSrec(model: IhexModel, options: IhexToSrecOptions = {}): string {
  const map = coalesceIhexMemoryMap(model);
  const bytesPerLine = Math.max(1, Math.min(250, Math.floor(options.bytesPerLine ?? 16)));
  const headerText = (options.header ?? model.name ?? "IHEX").slice(0, 32);

  const lines: string[] = [];

  // S0 header record
  const headerBytes: number[] = [];
  for (let i = 0; i < headerText.length; i++) {
    headerBytes.push(headerText.charCodeAt(i) & 0xff);
  }
  lines.push(formatSrecLine("S0", [0x00, 0x00], headerBytes));

  // Choose address width: 16-bit (S1/S9), 24-bit (S2/S8), or 32-bit (S3/S7)
  const maxEnd = Math.max(map.maxAddress, model.startLinearAddress ?? 0);
  const addrWidth = maxEnd > 0xffffff ? 4 : maxEnd > 0xffff ? 3 : 2;
  const dataType = addrWidth === 4 ? "S3" : addrWidth === 3 ? "S2" : "S1";
  const termType = addrWidth === 4 ? "S7" : addrWidth === 3 ? "S8" : "S9";

  const encodeAddr = (addr: number): number[] => {
    const u = addr >>> 0;
    if (addrWidth === 4) {
      return [(u >>> 24) & 0xff, (u >>> 16) & 0xff, (u >>> 8) & 0xff, u & 0xff];
    }
    if (addrWidth === 3) {
      return [(u >>> 16) & 0xff, (u >>> 8) & 0xff, u & 0xff];
    }
    return [(u >>> 8) & 0xff, u & 0xff];
  };

  let dataRecords = 0;
  for (const seg of map.segments) {
    for (let pos = 0; pos < seg.length; pos += bytesPerLine) {
      const len = Math.min(bytesPerLine, seg.length - pos);
      const slice: number[] = [];
      for (let i = 0; i < len; i++) {
        slice.push(seg.data[pos + i] ?? 0);
      }
      lines.push(formatSrecLine(dataType, encodeAddr(seg.startAddress + pos), slice));
      dataRecords += 1;
    }
  }

  // S5 record count (if <= 0xFFFF)
  if (dataRecords <= 0xffff) {
    lines.push(formatSrecLine("S5", [(dataRecords >>> 8) & 0xff, dataRecords & 0xff], []));
  }

  // Termination record with entry point if present
  const entryAddr =
    model.startLinearAddress ??
    (model.startSegmentAddress !== undefined
      ? ((model.startSegmentAddress.cs << 4) + model.startSegmentAddress.ip) >>> 0
      : map.minAddress);
  lines.push(formatSrecLine(termType, encodeAddr(entryAddr), []));

  return lines.join("\n") + "\n";
}

export interface IhexToVerilogMemOptions {
  /** Bytes per memory word (1 = byte, 2 = 16-bit, 4 = 32-bit; default 1) */
  wordWidthBytes?: 1 | 2 | 4 | undefined;
  /** Emit `@XXXXXXXX` address directives before each segment (default true) */
  includeAddresses?: boolean | undefined;
  /** Words per line (default 16) */
  wordsPerLine?: number | undefined;
}

/**
 * Projects an `IhexModel` to Verilog `$readmemh` `.mem` initialization format.
 */
export function ihexToVerilogMem(model: IhexModel, options: IhexToVerilogMemOptions = {}): string {
  const map = coalesceIhexMemoryMap(model);
  const wordWidth = options.wordWidthBytes ?? 1;
  const includeAddresses = options.includeAddresses ?? true;
  const wordsPerLine = Math.max(1, options.wordsPerLine ?? (wordWidth === 1 ? 16 : 8));

  const lines: string[] = [
    `// Generated by @modelscript/ihex from ${model.name} (${model.format})`,
    `// Segments: ${map.segments.length}, Total Data Bytes: ${map.totalDataBytes}`,
  ];

  for (const seg of map.segments) {
    if (includeAddresses) {
      const wordAddr = Math.floor(seg.startAddress / wordWidth) >>> 0;
      lines.push(`@${hexDword(wordAddr, true)}`);
    }
    const words: string[] = [];
    for (let pos = 0; pos < seg.length; pos += wordWidth) {
      let wordHex = "";
      // Little-endian word packing for multi-byte words (MSB first in hex token)
      for (let b = wordWidth - 1; b >= 0; b--) {
        const val = pos + b < seg.length ? (seg.data[pos + b] ?? 0xff) : 0xff;
        wordHex += hexByte(val, true);
      }
      words.push(wordHex);
    }

    for (let i = 0; i < words.length; i += wordsPerLine) {
      lines.push(words.slice(i, i + wordsPerLine).join(" "));
    }
  }

  return lines.join("\n") + "\n";
}

export interface IhexToCArrayOptions {
  /** C identifier name (default `"firmware_image"`) */
  symbolName?: string | undefined;
  /** Bytes per formatted line (default 12) */
  columns?: number | undefined;
  /** Fill byte for gaps (default `0xFF`) */
  fillByte?: number | undefined;
}

/**
 * Projects an `IhexModel` to a C `const uint8_t` byte array with base address and CRC-32 constants.
 */
export function ihexToCArray(model: IhexModel, options: IhexToCArrayOptions = {}): string {
  const fillByte = (options.fillByte ?? 0xff) & 0xff;
  const map = coalesceIhexMemoryMap(model, { fillByte });
  const image = toBinaryRomImage(map, fillByte);
  const crc = computeCrc32(image);
  const sym = (options.symbolName ?? "firmware_image").replace(/[^A-Za-z0-9_]/g, "_");
  const cols = Math.max(1, options.columns ?? 12);

  const lines: string[] = [
    `/* Generated by @modelscript/ihex from ${model.name} (${model.format}) */`,
    `#include <stddef.h>`,
    `#include <stdint.h>`,
    ``,
    `static const uint32_t ${sym}_base_address = 0x${hexDword(map.minAddress, true)}U;`,
    `static const uint32_t ${sym}_crc32 = 0x${hexDword(crc, true)}U;`,
    `static const size_t ${sym}_length = ${image.length}U;`,
    ``,
    `static const uint8_t ${sym}[${Math.max(1, image.length)}] = {`,
  ];

  if (image.length === 0) {
    lines.push("  0xFF");
  } else {
    for (let i = 0; i < image.length; i += cols) {
      const chunk: string[] = [];
      const end = Math.min(image.length, i + cols);
      for (let j = i; j < end; j++) {
        chunk.push(`0x${hexByte(image[j] ?? 0, true)}`);
      }
      const trailing = end < image.length ? "," : "";
      lines.push(`  ${chunk.join(", ")}${trailing}`);
    }
  }

  lines.push("};");
  return lines.join("\n") + "\n";
}
