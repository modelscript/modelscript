/**
 * @modelscript/ccsds — Projections to Modelica Astrodynamics Simulation Models.
 *
 * Translates CCSDS OEM, OPM, and OMM flight decks into continuous Modelica 3.x
 * orbital mechanics differential equations with WGS-84 geodetic parameters.
 */

import { keplerianToCartesian, MU_EARTH_KM, R_EARTH_KM } from "../astrodynamics/orbital-mechanics.js";
import type { CcsdsDocument } from "../types.js";

export function ccsdsToModelica(doc: CcsdsDocument): string {
  const modelName = (doc.format === "XTCE" ? doc.name : doc.metadata.objectName).replace(/[^a-zA-Z0-9_]/g, "_");
  const lines: string[] = [];

  lines.push(`model ${modelName}`);
  lines.push(`  // Auto-generated by ModelScript @modelscript/ccsds`);
  lines.push(`  // Standard: CCSDS 502.0-B-3 Spacecraft Astrodynamics`);
  lines.push("");

  // Determine initial conditions
  let initPos = [7000.0, 0.0, 0.0];
  let initVel = [0.0, 7.546, 0.0];

  if (doc.format === "OPM") {
    if (doc.stateVector.x !== 0 || doc.stateVector.y !== 0 || doc.stateVector.z !== 0) {
      initPos = [doc.stateVector.x, doc.stateVector.y, doc.stateVector.z];
      initVel = [doc.stateVector.vx, doc.stateVector.vy, doc.stateVector.vz];
    } else if (doc.keplerian) {
      const sv = keplerianToCartesian(doc.keplerian);
      initPos = [sv.x, sv.y, sv.z];
      initVel = [sv.vx, sv.vy, sv.vz];
    }
  } else if (doc.format === "OMM") {
    const sv = keplerianToCartesian(doc.meanElements);
    initPos = [sv.x, sv.y, sv.z];
    initVel = [sv.vx, sv.vy, sv.vz];
  } else if (doc.format === "OEM" && doc.points.length > 0) {
    const p0 = doc.points[0]!;
    initPos = [p0.x, p0.y, p0.z];
    initVel = [p0.vx, p0.vy, p0.vz];
  }

  let scMass = 500.0;
  let dragArea = 2.5;
  let dragCoeff = 2.2;
  if ("spacecraft" in doc && doc.spacecraft) {
    if (doc.spacecraft.massKg) scMass = doc.spacecraft.massKg;
    if (doc.spacecraft.dragAreaM2) dragArea = doc.spacecraft.dragAreaM2;
    if (doc.spacecraft.dragCoeff) dragCoeff = doc.spacecraft.dragCoeff;
  }

  // Parameters
  lines.push("  // Astrodynamic Gravitational and Planetary Parameters");
  lines.push(`  parameter Real mu = ${MU_EARTH_KM} "Earth gravitational parameter [km3/s2]";`);
  lines.push(`  parameter Real R_earth = ${R_EARTH_KM} "Earth mean equatorial radius [km]";`);
  lines.push(`  parameter Real mass = ${scMass.toFixed(1)} "Spacecraft wet mass [kg]";`);
  lines.push(`  parameter Real dragArea = ${dragArea.toFixed(2)} "Atmospheric drag reference area [m2]";`);
  lines.push(`  parameter Real dragCoeff = ${dragCoeff.toFixed(2)} "Drag coefficient Cd [-]";`);
  lines.push("");

  // Variables
  lines.push("  // Continuous 6-DOF Orbital State Variables (ECI / EME2000)");
  lines.push(`  Real x(start = ${initPos[0]!.toFixed(4)}, fixed = true) "ECI X position [km]";`);
  lines.push(`  Real y(start = ${initPos[1]!.toFixed(4)}, fixed = true) "ECI Y position [km]";`);
  lines.push(`  Real z(start = ${initPos[2]!.toFixed(4)}, fixed = true) "ECI Z position [km]";`);
  lines.push(`  Real vx(start = ${initVel[0]!.toFixed(4)}, fixed = true) "ECI X velocity [km/s]";`);
  lines.push(`  Real vy(start = ${initVel[1]!.toFixed(4)}, fixed = true) "ECI Y velocity [km/s]";`);
  lines.push(`  Real vz(start = ${initVel[2]!.toFixed(4)}, fixed = true) "ECI Z velocity [km/s]";`);
  lines.push("");
  lines.push("  // Auxiliary Orbital Trajectory Metrics");
  lines.push(`  Real r "Orbital radius [km]";`);
  lines.push(`  Real v "Orbital speed [km/s]";`);
  lines.push(`  Real altitude "Geodetic altitude above Earth [km]";`);
  lines.push(`  Real specificEnergy "Orbital mechanical energy [km2/s2]";`);
  lines.push("");

  // Equations
  lines.push("equation");
  lines.push("  // Kinematics");
  lines.push("  der(x) = vx;");
  lines.push("  der(y) = vy;");
  lines.push("  der(z) = vz;");
  lines.push("");
  lines.push("  // Geometrical Metrics");
  lines.push("  r = sqrt(x^2 + y^2 + z^2);");
  lines.push("  v = sqrt(vx^2 + vy^2 + vz^2);");
  lines.push("  altitude = r - R_earth;");
  lines.push("  specificEnergy = 0.5 * v^2 - mu / r;");
  lines.push("");
  lines.push("  // Dynamics (Two-Body Central Gravity)");
  lines.push("  der(vx) = -mu * x / (r^3);");
  lines.push("  der(vy) = -mu * y / (r^3);");
  lines.push("  der(vz) = -mu * z / (r^3);");
  lines.push(`end ${modelName};`);

  return lines.join("\n");
}
