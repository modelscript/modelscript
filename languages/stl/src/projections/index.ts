import { compileToStep } from "@modelscript/cad";
import { stlToCadSolid } from "../cad/index.js";
import { renderStlMeshSvg, type StlSvgOptions } from "../diagram/index.js";
import { weldStlMesh } from "../solver/index.js";
import type { StlMeshDocument } from "../types.js";

export interface StlObjOptions {
  name?: string | undefined;
  weldEpsilon?: number | undefined;
}

export interface StlStepOptions {
  name?: string | undefined;
  weldEpsilon?: number | undefined;
}

/**
 * Projects an STL mesh to Wavefront OBJ format with spatially welded vertices (`v`)
 * and 1-based triangular face indices (`f`).
 */
export function stlToObj(doc: StlMeshDocument, options?: StlObjOptions): string {
  const weldEps = options?.weldEpsilon ?? 1e-6;
  const { points, faces } = weldStlMesh(doc, weldEps);
  const name = (options?.name ?? doc.solids[0]?.name ?? doc.header ?? "stl_mesh").replace(/\s+/g, "_");

  const lines: string[] = [`# Generated by @modelscript/stl`, `o ${name}`];

  for (const p of points) {
    lines.push(`v ${p[0]} ${p[1]} ${p[2]}`);
  }
  for (const f of doc.facets) {
    lines.push(`vn ${f.normal[0]} ${f.normal[1]} ${f.normal[2]}`);
  }
  for (let i = 0; i < faces.length; i++) {
    const face = faces[i]!;
    const vnIdx = i + 1;
    lines.push(`f ${face[0] + 1}//${vnIdx} ${face[1] + 1}//${vnIdx} ${face[2] + 1}//${vnIdx}`);
  }

  return lines.join("\n") + "\n";
}

/**
 * Projects an STL mesh to ISO 10303-21 STEP AP214/AP242 via `@modelscript/cad` `PolyhedronSolid`.
 */
export function stlToStep(doc: StlMeshDocument, options?: StlStepOptions): string {
  const solid = stlToCadSolid(doc, {
    name: options?.name,
    weldEpsilon: options?.weldEpsilon,
  });
  return compileToStep(solid);
}

/**
 * Projects an STL mesh to an isometric or orthographic SVG rendering.
 */
export function stlToSvg(doc: StlMeshDocument, options?: StlSvgOptions): string {
  return renderStlMeshSvg(doc, options);
}
