import type { OlgaModel } from "../types.js";

/**
 * Projects an OLGA multiphase pipeline network into standard Modelica 3.x (Modelica.Fluid).
 */
export function olgaToModelica(model: OlgaModel): string {
  const modelName = (model.title || model.flowpaths[0]?.name || "OlgaPipeline").replace(/[^a-zA-Z0-9_]/g, "_");
  const lines: string[] = [
    `model ${modelName}`,
    `  // Generated by @modelscript/olga Modelica.Fluid projection`,
    `  extends Modelica.Icons.Example;`,
    ``,
  ];

  for (const fp of model.flowpaths) {
    lines.push(`  // Flowpath: ${fp.name}`);
    for (const pipe of fp.pipes) {
      const pLabel = pipe.label.replace(/[^a-zA-Z0-9_]/g, "_");
      lines.push(
        `  Modelica.Fluid.Pipes.DynamicPipe ${pLabel}(length = ${pipe.length}, diameter = ${pipe.diameter}, roughness = ${pipe.roughness}, nNodes = ${Math.max(2, pipe.discretization)});`,
      );
    }
    for (const valve of fp.valves) {
      const vName = valve.name.replace(/[^a-zA-Z0-9_]/g, "_");
      lines.push(`  Modelica.Fluid.Valves.ValveIncompressible ${vName}(opening = ${valve.opening});`);
    }
  }

  lines.push(``);
  lines.push(`  // Boundary Conditions`);
  for (const node of model.nodes) {
    const nName = node.name.replace(/[^a-zA-Z0-9_]/g, "_");
    if (node.type === "MASS_SOURCE") {
      lines.push(
        `  Modelica.Fluid.Sources.MassFlowSource_T ${nName}(m_flow = ${node.massRate ?? 25.0}, T = ${node.temperature ?? 345.15});`,
      );
    } else {
      lines.push(
        `  Modelica.Fluid.Sources.Boundary_pT ${nName}(p = ${node.pressure ?? 50.0e5}, T = ${node.temperature ?? 295.15});`,
      );
    }
  }

  lines.push(`equation`);
  lines.push(`end ${modelName};`);
  return lines.join("\n");
}
