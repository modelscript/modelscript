/**
 * @modelscript/olga — OLGA to SysML v2 Polyglot Projection.
 *
 * Translates OLGA .opi multiphase networks into formal SysML v2 packages,
 * projecting physical pipeline topologies into part definitions, flow assurance
 * constraints into requirements, and operational procedures into state machines.
 */

import type { FlowAssuranceLimits, OlgaModel } from "../types.js";

export interface Sysml2ProjectionOptions {
  packageName?: string | undefined;
  limits?: Partial<FlowAssuranceLimits> | undefined;
}

/**
 * Projects an OlgaModel into valid SysML v2 specification code.
 */
export function olgaToSysml2(model: OlgaModel, options?: Sysml2ProjectionOptions): string {
  const pkgName = options?.packageName ?? sanitizeIdentifier(model.title || "FlowlineSystem");
  const flowpath = model.flowpaths[0];

  let totalLength = 0;
  let totalElevation = 0;
  let nominalDiameter = 0.254;

  if (flowpath) {
    for (const p of flowpath.pipes) {
      totalLength += p.length;
      totalElevation += p.elevation;
      nominalDiameter = p.diameter;
    }
  }

  const maopBar = (options?.limits?.maop ?? 220e5) / 1e5;
  const hydrateMarginK = options?.limits?.hydrateMarginKelvin ?? 3.0;
  const slugCapacityM3 = options?.limits?.slugCatcherLiquidCapacity ?? 150.0;
  const minVelocityMs = options?.limits?.minGasVelocity ?? 2.5;

  const lines: string[] = [
    `// Auto-generated by @modelscript/olga from '${model.title}'`,
    `package ${pkgName} {`,
    `    import ScalarValues::*;`,
    `    import ISQ::*;`,
    ``,
    `    // ─────────────────────────────────────────────────────────────`,
    `    // 1. Port & Interface Definitions`,
    `    // ─────────────────────────────────────────────────────────────`,
    `    port def MultiphaseFluidPort {`,
    `        attribute pressure: Pressure;`,
    `        attribute temperature: Temperature;`,
    `        attribute massFlowRate: MassFlowRate;`,
    `        attribute liquidHoldup: Real;`,
    `    }`,
    ``,
    `    // ─────────────────────────────────────────────────────────────`,
    `    // 2. Physical Subsea Pipeline Architecture`,
    `    // ─────────────────────────────────────────────────────────────`,
    `    part def FlowlineRiserSystem {`,
    `        attribute totalLength: Length = ${totalLength.toFixed(1)} [m];`,
    `        attribute elevationDelta: Length = ${totalElevation.toFixed(1)} [m];`,
    `        attribute innerDiameter: Length = ${nominalDiameter.toFixed(4)} [m];`,
    ``,
    `        port wellheadInlet: MultiphaseFluidPort;`,
    `        port topsideArrival: MultiphaseFluidPort;`,
  ];

  if (flowpath) {
    for (const [idx, pipe] of flowpath.pipes.entries()) {
      lines.push(
        `        part pipe_${idx + 1} {`,
        `            attribute label: String = "${pipe.label}";`,
        `            attribute length: Length = ${pipe.length.toFixed(1)} [m];`,
        `            attribute diameter: Length = ${pipe.diameter.toFixed(4)} [m];`,
        `            attribute elevation: Length = ${pipe.elevation.toFixed(1)} [m];`,
        `        }`,
      );
    }

    for (const valve of flowpath.valves) {
      lines.push(
        `        part ${sanitizeIdentifier(valve.name)} {`,
        `            attribute position: Length = ${valve.position.toFixed(1)} [m];`,
        `            attribute openingFraction: Real = ${valve.opening.toFixed(2)};`,
        `            attribute throatDiameter: Length = ${valve.diameter.toFixed(4)} [m];`,
        `        }`,
      );
    }
  }

  lines.push(
    `    }`,
    ``,
    `    // ─────────────────────────────────────────────────────────────`,
    `    // 3. Flow Assurance Requirements (Verification Targets)`,
    `    // ─────────────────────────────────────────────────────────────`,
    `    requirement def HydrateAvoidanceRequirement {`,
    `        doc /* Flowline temperature must maintain at least ${hydrateMarginK} K subcooling margin above hydrate equilibrium */`,
    `        attribute operatingPressure: Pressure;`,
    `        attribute operatingTemperature: Temperature;`,
    `        attribute hydrateEquilibriumTemp: Temperature;`,
    `        attribute subcoolingMargin: Temperature = operatingTemperature - hydrateEquilibriumTemp;`,
    ``,
    `        assert constraint { subcoolingMargin >= ${hydrateMarginK} [K] }`,
    `    }`,
    ``,
    `    requirement def TopsideSlugCapacityRequirement {`,
    `        doc /* Transient arrival liquid surge volume must not exceed 85% of topside slug catcher buffer */`,
    `        attribute arrivalSurgeVolume: Volume;`,
    `        attribute slugCatcherCapacity: Volume = ${slugCapacityM3.toFixed(1)} [m^3];`,
    ``,
    `        assert constraint { arrivalSurgeVolume <= 0.85 * slugCatcherCapacity }`,
    `    }`,
    ``,
    `    requirement def PipelineMaopRequirement {`,
    `        doc /* Maximum transient pressure must not exceed pipeline MAOP */`,
    `        attribute peakPressure: Pressure;`,
    `        attribute maopLimit: Pressure = ${maopBar.toFixed(1)} [bar];`,
    ``,
    `        assert constraint { peakPressure <= maopLimit }`,
    `    }`,
    ``,
    `    requirement def MinimumTurndownVelocityRequirement {`,
    `        doc /* Gas superficial velocity must remain above critical droplet suspension threshold */`,
    `        attribute gasSuperficialVelocity: Speed;`,
    `        attribute criticalVelocity: Speed = ${minVelocityMs.toFixed(2)} [m/s];`,
    ``,
    `        assert constraint { gasSuperficialVelocity >= criticalVelocity }`,
    `    }`,
    ``,
    `    // ─────────────────────────────────────────────────────────────`,
    `    // 4. Operating Procedure State Machine (Safety & Transients)`,
    `    // ─────────────────────────────────────────────────────────────`,
    `    state def SubseaFlowlineOperatingProcedure {`,
    `        entry; then SteadyProduction;`,
    ``,
    `        state SteadyProduction {`,
    `            doc /* Normal continuous production at nominal design rates */`,
    `        }`,
    `        accept ESD_Trip_Signal then EmergencyShutIn;`,
    `        accept Turndown_Command then LowTurndown;`,
    ``,
    `        state LowTurndown {`,
    `            doc /* Reduced rate production with potential liquid accumulation */`,
    `        }`,
    `        accept Restore_Rate_Command then SteadyProduction;`,
    `        accept ESD_Trip_Signal then EmergencyShutIn;`,
    ``,
    `        state EmergencyShutIn {`,
    `            doc /* Valves closed, cooldown clock active */`,
    `        }`,
    `        accept Depressurize_Command when wallTemperature > 18.0 [degC] then ControlledBlowdown;`,
    `        accept Cooldown_Timeout when shutInDurationHours >= 8.0 [hr] then ChemicalInhibitionFlushing;`,
    ``,
    `        state ControlledBlowdown {`,
    `            doc /* Controlled flaring to depressurize below hydrate curve */`,
    `        }`,
    `        accept Depressurized_Done when systemPressure <= 15.0 [bar] then SafeDepressurized;`,
    ``,
    `        state ChemicalInhibitionFlushing {`,
    `            doc /* Subsea MEG / Methanol injection to prevent hydrate blockages */`,
    `        }`,
    `        accept Inhibition_Complete when inhibitorFraction >= 0.45 then WarmUpRestart;`,
    ``,
    `        state SafeDepressurized;`,
    `        state WarmUpRestart;`,
    `        accept Restart_Complete then SteadyProduction;`,
    `    }`,
    `}`,
  );

  return lines.join("\n");
}

function sanitizeIdentifier(name: string): string {
  const clean = name.replace(/[^A-Za-z0-9_]/g, "_");
  return /^[A-Za-z_]/.test(clean) ? clean : `_${clean}`;
}

export const projectOlgaToSysml2 = olgaToSysml2;
