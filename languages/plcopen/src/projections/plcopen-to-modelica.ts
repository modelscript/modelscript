/**
 * @modelscript/plcopen — Bidirectional Projections to Modelica 3.x.
 *
 * Translates IEC 61131-3 PLCopen POUs into canonical Modelica 3.x blocks:
 * - VAR_INPUT -> Modelica.Blocks.Interfaces.BooleanInput / RealInput
 * - VAR_OUTPUT -> Modelica.Blocks.Interfaces.BooleanOutput / RealOutput
 * - VAR -> Protected / Discrete internal variables
 * - Structured Text statements -> Modelica equation / algorithm sections
 */

import type { PlcExpr, PlcPou, PlcProject, PlcStatement, PlcVariable } from "../types.js";

export function plcopenToModelica(target: PlcPou | PlcProject): string {
  const pous = "pous" in target ? target.pous : [target];
  const pkgName = "pous" in target ? (target.contentHeader?.name ?? "PlcModels") : "PlcModels";

  const lines: string[] = [];
  lines.push(`package ${sanitizeIdent(pkgName)}`);
  lines.push(`  "Generated by ModelScript @modelscript/plcopen from IEC 61131-3 PLCopen"`);
  lines.push("");

  for (const pou of pous) {
    lines.push(pouToModelicaBlock(pou));
    lines.push("");
  }

  lines.push(`end ${sanitizeIdent(pkgName)};`);
  return lines.join("\n");
}

function pouToModelicaBlock(pou: PlcPou): string {
  const name = sanitizeIdent(pou.name);
  const lines: string[] = [];
  lines.push(`  block ${name}`);
  lines.push(`    "PLC POU: ${pou.name} (${pou.pouType})"`);

  const inputs = pou.variables.filter((v) => v.scope === "input");
  const outputs = pou.variables.filter((v) => v.scope === "output");
  const locals = pou.variables.filter((v) => v.scope !== "input" && v.scope !== "output");

  // 1. Inputs
  if (inputs.length > 0) {
    lines.push("    // Inputs");
    for (const inp of inputs) {
      lines.push(`    ${mapModelicaConnector(inp, true)} ${sanitizeIdent(inp.name)};`);
    }
  }

  // 2. Outputs
  if (outputs.length > 0) {
    lines.push("    // Outputs");
    for (const out of outputs) {
      lines.push(`    ${mapModelicaConnector(out, false)} ${sanitizeIdent(out.name)};`);
    }
  }

  // 3. Protected Variables
  if (locals.length > 0) {
    lines.push("  protected");
    for (const loc of locals) {
      lines.push(`    ${mapModelicaType(loc)} ${sanitizeIdent(loc.name)};`);
    }
  }

  // 4. Algorithm / Equation Section
  if (pou.body.kind === "ST" && pou.body.st && pou.body.st.statements.length > 0) {
    lines.push("  algorithm");
    for (const stmt of pou.body.st.statements) {
      lines.push(statementToModelica(stmt, 4));
    }
  }

  lines.push(`  end ${name};`);
  return lines.join("\n");
}

function mapModelicaConnector(v: PlcVariable, isInput: boolean): string {
  const dt = v.dataType.toUpperCase();
  if (dt === "BOOL") {
    return isInput ? "Modelica.Blocks.Interfaces.BooleanInput" : "Modelica.Blocks.Interfaces.BooleanOutput";
  }
  if (dt === "INT" || dt === "DINT") {
    return isInput ? "Modelica.Blocks.Interfaces.IntegerInput" : "Modelica.Blocks.Interfaces.IntegerOutput";
  }
  return isInput ? "Modelica.Blocks.Interfaces.RealInput" : "Modelica.Blocks.Interfaces.RealOutput";
}

function mapModelicaType(v: PlcVariable): string {
  const dt = v.dataType.toUpperCase();
  const prefix = v.isConstant ? "constant " : "";
  if (dt === "BOOL") return `${prefix}Boolean`;
  if (dt === "INT" || dt === "DINT") return `${prefix}Integer`;
  return `${prefix}Real`;
}

function statementToModelica(stmt: PlcStatement, indent: number): string {
  const pad = " ".repeat(indent);
  if (stmt.kind === "assignment") {
    const targetStr = exprToModelica(stmt.target);
    const valStr = exprToModelica(stmt.value);
    return `${pad}${targetStr} := ${valStr};`;
  }

  if (stmt.kind === "if") {
    const lines: string[] = [];
    lines.push(`${pad}if ${exprToModelica(stmt.condition)} then`);
    for (const s of stmt.thenStatements) {
      lines.push(statementToModelica(s, indent + 2));
    }
    for (const el of stmt.elsifs) {
      lines.push(`${pad}elseif ${exprToModelica(el.condition)} then`);
      for (const s of el.statements) {
        lines.push(statementToModelica(s, indent + 2));
      }
    }
    if (stmt.elseStatements.length > 0) {
      lines.push(`${pad}else`);
      for (const s of stmt.elseStatements) {
        lines.push(statementToModelica(s, indent + 2));
      }
    }
    lines.push(`${pad}end if;`);
    return lines.join("\n");
  }

  if (stmt.kind === "call") {
    const argList = stmt.args.map((a) => {
      if (a.name) return `${a.name} = ${exprToModelica(a.expr)}`;
      return exprToModelica(a.expr);
    });
    return `${pad}${stmt.callee}(${argList.join(", ")});`;
  }

  if (stmt.kind === "return") {
    return `${pad}return;`;
  }

  return "";
}

function exprToModelica(expr: PlcExpr): string {
  if (expr.kind === "literal") {
    if (expr.literalType === "bool") return expr.value ? "true" : "false";
    if (expr.literalType === "time") {
      const num = parseFloat(String(expr.value));
      return isNaN(num) ? "0.0" : num.toFixed(3);
    }
    if (typeof expr.value === "number") {
      return Number.isInteger(expr.value) ? `${expr.value}` : `${expr.value}`;
    }
    return String(expr.value);
  }

  if (expr.kind === "identifier") {
    return sanitizeIdent(expr.name);
  }

  if (expr.kind === "binary") {
    const op = expr.op.toLowerCase();
    const l = exprToModelica(expr.left);
    const r = exprToModelica(expr.right);
    if (op === "=") return `(${l} == ${r})`;
    if (op === "<>") return `(${l} <> ${r})`;
    return `(${l} ${op} ${r})`;
  }

  if (expr.kind === "unary") {
    const op = expr.op.toLowerCase();
    const arg = exprToModelica(expr.argument);
    return `(${op} ${arg})`;
  }

  if (expr.kind === "member") {
    return `${exprToModelica(expr.object)}.${sanitizeIdent(expr.property)}`;
  }

  return "0";
}

function sanitizeIdent(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, "_");
}
