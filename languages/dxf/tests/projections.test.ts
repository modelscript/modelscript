describe("DXF projections (SVG and STEP)", () => {
  it("projects multi-entity DXF with expanded INSERT blocks to standalone SVG", () => {
    const doc = parseDxf(PROJECTION_DXF);
    const svg = dxfToSvg(doc);

    assert.ok(svg.startsWith('<svg xmlns="http://www.w3.org/2000/svg" viewBox="'));
    assert.ok(svg.trimEnd().endsWith("</svg>"));

    // Layer groups with XML escaping
    assert.ok(svg.includes('<g data-layer="OUTLINE"'));
    assert.ok(svg.includes('<g data-layer="HOLES"'));
    assert.ok(svg.includes('<g data-layer="ANNOT &amp; &lt;NOTES&gt;"'));

    // ACI color resolution: layer OUTLINE (ACI 1 -> #ef4444), LINE override (ACI 3 -> #22c55e), HOLES (ACI 5 -> #3b82f6)
    assert.ok(svg.includes('stroke="#ef4444"'));
    assert.ok(svg.includes('stroke="#22c55e"'));
    assert.ok(svg.includes('stroke="#3b82f6"'));

    // Expanded INSERT block renders the CIRCLE at (15, -20) with r="4"
    assert.ok(svg.includes('<circle cx="15" cy="-20" r="4" stroke="#3b82f6"/>'));

    // Entity primitives: LINE, bulge LWPOLYLINE arc path, ELLIPSE/SPLINE paths, 3DFACE polygon, POLYLINE, POINT, escaped TEXT
    assert.ok(svg.includes('<line x1="0" y1="-20" x2="60" y2="-20" stroke="#22c55e"/>'));
    assert.ok(svg.includes(" A "));
    assert.ok(svg.includes('<polygon points="0,0 10,0 10,-10 0,-10"'));
    assert.ok(svg.includes('<polyline points="0,5 20,5"'));
    assert.ok(svg.includes(">Plate A &amp; &lt;B&gt;</text>"));
  });

  it("respects custom dxfToSvg options (background, padding, strokeWidth, defaultColor)", () => {
    const simpleDxf = [
      "0",
      "SECTION",
      "2",
      "ENTITIES",
      "0",
      "LINE",
      "8",
      "UNLISTED_LAYER",
      "10",
      "0",
      "20",
      "0",
      "30",
      "0",
      "11",
      "10",
      "21",
      "0",
      "31",
      "0",
      "0",
      "ENDSEC",
      "0",
      "EOF",
    ].join("\n");

    const doc = parseDxf(simpleDxf);
    const svg = dxfToSvg(doc, {
      background: "#ffffff",
      padding: 5,
      strokeWidth: 0.75,
      defaultColor: "#112233",
    });

    assert.ok(svg.includes('fill="#ffffff"'));
    assert.ok(svg.includes('stroke-width="0.75"'));
    assert.ok(svg.includes('stroke="#112233"'));
    assert.ok(svg.includes('viewBox="-5 -5 20 11"'));
  });

  it("projects DXF solids and expanded INSERT blocks to ISO 10303-21 STEP", () => {
    const doc = parseDxf(PROJECTION_DXF);
    const step = dxfToStep(doc, {
      assemblyName: "FlangePlateStep",
      extrusionHeight: 12,
      arcSegments: 24,
    });

    assert.ok(step.includes("ISO-10303-21;"));
    assert.ok(step.includes("HEADER;"));
    assert.ok(step.includes("DATA;"));
    assert.ok(step.includes("END-ISO-10303-21;"));
    assert.ok(
      step.includes("FlangePlateStep") || step.includes("MANIFOLD_SOLID_BREP") || step.includes("ADVANCED_FACE"),
    );
  });
});
