/**
 * PSS/E .dyr Dynamic Case Serializer and NERC MOD-026/027 Report Generator.
 *
 * Updates dynamic records with calibrated parameter values, writes canonical
 * PSS/E .dyr files, and generates audit-ready NERC validation reports.
 */

import type { DyrCalibrationReport } from "../calibration/dyr-calibrator.js";
import type { PsseDyrCase, PsseDyrRecord } from "../types.js";
import { DYR_MODEL_SCHEMAS } from "./dyr-parser.js";

/**
 * Updates a `PsseDyrRecord` with new parameter values, synchronizing both
 * `namedParams` and the positional `con` parameter array.
 */
export function updateDyrRecordParameters(
  rec: PsseDyrRecord,
  updates: Record<string, number>,
): PsseDyrRecord {
  const schema = DYR_MODEL_SCHEMAS[rec.model];
  const updatedCon = [...rec.con];
  const updatedNamed = { ...rec.namedParams, ...updates };

  if (schema) {
    for (let idx = 0; idx < schema.params.length; idx++) {
      const pMeta = schema.params[idx]!;
      if (updates[pMeta.name] !== undefined) {
        updatedCon[idx] = updates[pMeta.name]!;
      }
    }
  }

  return {
    ...rec,
    con: updatedCon,
    namedParams: updatedNamed,
  };
}

/**
 * Applies calibrated parameter updates from a `DyrCalibrationReport` to a `PsseDyrCase`.
 */
export function applyCalibrationToDyrCase(
  dyrCase: PsseDyrCase,
  report: DyrCalibrationReport,
): PsseDyrCase {
  // Group updates by target model category
  const genUpdates: Record<string, number> = {};
  const excUpdates: Record<string, number> = {};
  const govUpdates: Record<string, number> = {};

  for (const p of report.parameters) {
    if (p.targetModel === "generator") genUpdates[p.name] = p.calibratedValue;
    else if (p.targetModel === "exciter") excUpdates[p.name] = p.calibratedValue;
    else if (p.targetModel === "governor") govUpdates[p.name] = p.calibratedValue;
  }

  const updatedRecords = dyrCase.records.map((rec) => {
    const isTargetBus = rec.ibus === report.busNumber;
    const isTargetGen = isTargetBus && (rec.id.trim() === report.genId || rec.id.trim() === "");

    if (!isTargetBus) return rec;

    if (rec.category === "generator" && isTargetGen && Object.keys(genUpdates).length > 0) {
      return updateDyrRecordParameters(rec, genUpdates);
    }
    if (rec.category === "exciter" && (isTargetGen || !rec.id.trim()) && Object.keys(excUpdates).length > 0) {
      return updateDyrRecordParameters(rec, excUpdates);
    }
    if (rec.category === "governor" && (isTargetGen || !rec.id.trim()) && Object.keys(govUpdates).length > 0) {
      return updateDyrRecordParameters(rec, govUpdates);
    }
    return rec;
  });

  // Re-index updated maps
  const generatorsByBusId = new Map(dyrCase.generatorsByBusId);
  const excitersByBusId = new Map(dyrCase.excitersByBusId);
  const governorsByBusId = new Map(dyrCase.governorsByBusId);

  for (const rec of updatedRecords) {
    const key = `${rec.ibus}_${rec.id.trim()}`;
    if (rec.category === "generator") {
      generatorsByBusId.set(key, rec);
      generatorsByBusId.set(String(rec.ibus), rec);
    } else if (rec.category === "exciter") {
      excitersByBusId.set(key, rec);
      excitersByBusId.set(String(rec.ibus), rec);
    } else if (rec.category === "governor") {
      governorsByBusId.set(key, rec);
      governorsByBusId.set(String(rec.ibus), rec);
    }
  }

  return {
    ...dyrCase,
    records: updatedRecords,
    generatorsByBusId,
    excitersByBusId,
    governorsByBusId,
  };
}

/**
 * Serializes a `PsseDyrCase` to standard PSS/E `.dyr` file format.
 */
export function serializeDyrCase(
  dyrCase: PsseDyrCase,
  options: { includeComments?: boolean } = {},
): string {
  const lines: string[] = [];
  lines.push("// PSS/E Dynamic Simulation Data File (.dyr)");
  lines.push(`// Generated by ModelScript on ${new Date().toISOString()}`);
  lines.push("");

  for (const rec of dyrCase.records) {
    const paddedModel = `'${rec.model.trim().padEnd(6, " ")}'`;
    const idStr = `'${rec.id.trim() || "1"}'`;
    const schema = DYR_MODEL_SCHEMAS[rec.model];

    if (options.includeComments && schema) {
      lines.push(`// ${schema.title} (${schema.category})`);
    }

    // Format CON values: 6 per line with standard indentation
    const conFormatted = rec.con.map((v) => {
      if (Number.isInteger(v)) return v.toFixed(1);
      return Number(v.toPrecision(6)).toString();
    });

    if (conFormatted.length <= 6) {
      lines.push(`${rec.ibus} ${paddedModel} ${idStr} ${conFormatted.join(" ")} /`);
    } else {
      lines.push(`${rec.ibus} ${paddedModel} ${idStr}`);
      for (let i = 0; i < conFormatted.length; i += 6) {
        const chunk = conFormatted.slice(i, i + 6);
        const isLast = i + 6 >= conFormatted.length;
        lines.push(`     ${chunk.join(" ")}${isLast ? " /" : ""}`);
      }
    }
    lines.push("");
  }

  return lines.join("\n");
}

/**
 * Generates a formal NERC MOD-026-1 / MOD-027-1 Model Verification Markdown Report.
 */
export function generateNercMod026VerificationReport(report: DyrCalibrationReport): string {
  const statusBadge = report.isCompliant ? "**COMPLIANT (PASS)**" : "**NON-COMPLIANT (FAIL)**";
  const pInit = report.initialSimulation.pMetrics;
  const pCal = report.calibratedSimulation.pMetrics;
  const qInit = report.initialSimulation.qMetrics;
  const qCal = report.calibratedSimulation.qMetrics;

  const lines: string[] = [
    `# NERC MOD-026-1 / MOD-027-1 Dynamic Model Verification Report`,
    ``,
    `* **Timestamp:** ${report.timestamp}`,
    `* **Element Tested:** Generator Bus ${report.busNumber} (ID: '${report.genId}')`,
    `* **Generator Model:** \`${report.generatorModel}\``,
    `* **Excitation System:** \`${report.exciterModel ?? "N/A"}\``,
    `* **Turbine-Governor:** \`${report.governorModel ?? "N/A"}\``,
    `* **Overall Audit Status:** ${statusBadge}`,
    `* **Goodness-of-Fit Composite Score:** ${report.calibratedSimulation.overallScore.toFixed(1)} / 100`,
    `* **Calibration Improvement:** ${report.improvementPercent.toFixed(1)}% residual error reduction`,
    ``,
    `---`,
    ``,
    `## 1. Goodness-of-Fit Comparison vs. NERC Criteria`,
    ``,
    `| Metric | Active Power P(t) Pre | Active Power P(t) Calibrated | Reactive Power Q(t) Pre | Reactive Power Q(t) Calibrated | NERC Requirement | Verdict |`,
    `| :--- | :--- | :--- | :--- | :--- | :--- | :--- |`,
    `| **R² (Determination)** | ${pInit.rSquared.toFixed(3)} | **${pCal.rSquared.toFixed(3)}** | ${qInit.rSquared.toFixed(3)} | **${qCal.rSquared.toFixed(3)}** | $\\ge 0.85$ | ${pCal.rSquared >= 0.85 ? "PASS" : "FAIL"} |`,
    `| **NRMSE** | ${(pInit.nrmse * 100).toFixed(1)}% | **${(pCal.nrmse * 100).toFixed(1)}%** | ${(qInit.nrmse * 100).toFixed(1)}% | **${(qCal.nrmse * 100).toFixed(1)}%** | $\\le 10.0\\%$ | ${pCal.nrmse <= 0.10 ? "PASS" : "FAIL"} |`,
    `| **RMSE** | ${pInit.rmse.toFixed(2)} MW | **${pCal.rmse.toFixed(2)} MW** | ${qInit.rmse.toFixed(2)} Mvar | **${qCal.rmse.toFixed(2)} Mvar** | Minimizing | - |`,
    `| **Peak Error** | ${pInit.peakError.toFixed(2)} MW | **${pCal.peakError.toFixed(2)} MW** | ${qInit.peakError.toFixed(2)} Mvar | **${qCal.peakError.toFixed(2)} Mvar** | $\\le 15.0\\%$ | ${pCal.peakErrorPercent <= 15.0 ? "PASS" : "FAIL"} |`,
    ``,
    `---`,
    ``,
    `## 2. Dynamic Model Parameter Transition Table`,
    ``,
    `| Parameter | Target Subsystem | Prior / Initial | Calibrated | Change (%) | Allowable Bounds | Unit | Description |`,
    `| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |`,
  ];

  for (const p of report.parameters) {
    const sign = p.relativeChangePercent >= 0 ? "+" : "";
    lines.push(
      `| \`${p.name}\` | ${p.targetModel} | ${p.initialValue.toFixed(4)} | **${p.calibratedValue.toFixed(4)}** | ${sign}${p.relativeChangePercent.toFixed(1)}% | [${p.minValue}, ${p.maxValue}] | ${p.unit} | ${p.description} |`,
    );
  }

  lines.push(``);
  lines.push(`---`);
  lines.push(``);
  lines.push(`## 3. Engineering Verification Notes & Auditor Conclusions`);
  for (const note of report.notes) {
    lines.push(`* ${note}`);
  }
  lines.push(``);

  return lines.join("\n");
}
