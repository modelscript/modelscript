import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DYR_SCHEMA_LIST, resolveCanonicalDyrModelName } from "../src/schema/index.js";
import type { DyrHeaderKind, PsseDyrCategory } from "../src/types.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PSSE_DIR = path.resolve(__dirname, "..");

const CATEGORY_CODE: Record<PsseDyrCategory, number> = {
  generator: 0,
  exciter: 1,
  governor: 2,
  stabilizer: 3,
  load: 4,
  facts: 5,
  hvdc: 6,
  relay: 7,
  user: 8,
};

const HEADER_KIND_CODE: Record<DyrHeaderKind, number> = {
  machine: 0,
  bus: 1,
  load: 2,
  subsystem: 3,
  branch: 4,
  xfmr2w: 5,
  dc2t: 6,
  vscdc: 7,
  facts: 8,
  usrmdl: 9,
};

function fnv1aAsciiUpper(str: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    let c = str.charCodeAt(i);
    if (c >= 97 && c <= 122) c -= 32;
    h ^= c;
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

function writeIfChanged(filePath: string, content: string): boolean {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, "utf-8") === content) {
    return false;
  }
  fs.writeFileSync(filePath, content, "utf-8");
  return true;
}

function generateAssemblyModelTable(): string {
  const n = DYR_SCHEMA_LIST.length;
  // Next power of 2 >= 4 * n for <25% open-addressing load factor
  let cap = 256;
  while (cap < n * 4) cap <<= 1;

  const hashSlots = new Uint16Array(cap); // stores 1-based schemaId, 0 = empty
  const nameBytes: number[] = [];
  const nameOffs: number[] = [0]; // index 0 unused
  const nameLens: number[] = [0];
  const catCodes: number[] = [0];
  const hdrCodes: number[] = [0];
  const iconCounts: number[] = [0];
  const conCounts: number[] = [0];
  const canonicalIds: number[] = [0];

  const idByName = new Map<string, number>();
  for (let i = 0; i < n; i++) {
    idByName.set(DYR_SCHEMA_LIST[i]!.model.toUpperCase(), i + 1);
  }

  for (let i = 0; i < n; i++) {
    const s = DYR_SCHEMA_LIST[i]!;
    const upper = s.model.toUpperCase();
    const schemaId = i + 1;
    nameOffs.push(nameBytes.length);
    nameLens.push(upper.length);
    for (let k = 0; k < upper.length; k++) {
      nameBytes.push(upper.charCodeAt(k));
    }
    catCodes.push(CATEGORY_CODE[s.category] ?? 8);
    hdrCodes.push(HEADER_KIND_CODE[s.headerKind ?? "machine"] ?? 0);
    iconCounts.push(s.icons?.length ?? 0);
    conCounts.push(s.params.length);
    const canonName = resolveCanonicalDyrModelName(upper);
    canonicalIds.push(idByName.get(canonName) ?? schemaId);

    let slot = fnv1aAsciiUpper(upper) & (cap - 1);
    while (hashSlots[slot] !== 0) {
      slot = (slot + 1) & (cap - 1);
    }
    hashSlots[slot] = schemaId;
  }

  return `// SPDX-License-Identifier: AGPL-3.0-or-later
// AUTO-GENERATED by scripts/sync-dyr-schemas.ts — DO NOT EDIT BY HAND.

export const NUM_DYR_SCHEMAS: i32 = ${n};
export const SCHEMA_HASH_MASK: u32 = ${cap - 1};

export const SCHEMA_HASH_SLOTS: StaticArray<u16> = [${Array.from(hashSlots).join(",")}];
export const SCHEMA_NAME_BYTES: StaticArray<u8> = [${nameBytes.join(",")}];
export const SCHEMA_NAME_OFFSETS: StaticArray<u16> = [${nameOffs.join(",")}];
export const SCHEMA_NAME_LENS: StaticArray<u8> = [${nameLens.join(",")}];
export const SCHEMA_CATEGORIES: StaticArray<u8> = [${catCodes.join(",")}];
export const SCHEMA_HEADER_KINDS: StaticArray<u8> = [${hdrCodes.join(",")}];
export const SCHEMA_ICON_COUNTS: StaticArray<u8> = [${iconCounts.join(",")}];
export const SCHEMA_CON_COUNTS: StaticArray<u8> = [${conCounts.join(",")}];
export const SCHEMA_CANONICAL_IDS: StaticArray<u16> = [${canonicalIds.join(",")}];
`;
}

function domainForCategory(cat: PsseDyrCategory, sub?: string): string {
  if (cat === "generator" || cat === "load" || cat === "facts" || cat === "hvdc") {
    return sub === "ibr_converter" || sub === "ibr_gfm" ? "electrical" : "electrical";
  }
  if (cat === "governor") return "mechanical";
  return "control";
}

function exportsForSchema(cat: PsseDyrCategory, sub?: string): string[] {
  if (sub === "ibr_converter" || sub === "ibr_gfm") return ["Vterm", "Ip", "Iq"];
  switch (cat) {
    case "generator":
      return ["Efd", "Pmech", "Pe", "omega"];
    case "exciter":
      return ["Vterm", "Efd"];
    case "governor":
      return ["dOmega", "Pmech"];
    case "stabilizer":
      return ["dOmega", "Vs"];
    case "load":
      return ["Vterm", "Pload", "Qload"];
    case "facts":
      return ["Vterm", "Qinj"];
    case "hvdc":
      return ["Pdc", "Qdc"];
    case "relay":
      return ["Signal", "Trip"];
    default:
      return ["In", "Out"];
  }
}

function generateSymbolsAndDiagrams(): { symbolsJson: string; diagramsJson: string } {
  const symbols = DYR_SCHEMA_LIST.map((s) => {
    const isIbr = s.subCategory?.startsWith("ibr_");
    return {
      name: s.model,
      kind: "psse_dyr_model",
      ruleName: "dyr_record",
      namePath: `psse:${s.model}`,
      exports: exportsForSchema(s.category, s.subCategory),
      inherits: [],
      metadata: {
        label: s.title,
        category: isIbr ? "ibr" : s.category,
        subCategory: s.subCategory ?? s.category,
        headerKind: s.headerKind ?? "machine",
        domain: domainForCategory(s.category, s.subCategory),
        minCon: s.params.length,
        minIcon: s.icons?.length ?? 0,
        daeArchetype: s.daeArchetype,
      },
    };
  });

  const diagrams = DYR_SCHEMA_LIST.map((s) => {
    const ex = exportsForSchema(s.category, s.subCategory);
    const inPort = ex[0] ?? "In";
    const outPort = ex[1] ?? "Out";
    return {
      namePath: `psse:${s.model}`,
      aliases: [s.model],
      label: s.title,
      category: s.category,
      domain: domainForCategory(s.category, s.subCategory),
      width: 72,
      height: 44,
      ports: [
        { name: inPort, kind: "signal", side: "left", dx: -36, dy: 0 },
        { name: outPort, kind: "signal", side: "right", dx: 36, dy: 0 },
      ],
    };
  });

  return {
    symbolsJson: JSON.stringify(symbols, null, 2) + "\n",
    diagramsJson: JSON.stringify(diagrams, null, 2) + "\n",
  };
}

export function syncDyrSchemas(): void {
  const tableTs = generateAssemblyModelTable();
  const { symbolsJson, diagramsJson } = generateSymbolsAndDiagrams();

  const updatedTable = writeIfChanged(path.join(PSSE_DIR, "assembly", "model-table.gen.ts"), tableTs);
  const updatedSym = writeIfChanged(path.join(PSSE_DIR, "assets", "psse-std-lib", "src", "symbols.json"), symbolsJson);
  const updatedDiag = writeIfChanged(
    path.join(PSSE_DIR, "assets", "psse-std-lib", "src", "diagrams.json"),
    diagramsJson,
  );

  console.log(
    `[psse-sync] Synchronized ${DYR_SCHEMA_LIST.length} schemas (table=${updatedTable}, symbols=${updatedSym}, diagrams=${updatedDiag}).`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  syncDyrSchemas();
}
