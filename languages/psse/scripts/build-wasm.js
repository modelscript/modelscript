import { emitAssemblyScriptCodec, emitTypeScriptCodecBindings } from "@modelscript/dsl";
import fs from "node:fs";
import path from "node:path";
import {
  emitCleanroomCatalogJsonArtifacts,
  writeFormattedTsIfChanged,
} from "../../../scripts/build/build-cleanroom-stdlib.js";
import { runLanguageWasmBuild } from "../../../scripts/build/build-language-wasm.js";
import { psseSavSoaCodecDef } from "../src/parser/codec-defs.ts";

const psseDir = new URL("..", import.meta.url).pathname;

// 1. Build @modelscript/psse native DYR scanner WASM kernel
runLanguageWasmBuild({
  langName: "psse-dyr",
  dir: psseDir,
  entryFile: "assembly/dyr-kernel.ts",
  outWasmFile: "dist/dyr-kernel.wasm",
  binaryTsFile: "src/parser/dyr-wasm-binary.ts",
  base64ConstName: "DYR_KERNEL_WASM_BASE64",
  binaryGetterName: "getDyrKernelWasmBinary",
  description: "Pre-compiled WebAssembly binary payload for PSS/E Linear-Memory DYR Scanner Kernel.",
});

// 1b. Emit & compile declarative @modelscript/dsl Binary-to-SoA WASM codec for PSS/E .sav snapshots
fs.mkdirSync(path.join(psseDir, "as-gen"), { recursive: true });
fs.mkdirSync(path.join(psseDir, "src-gen"), { recursive: true });
fs.writeFileSync(
  path.join(psseDir, "as-gen", "psse-sav-codec.ts"),
  emitAssemblyScriptCodec(psseSavSoaCodecDef),
  "utf-8",
);
fs.writeFileSync(
  path.join(psseDir, "src-gen", "psse-sav-codec.ts"),
  emitTypeScriptCodecBindings(psseSavSoaCodecDef),
  "utf-8",
);

runLanguageWasmBuild({
  langName: "psse-sav-codec",
  dir: psseDir,
  entryFile: "as-gen/psse-sav-codec.ts",
  outWasmFile: "dist/psse-sav-codec.wasm",
  binaryTsFile: "src/parser/sav-codec-wasm-binary.ts",
  base64ConstName: "SAV_CODEC_WASM_BASE64",
  binaryGetterName: "getSavCodecWasmBinary",
  description: "Pre-compiled WebAssembly binary payload for PSS/E Linear-Memory SoA .sav Codec.",
});

// 2. Build @modelscript/psse-std-lib/dist from src/
const stdLibDir = path.join(psseDir, "assets", "psse-std-lib");
const stdLibSrc = path.join(stdLibDir, "src");
const stdLibDist = path.join(stdLibDir, "dist");
fs.mkdirSync(stdLibDist, { recursive: true });
for (const file of ["symbols.json", "diagrams.json"]) {
  const srcFile = path.join(stdLibSrc, file);
  if (fs.existsSync(srcFile)) {
    fs.copyFileSync(srcFile, path.join(stdLibDist, file));
  }
}

runLanguageWasmBuild({
  langName: "psse-std-lib",
  dir: stdLibDir,
  entryFile: "src/models.ts",
  outWasmFile: "dist/runtime.wasm",
});

// 3. Emit zero-I/O browser & Web Worker pre-bundled payload (symbols + cleanroom SVG icons + runtime.wasm)
const pkgJsonPath = path.join(stdLibDir, "package.json");
const symbolsPath = path.join(stdLibDist, "symbols.json");
const diagramsPath = path.join(stdLibDist, "diagrams.json");
const runtimeWasmPath = path.join(stdLibDist, "runtime.wasm");
const defaultPkgJsonText = JSON.stringify(
  {
    name: "@modelscript/psse-std-lib",
    version: "0.1.0",
    license: "AGPL-3.0-or-later",
    modelscript: {
      category: "library",
      language: "psse",
      symbols: "./dist/symbols.json",
      diagrams: "./dist/diagrams.json",
      runtime: { wasm: "./dist/runtime.wasm" },
    },
  },
  null,
  2,
);
if (fs.existsSync(symbolsPath) && fs.existsSync(diagramsPath) && fs.existsSync(runtimeWasmPath)) {
  const pkgJsonText = fs.existsSync(pkgJsonPath) ? fs.readFileSync(pkgJsonPath, "utf-8").trim() : defaultPkgJsonText;
  const wasmBase64 = fs.readFileSync(runtimeWasmPath).toString("base64");
  const outTsPath = path.join(psseDir, "src", "catalog", "psse-std-lib-data.ts");
  const { symbolsJsonName, diagramsJsonName } = await emitCleanroomCatalogJsonArtifacts({
    outTsPath,
    symbolsPath,
    diagramsPath,
  });
  const content = [
    "// SPDX-License-Identifier: AGPL-3.0-or-later",
    "// AUTO-GENERATED by languages/psse/scripts/build-wasm.js — do not edit manually.",
    "",
    'import type { DiagramComponentSpec, LibrarySymbolStub, ModelscriptLibraryManifest } from "@modelscript/runtime";',
    `import rawDiagrams from "./${diagramsJsonName}" with { type: "json" };`,
    `import rawSymbols from "./${symbolsJsonName}" with { type: "json" };`,
    "",
    `export const PSSE_STD_LIB_PKG_JSON = ${pkgJsonText} as {`,
    "  name: string;",
    "  version: string;",
    "  license: string;",
    "  modelscript: ModelscriptLibraryManifest;",
    "};",
    "",
    "export const PSSE_STD_LIB_SYMBOLS: LibrarySymbolStub[] = rawSymbols;",
    "",
    "export const PSSE_STD_LIB_DIAGRAMS: DiagramComponentSpec[] = rawDiagrams;",
    "",
    `export const PSSE_STD_LIB_WASM_BASE64 = "${wasmBase64}";`,
    "",
    "let cachedWasmBytes: Uint8Array | undefined;",
    "",
    "/**",
    " * Decodes the pre-bundled `@modelscript/psse-std-lib` `runtime.wasm` binary in Node.js, Browsers, or Web Workers.",
    " */",
    "export function getPsseStdLibWasmBytes(): Uint8Array {",
    "  if (cachedWasmBytes) return cachedWasmBytes;",
    '  if (typeof Buffer !== "undefined") {',
    '    const buf = Buffer.from(PSSE_STD_LIB_WASM_BASE64, "base64");',
    "    cachedWasmBytes = new Uint8Array(buf.buffer, buf.byteOffset, buf.byteLength);",
    "    return cachedWasmBytes;",
    "  }",
    "  const bin = atob(PSSE_STD_LIB_WASM_BASE64);",
    "  const out = new Uint8Array(bin.length);",
    "  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);",
    "  cachedWasmBytes = out;",
    "  return out;",
    "}",
    "",
  ].join("\n");
  await writeFormattedTsIfChanged(outTsPath, content);
}
