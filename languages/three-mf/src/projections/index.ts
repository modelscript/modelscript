/**
 * @modelscript/three-mf — Projections to ISO 10303-21 STEP AP242 (.step)
 * and OpenSCAD (.scad) polyhedron CSG.
 */

import type { ThreeMfDocument } from "../types.js";

/**
 * Projects a 3MF document into an ISO 10303-21 STEP AP242 faceted B-rep model.
 */
export function threeMfToStep(doc: ThreeMfDocument): string {
  const title = doc.metadata["Title"] ?? "ThreeMF_Surgical_Guide";
  const lines: string[] = [
    "ISO-10303-21;",
    "HEADER;",
    `FILE_DESCRIPTION(('3MF Medical Extension Surgical Guide','${title}'),'2;1');`,
    `FILE_NAME('${title}.step','2026-01-01T00:00:00',('ModelScript 3MF'),('ModelScript'),'','','');`,
    "FILE_SCHEMA(('AP242_MANAGED_MODEL_BASED_3D_ENGINEERING_MIM_LF'));",
    "ENDSEC;",
    "DATA;",
  ];

  let nextEntityId = 10;

  for (const obj of doc.objects) {
    const objName = obj.name ?? `Object_${obj.id}`;
    const matName = obj.surgicalGuide?.biocompatibleMaterial ?? obj.materialName ?? "Ti-6Al-4V";
    const prodId = nextEntityId++;
    lines.push(`#${prodId} = PRODUCT('${obj.id}','${objName}','Material: ${matName}',());`);

    if (obj.mesh) {
      const vertIds: number[] = [];
      for (let vIdx = 0; vIdx < obj.mesh.vertices.length; vIdx++) {
        const v = obj.mesh.vertices[vIdx]!;
        const cpId = nextEntityId++;
        const vpId = nextEntityId++;
        lines.push(`#${cpId} = CARTESIAN_POINT('V_${vIdx}',(${v.x},${v.y},${v.z}));`);
        lines.push(`#${vpId} = VERTEX_POINT('VP_${vIdx}',#${cpId});`);
        vertIds.push(vpId);
      }

      const faceIds: number[] = [];
      for (let tIdx = 0; tIdx < obj.mesh.triangles.length; tIdx++) {
        const t = obj.mesh.triangles[tIdx]!;
        const vp1 = vertIds[t.v1] ?? vertIds[0] ?? 1;
        const vp2 = vertIds[t.v2] ?? vertIds[0] ?? 1;
        const vp3 = vertIds[t.v3] ?? vertIds[0] ?? 1;
        const loopId = nextEntityId++;
        const boundId = nextEntityId++;
        const faceId = nextEntityId++;
        lines.push(`#${loopId} = POLY_LOOP('Loop_${tIdx}',(#${vp1},#${vp2},#${vp3}));`);
        lines.push(`#${boundId} = FACE_OUTER_BOUND('Bound_${tIdx}',#${loopId},.T.);`);
        lines.push(`#${faceId} = FACE_SURFACE('Tri_${tIdx}',(#${boundId}),.T.);`);
        faceIds.push(faceId);
      }

      const shellId = nextEntityId++;
      const faceList = faceIds.map((id) => `#${id}`).join(",");
      lines.push(`#${shellId} = CLOSED_SHELL('${objName}_Shell',(${faceList}));`);
      const brepId = nextEntityId++;
      lines.push(`#${brepId} = FACETED_BREP('${objName}',#${shellId});`);
    }
  }

  lines.push("ENDSEC;");
  lines.push("END-ISO-10303-21;");
  return lines.join("\n");
}

/**
 * Projects a 3MF document (meshes, osteotomy cutting slots, and drill guide sleeves)
 * into OpenSCAD (.scad) `polyhedron` and CSG code.
 */
export function threeMfToScad(doc: ThreeMfDocument): string {
  const lines: string[] = [
    "// Generated by @modelscript/three-mf — Patient-Specific Surgical Guide & Mesh Polyhedron",
    "$fn = 64;",
    "",
  ];

  for (const obj of doc.objects) {
    const safeName = (obj.name ?? `Object_${obj.id}`).replace(/[^a-zA-Z0-9_]/g, "_");
    const matName = obj.surgicalGuide?.biocompatibleMaterial ?? obj.materialName ?? "Ti-6Al-4V";
    lines.push(`// Object #${obj.id}: ${obj.name ?? obj.id} (Material: ${matName})`);
    lines.push(`module ThreeMF_${safeName}() {`);

    if (obj.mesh && obj.mesh.vertices.length > 0) {
      const pts = obj.mesh.vertices.map((v) => `[${v.x}, ${v.y}, ${v.z}]`).join(", ");
      const faces = obj.mesh.triangles.map((t) => `[${t.v1}, ${t.v2}, ${t.v3}]`).join(", ");
      lines.push(`  polyhedron(points = [${pts}], faces = [${faces}], convexity = 4);`);
    }

    if (obj.surgicalGuide) {
      for (const sleeve of obj.surgicalGuide.drillSleeves) {
        const [ex, ey, ez] = sleeve.entryPoint;
        const h = sleeve.lengthMm ?? 12.0;
        lines.push(`  // Drill Sleeve: ${sleeve.id} (ID=${sleeve.innerDiameterMm}mm, OD=${sleeve.outerDiameterMm}mm)`);
        lines.push(`  translate([${ex}, ${ey}, ${ez}])`);
        lines.push(
          `    difference() { cylinder(h = ${h}, d = ${sleeve.outerDiameterMm}, center = true); cylinder(h = ${h + 0.2}, d = ${sleeve.innerDiameterMm}, center = true); }`,
        );
      }
    }

    lines.push("}");
    lines.push(`ThreeMF_${safeName}();`);
    lines.push("");
  }

  return lines.join("\n");
}
